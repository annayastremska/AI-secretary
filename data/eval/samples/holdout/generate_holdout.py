def main():
    # Порожній бланк
    build_certificate(
        os.path.join(HERE, "довідка_лікування_шаблон.docx"), {})

    # Заповнені варіанти + еталони
    for num, variant in VARIANTS.items():
        docx_path = os.path.join(HERE, f"довідка_лікування_{num}.docx")
        build_certificate(docx_path, variant["printed"])

        expected = {
            "надруковано": {k: variant["printed"].get(k, "") for k in SLOT_KEYS},
            "правильні_відповіді": variant["normalized"],
        }
        json_path = os.path.join(HERE, f"довідка_лікування_{num}.expected.json")
        with open(json_path, "w", encoding="utf-8") as fh:
            json.dump(expected, fh, ensure_ascii=False, indent=2)
        print("OK", docx_path)

    print("OK", os.path.join(HERE, "довідка_лікування_шаблон.docx"))


if __name__ == "__main__":
    main()

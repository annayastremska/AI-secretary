def _p(doc, text, *, bold=False, italic=False, size=12, center=False, space_after=6):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    par.paragraph_format.space_after = Pt(space_after)
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    return par


def build_certificate(path, values):
    """Будує один docx. values — словник слотів; порожній рядок => слот-пропуск."""

    def slot(key):
        v = values.get(key, "")
        return v if v else BLANK

    doc = Document()
    section = doc.sections[0]
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(1.6)

    # Шапка закладу
    _p(doc, slot("заклад"), bold=True, center=True, size=13, space_after=0)
    _p(doc, "(повне найменування закладу охорони здоров'я, що видав документ)",
       italic=True, center=True, size=8, space_after=14)

    # Назва документа
    _p(doc, "Д О В І Д К А", bold=True, center=True, size=16, space_after=2)
    _p(doc, "про перебування на лікуванні", center=True, size=12, space_after=10)

    # Реєстраційний рядок
    _p(doc,
       "Реєстраційний № {num}        Дата оформлення: {dat}".format(
           num=values.get("номер_довідки") or "________",
           dat=values.get("дата_видачі") or "________________"),
       center=True, size=12, space_after=14)

    # Таблиця «поле : значення»
    table = doc.add_table(rows=len(GRID_ROWS), cols=2)
    table.style = "Table Grid"
    for i, (label, key) in enumerate(GRID_ROWS):
        left, right = table.rows[i].cells
        lp = left.paragraphs[0]
        lr = lp.add_run(label)
        lr.font.size = Pt(10)
        lr.font.name = "Times New Roman"
        rp = right.paragraphs[0]
        rr = rp.add_run(slot(key))
        rr.font.size = Pt(12)
        rr.font.name = "Times New Roman"
    table.columns[0].width = Cm(7.5)
    table.columns[1].width = Cm(9.5)

    doc.add_paragraph()
    _p(doc,
       "Довідку оформлено для пред'явлення за місцем проходження військової "
       "служби. Записи звірено з журналом обліку стаціонарних хворих.",
       size=11, space_after=16)

    # Блок підписанта
    _p(doc, "Відповідальна особа закладу:", size=11, space_after=2)
    _p(doc, slot("підписант"), size=12, space_after=0)
    _p(doc, "(посада, військове звання, ініціали та прізвище)     М.П.",
       italic=True, size=8)

    doc.save(path)



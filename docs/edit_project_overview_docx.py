def find(prefix, start=0):
    for i in range(start, len(doc.paragraphs)):
        if doc.paragraphs[i].text.strip().startswith(prefix):
            return doc.paragraphs[i]
    raise SystemExit(f"НЕ ЗНАЙДЕНО: {prefix!r}")


BULLET_SRC = None
NUMBER_SRC = None


def _template(kind):
    """Зразок абзацу потрібного виду з САМОГО документа.

    Word, зберігаючи файл, прибрав стилі «List Bullet»/«List Number» -- списки
    в ньому зроблені нумерацією в стилі «normal». Тому новий пункт робиться
    копією наявного: інакше маркер і відступи не збігатимуться.
    """
    global BULLET_SRC, NUMBER_SRC
    if BULLET_SRC is None:
        BULLET_SRC = find("docx — текст беремо напряму")
        NUMBER_SRC = find("Командир питає")
    return BULLET_SRC if kind == "bullet" else NUMBER_SRC


def _clone(kind):
    src = _template(kind)
    new = copy.deepcopy(src._p)
    for r in new.findall(
            "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}r"):
        new.remove(r)
    return new


def after(anchor, text, style=None, bold_prefix=None, example=False):
    """Вставити абзац ПІСЛЯ anchor; style: None | 'List Bullet' | 'List Number'."""
    from docx.text.paragraph import Paragraph
    if style == "List Bullet":
        el = _clone("bullet")
    elif style == "List Number":
        el = _clone("number")
    else:
        el = copy.deepcopy(find("Дані при цьому в частині Є")._p)
        for r in el.findall(
                "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}r"):
            el.remove(r)
    anchor._p.addnext(el)
    p = Paragraph(el, anchor._parent)
    if example:
        p.paragraph_format.left_indent = Cm(0.6)
        p.paragraph_format.space_before = Pt(2)
        run = p.add_run("Наш квиток: ")
        run.bold = True
        run.italic = True
        run.font.color.rgb = EXAMPLE
        run.font.size = Pt(10)
        run = p.add_run(text)
        run.italic = True
        run.font.color.rgb = EXAMPLE
        run.font.size = Pt(10)
    else:
        if bold_prefix:
            p.add_run(bold_prefix).bold = True
        p.add_run(text)
    return p


def retext(anchor, text, bold_prefix=None):
    """Замінити текст абзацу, лишивши його вид і відступи."""
    for run in list(anchor.runs):
        run._element.getparent().remove(run._element)
    if bold_prefix:
        anchor.add_run(bold_prefix).bold = True
    anchor.add_run(text)
    return anchor


def heading_after(anchor, text, level=2):
    from docx.text.paragraph import Paragraph
    src = find("3.2. Чи вже бачили цей файл") if level == 2 else         find("Друга частина ланцюга")
    el = copy.deepcopy(src._p)
    for r in el.findall(
            "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}r"):
        el.remove(r)
    anchor._p.addnext(el)
    p = Paragraph(el, anchor._parent)
    p.add_run(text)
    return p



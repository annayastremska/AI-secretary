import os

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor, Cm

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "AI-секретар_опис_проєкту.docx")

ACCENT = RGBColor(0x2E, 0x4A, 0x6B)
MUTED = RGBColor(0x55, 0x5F, 0x6B)
EXAMPLE = RGBColor(0x1F, 0x5C, 0x3D)


def setup(doc):
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)
    style.paragraph_format.space_after = Pt(5)
    style.paragraph_format.line_spacing = 1.1
    for name, size, color, before in (("Heading 1", 15, ACCENT, 14),
                                      ("Heading 2", 12, ACCENT, 10),
                                      ("Heading 3", 10.5, MUTED, 8)):
        st = doc.styles[name]
        st.font.name = "Calibri"
        st.font.size = Pt(size)
        st.font.color.rgb = color
        st.font.bold = True
        st.paragraph_format.space_before = Pt(before)
        st.paragraph_format.space_after = Pt(3)
        st.paragraph_format.keep_with_next = True
    for section in doc.sections:
        section.top_margin = section.bottom_margin = Cm(1.7)
        section.left_margin = section.right_margin = Cm(1.9)


def para(doc, text):
    return doc.add_paragraph(text)


def bullets(doc, items):
    for item in items:
        if isinstance(item, tuple):
            p = doc.add_paragraph(style="List Bullet")
            p.add_run(item[0]).bold = True
            p.add_run(item[1])
        else:
            doc.add_paragraph(item, style="List Bullet")


def numbered(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Number")


def example(doc, text):
    """Рядок «наш квиток» після пункту, який із ним щось робить."""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.6)
    p.paragraph_format.space_before = Pt(2)
    run = p.add_run("Наш квиток: ")
    run.bold = True
    run.italic = True
    run.font.color.rgb = EXAMPLE
    run.font.size = Pt(10)
    run = p.add_run(text)
    run.italic = True
    run.font.color.rgb = EXAMPLE
    run.font.size = Pt(10)


def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = h
        for p in cell.paragraphs:
            for run in p.runs:
                run.bold = True
                run.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
            for p in cells[i].paragraphs:
                p.paragraph_format.space_after = Pt(1)
                for run in p.runs:
                    run.font.size = Pt(9.5)
    doc.add_paragraph()



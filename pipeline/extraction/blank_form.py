# -*- coding: utf-8 -*-
"""Друкований текст порожнього бланка як опора для двох різних задач.

1. Перевірка «кандидат — це друкований текст самого бланка, а не значення»
   (`is_printed_form_text`) — known-weak-spots.md 5.9 і 5.8.
2. ВІДНОВЛЕННЯ МЕЖ ПОЛІВ у злитому блоці OCR (`resegment_by_blank`) —
   known-weak-spots.md 2.11a/A3. Той самий перелік друкованих рядків, та сама
   єдина залежність (`blank_template:` у схемі), дві задачі.

## Чому шаблон, а не перелік фраз у схемі

Розглядалось два варіанти (docs/known-weak-spots.md розд. 7, Агент 4):

1. **оголошувати друковані фрази в схемі** -- слабше, зате без нових
   залежностей;
2. **звіряти кандидата з текстом ПОРОЖНЬОГО бланка** -- сильніше й
   універсальніше, але вимагає, щоб шаблон лежав поруч зі схемою.

Обрано (2), і причина не в силі, а в тому, ХТО веде перелік. Перелік фраз у
схемі веде людина: щойно бланк змінить формулювання -- перелік мовчки
застаріє, і повернеться той самий клас помилки, тільки пізніше й тихіше.
Порожній бланк -- це артефакт, який у частині й так існує в одному
екземплярі на форму, і він оновлюється разом із формою. Перелік фраз стає
похідним від нього, а не окремою сутністю, яку треба синхронізувати.

Ціна вибору чесна: схема без `blank_template:` не отримує перевірки взагалі
(див. `printed_lines` -> порожній frozenset). Це навмисно -- новий бланк без
оголошеного шаблону НЕ має почати мовчки відхиляти значення.

## Межа перевірки

Відхиляється лише кандидат, який ЦІЛКОМ складається з рядків бланка. Якщо
друкований рядок приклеївся до справжнього значення -- значення лишається:
там є текст, вписаний людиною, і втратити його гірше, ніж віддати з
приклеєним лейблом. Цей клас ловлять інші перевірки
(`_value_lines_after_label_note`, `printed_label_in_value`).
"""
import os
import re

from pipeline.classification.classify import normalize_ws

#: Ключ схеми: шлях до порожнього бланка ЦІЄЇ форми, від кореня репозиторію.
BLANK_TEMPLATE_KEY = "blank_template"

_PROJECT_ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Гліфи, що позначають той самий знак у різних джерелах. Той самий друкований
# рядок приходить із docx із фігурним ’, а з OCR -- із прямим '. Якби
# порівняння залежало від гліфа, перевірка працювала б на docx і мовчки НЕ
# працювала на фото -- тобто рівно там, де помилок більше.
_GLYPH_FOLD = str.maketrans({
    "’": "'", "‘": "'", "`": "'", "´": "'", "ʼ": "'",
    "“": '"', "”": '"', "„": '"', "‟": '"', "«": '"', "»": '"',
    "–": "-", "—": "-", "‑": "-",
})

_cache = {}


def _fold(text: str) -> str:
    """Порівнювана форма рядка: єдині гліфи, згорнуті пробіли, нижній
    регістр."""
    return normalize_ws(str(text).translate(_GLYPH_FOLD)).strip().lower()


def _has_letter(text: str) -> bool:
    """Чи є в рядку хоч одна літера.

    Потрібно, бо в бланку окремим блоком стоїть номер сторінки "2", а "2" --
    цілком законне значення (TRIP-001: 'Термін відрядження "2" днів'). Рядки
    без літер до переліку друкованого НЕ беруться, інакше перевірка з'їдала б
    короткі числові значення.
    """
    return any(ch.isalpha() for ch in text)


def blank_template_path(schema: dict) -> str:
    """Абсолютний шлях до порожнього бланка, оголошеного схемою."""
    declared = schema.get(BLANK_TEMPLATE_KEY)
    if not declared:
        return ""
    return os.path.normpath(os.path.join(_PROJECT_ROOT, declared))


def printed_lines(schema: dict) -> frozenset:
    """Множина друкованих рядків бланка у порівнюваній формі.

    Порожній frozenset, якщо схема шаблону не оголосила -- перевірка тоді
    інертна (див. докстрінг модуля).
    """
    path = blank_template_path(schema)
    if not path:
        return frozenset()
    cached = _cache.get(path)
    if cached is not None:
        return cached
    lines = _read_lines(path)
    result = frozenset(f for f in (_fold(ln) for ln in lines) if f and _has_letter(f))
    _cache[path] = result
    return result


_text_cache = {}


def blank_template_text(schema: dict) -> str:
    """Суцільний текст порожнього бланка (рядки через `\\n`), або "" якщо
    схема шаблону не оголосила.

    Потрібен валідатору схем: `empty_pattern:` -- це друкований СКЕЛЕТ
    порожнього слота, тобто він за визначенням існує в порожньому бланку.
    Патерн, який у ньому не збігається, написаний неправильно й мовчки не
    діяв би ніколи (та сама логіка, що для перевірки blank_template вище).
    Читається тим самим `_read_lines`, що й решта модуля -- інакше валідатор
    перевіряв би текст, якого рушій не бачить."""
    path = blank_template_path(schema)
    if not path:
        return ""
    cached = _text_cache.get(path)
    if cached is None:
        cached = "\n".join(_read_lines(path))
        _text_cache[path] = cached
    return cached


_order_cache = {}


def printed_order(schema: dict) -> dict:
    """{друкований рядок: його номер у бланку}. Порожній словник, якщо схема
    шаблону не оголосила.

    Навіщо ПОРЯДОК, а не лише множина: OCR читає бланк по областях зображення,
    і два друковані рядки, що на папері стоять один під одним, можуть прийти
    в зворотному порядку. Заміряно (LEAVE-003/004/007.png): між значенням
    `місце` і другою половиною його лейбла Surya вставила рядок "терміном на",
    який на бланку стоїть ПІСЛЯ лейбла, а не перед ним. Знаючи номер рядка в
    бланку, такий випадок можна відрізнити від законного сусідства -- див.
    `find_block_before_label`.

    Повторювані рядки бланка ("(військове звання, прізвище та ініціали"
    друкується двічі) беруть ПЕРШИЙ номер: далі він використовується лише для
    порівняння "раніше/пізніше за лейбл", і перше входження дає найобережнішу
    відповідь (менше приводів визнати блок переставленим).
    """
    path = blank_template_path(schema)
    if not path:
        return {}
    cached = _order_cache.get(path)
    if cached is not None:
        return cached
    order = {}
    for index, raw in enumerate(_read_lines(path)):
        folded = _fold(raw)
        if folded and _has_letter(folded) and folded not in order:
            order[folded] = index
    _order_cache[path] = order
    return order


def label_order_index(label_substring: str, order: dict):
    """Номер рядка бланка, у якому надрукований цей лейбл. None, якщо лейбл у
    бланку не знайдено (схема оголосила фразу, якої в шаблоні немає, --
    тоді жодних висновків про порядок ми не робимо)."""
    if not order or not label_substring:
        return None
    needle = _fold(label_substring)
    if not needle:
        return None
    return min((n for line, n in order.items() if needle in line), default=None)


def printed_after_label(candidate: str, label_index, order: dict) -> bool:
    """True, якщо кандидат -- ЦІЛКОМ друкований текст бланка, і на бланку він
    стоїть ПІСЛЯ лейбла.

    Такий блок не може бути значенням цього поля за побудовою бланка: він
    надрукований нижче лейбла. Опинившись у потоці OCR ВИЩЕ лейбла, він
    свідчить лише про порядок читання, і його можна пропустити.

    Друкований рядок, що стоїть на бланку ПЕРЕД лейблом, НЕ пропускається --
    і це головне обмеження цієї перевірки: саме він законно опиняється
    впритул до лейбла, коли поле на бланку порожнє (перша половина
    розрізаного лейбла `місце`). Пропустивши його, ми віддали б значення
    ПОПЕРЕДНЬОГО поля як своє -- рівно та тиха помилка, проти якої стоїть
    правило "відмова краща за вигадку".
    """
    if label_index is None or not order or candidate is None:
        return False
    numbers = []
    for line in str(candidate).split("\n"):
        folded = _fold(line)
        if not folded:
            continue
        if folded not in order:
            return False
        numbers.append(order[folded])
    return bool(numbers) and min(numbers) > label_index


def _read_lines(path: str) -> list:
    """Рядки порожнього бланка. Читається ТИМ САМИМ інжестом, що й документи
    (`extract_docx_blocks`), а не окремим читачем: інакше шаблон і документ
    розбивались би на рядки по-різному, і перевірка мовчки не збігалася б
    саме на верстці з таблицями, заради якої вона й потрібна."""
    if not os.path.exists(path):
        return []
    from pipeline.ingestion.ingest import extract_docx_blocks
    # Порядок значень саме такий: (суцільний текст, список блоків).
    try:
        _text, blocks = extract_docx_blocks(path)
    except Exception:
        # НЕ-DOCX (або побитий) шлях у `blank_template:` -- це помилка СХЕМИ, і
        # сказати про неї має валідатор, а не необроблений PackageNotFoundError
        # посеред батчу (рев'ю 22.08.2026, A-14). Раніше виняток проходив
        # `validate_schema` і `build_resources` наскрізь до `run_pipeline`:
        # одна одруківка в шляху -> НУЛЬ оброблених документів і traceback без
        # причини, тобто ламався сам інваріант «невалідна схема виключається,
        # решта обробляється» (run.py:211-218).
        # Порожній список тут означає для решти модуля рівно те саме, що
        # відсутній файл, -- «друкованих рядків немає», а валідатор із цього
        # робить error і виключає схему.
        return []
    out = []
    for block in blocks:
        text = block if isinstance(block, str) else (block or {}).get("text", "")
        out.extend(str(text).split("\n"))
    return out


# --- Відновлення меж полів у злитому блоці OCR ---------------------------
#
# ЩО САМЕ ЗЛАМАНО (known-weak-spots.md 2.11a, A3 у docs/known-weak-spots.md розд. 7).
# Surya групує не абзаци, а області зображення. Виміряний дамп LEAVE-001.png:
# ВЕСЬ корпус бланка (десять полів) приходить ОДНИМ блоком висотою 908 px, а
# всередині нього значення й друковані лейбли склеєні БЕЗ ЖОДНОГО роздільника:
#
#   "звільнена(військове звання, прізвище, ім'я та по батькові)щорічна
#    основна відпустка за 2026 рік(вид відпустки та найменування населеного
#    пункту,\nм. Житомирдо якого звільнено військовослужбовця)терміном
#    натринадцять(кількість днів прописом)з "10" травня 2026 р. ..."
#
# Наслідки, які з цього однозначно випливають і всі шість заміряні:
#   * `місце` 0/6 НАЗАВЖДИ: лейбл "до якого звільнено військовослужбовця"
#     склеєний із попереднім значенням у слово "Житомирдо", тому
#     `phrase_in_text` (межа слова на початку) його не бачить -- `no_label`;
#   * `днів` 2/6: схемний regex вимагає "терміном\s+на\s+", а в документі
#     стоїть "терміном натринадцять";
#   * `військова_частина`, `підстава`, `ПІБ`, `звання`: лейбл усередині
#     мега-блоку, де ні порядок списку, ні bbox не описують позицію ОКРЕМОГО
#     рядка -- див. _is_mega_block в extract.py.
# Тобто причина одна, а полів шість. Лікується причина.
#
# ЧИМ ЛІКУЄМО. Ми знаємо ТОЧНИЙ друкований текст цього бланка -- він уже
# оголошений схемою (`blank_template:`) і вже читається цим модулем. Друковані
# рядки бланка -- це і є межі полів: на папері між ними стоїть рукописне
# значення. Тому злитий блок ріжеться по знайдених у ньому друкованих рядках,
# і виходить рівно та сама послідовність "лейбл / значення / лейбл", яку
# docx-шлях отримує з абзаців безкоштовно.
#
# Це і є сенс правки: НЕ нова евристика для кожного поля, а зведення
# фото-шляху до вже працюючого docx-шляху. Нижче за течією не змінюється
# нічого -- find_block_before_label, геометрія, `strip_prefix`, перевірки
# порожнього бланка працюють, як працювали.
#
# ЧОМУ ЦЕ НЕ ЗАЧІПАЄ docx/PDF. Різання застосовується ЛИШЕ до блоку, де
# знайдений друкований рядок НЕ збігається з межею рядка блоку (тобто справді
# склеєний із сусіднім текстом). У docx кожен абзац -- або цілий друкований
# рядок, або значення цілком, тому збіг завжди по межі й блок повертається
# незміненим ТИМ САМИМ об'єктом. Перевірено регресією: 176/176 і 140/140.

#: Мінімальна довжина друкованого рядка, щоб він працював різаком. Коротка
#: фраза ("М.П.", "Разом з") надто ймовірно трапиться всередині значення, і
#: ціна помилкового розрізу -- розірване навпіл значення -- вища за користь.
#: 8 символів лишає всі рядки, від яких залежать поля бланка (найкоротший --
#: "звільнений", 10; "терміном на", 11).
MIN_CUTTER_CHARS = 8

_cutter_cache = {}


#: Слово, коротше за це, лишається в різаку літеральним: у короткому слові
#: закінчення -- надто велика частка, і послаблення перетворило б його на
#: майже будь-що ("на", "у", "з").
MIN_INFLECTED_WORD = 6
#: Скільки кінцевих символів слова вважаються закінченням. 2 покриває всі
#: заміряні розходження роду в цих бланках ("звільнений"/"звільнена",
#: "зобов'язаний"/"зобов'язана", "відрядженому"/"відрядженій") і не дає слову
#: змінити довжину більш ніж на два символи.
INFLECTION_TAIL = 2


def _is_word(token: str) -> bool:
    """Токен -- ЧИСТЕ слово (літери й апостроф), без розділових знаків і цифр.

    Перевірка обов'язкова перед послабленням закінчення: у бланку розділовий
    знак прилипає до слова ("пункту," і "пункту)" -- це кінець лейбла), і
    послаблення з'їдало б саме його. Заміряний наслідок: кома лишалась у
    значенні (`місце` = ",\\nм. Житомир"), а дужка -- у даті повернення.
    """
    return bool(token) and all(ch.isalpha() or ch == "'" for ch in token)


def _cutter_pattern(line: str):
    """Регекс, що знаходить друкований рядок у злитому OCR-тексті.

    Дві послаблення проти літерального пошуку, обидва -- на заміряних збоях:

    * пробіли між словами -- `\\s*`, а не `\\s+`: саме ВІДСУТНІСТЬ пробілу і є
      те, що ламається ("терміном натринадцять", "Житомирдо"). Пробіл
      усередині самого друкованого рядка OCR теж може загубити, тому нуль
      пробілів допускається всюди, а не лише на межах;
    * закінчення довгих слів -- вільні: бланк друкує чоловічий рід, а
      документ несе рід військовослужбовця ("зобов'язаний прибути до місця
      служби у" на бланку проти "зобов'язана прибути до місця служби у" в
      LEAVE-001). Той самий інваріант уже несе `prefix_match_length` в
      extract.py для `strip_prefix`; тут він потрібен з тієї самої причини й
      без залежності від морфології (pymorphy3 на цій машині недоступний).
    """
    words = [w for w in _fold(line).split(" ") if w]
    if not words:
        return None
    tokens = []
    for word in words:
        if len(word) >= MIN_INFLECTED_WORD and _is_word(word):
            tokens.append(re.escape(word[:-INFLECTION_TAIL])
                          + r"\w{0,%d}" % INFLECTION_TAIL)
        else:
            tokens.append(re.escape(word))
    return re.compile(r"\s*".join(tokens))


def printed_cutters(schema: dict) -> tuple:
    """Різаки бланка: (скомпільований патерн, НОМЕР рядка в бланку), ВІД
    ДОВШОГО ДО КОРОТШОГО.

    Довжина визначає порядок перебору: довший збіг має вигравати, інакше
    різак відрізав би шматок довшого лейбла й лишав хвіст у значенні.

    Номер рядка їде РАЗОМ із патерном, а не шукається потім за текстом
    шматка, і це принципово: різак терпить іншу словоформу ("звільнена"
    замість "звільнений"), тому в переліку друкованих рядків такого шматка
    просто немає -- пошук за текстом віддав би None саме там, де номер
    найпотрібніший (див. `_reorder_printed`).
    """
    path = blank_template_path(schema)
    if not path:
        return ()
    cached = _cutter_cache.get(path)
    if cached is not None:
        return cached
    seen, out = set(), []
    for index, raw in enumerate(_read_lines(path)):
        folded = _fold(raw)
        if len(folded) < MIN_CUTTER_CHARS or not _has_letter(folded) or folded in seen:
            continue
        seen.add(folded)
        pattern = _cutter_pattern(raw)
        if pattern is not None:
            out.append((len(folded), pattern, index))
    out.sort(key=lambda t: -t[0])
    result = _cutter_cache[path] = tuple((p, n) for _len, p, n in out)
    return result


#: Скільки різаків мусять зустрітись у документі ЧАСТІШЕ, ніж у самому
#: бланку, щоб вважати, що друкований скелет бланка стоїть у документі
#: ДВІЧІ. Не «на око»: заміряно на всіх docx/pdf обох корпусів (34 файли,
#: включно з порожніми бланками й чужою редакцією) -- надлишок РІВНО 0 на
#: кожному; штучний документ «заповнений + порожній примірник полів» дає
#: 25 з 27. Тобто між нормою і другим примірником зазор у весь бланк, і
#: поріг 2 (а не 1) стоїть лише проти одного випадкового повтору рядка в
#: OCR -- місця для помилки він не забирає.
MIN_REPEATED_CUTTERS = 2


def printed_skeleton_repeats(text, schema) -> int:
    """Скільки різаків бланка стоять у тексті ЧАСТІШЕ, ніж у самому бланку.

    Питання, на яке це відповідає: «чи друкований скелет цього бланка
    зустрічається в документі більше одного разу» -- двосторонній аркуш,
    другий незаповнений примірник полів, дві сторінки в одному файлі.

    Порівняння саме з бланком, а не з одиницею: сам бланк деякі рядки
    друкує двічі (заміряно: 5 різаків із 27 у відпускному квитку, 8 із 27 у
    посвідченні), тож правило «рядок повторився -> примірників два» назвало б
    другим примірником КОЖЕН документ. Надлишок ПОНАД бланк -- це вже про
    документ, а не про верстку форми.

    Навіщо: `empty_pattern` (доказ порожнього слота) шукається по ВСЬОМУ
    тексту, тож при двох примірниках полів скелет порожнечі з одного
    примірника «доводить» порожнечу поля, значення якого стоїть в іншому
    (рев'ю 22.08.2026, C-06).
    """
    cutters = printed_cutters(schema)
    if not cutters:
        return 0
    haystack = _fold_inplace(text or "")
    baseline = _fold_inplace(blank_template_text(schema))
    return sum(1 for pattern, _n in cutters
               if len(pattern.findall(haystack)) > len(pattern.findall(baseline)))


def blank_line_coverage(text, schema):
    """(скільки друкованих рядків бланка знайдено в тексті, скільки їх усього).

    (0, 0) означає «сигналу немає»: схема не оголосила `blank_template:`, тобто
    порівнювати ні з чим. Це НЕ те саме, що (0, N) -- «бланк оголошений, і в
    документі не знайдено жодного його рядка».

    Міра стоїть на ТИХ САМИХ різаках (`printed_cutters`), якими ріжуться межі
    полів, і це головне рішення тут. Своя, окрема міра «схожості на бланк»
    розійшлася б із різаком: різак терпить відсутній пробіл і зміну закінчення,
    і будь-яка інша міра або рахувала б знайденим те, чого різак не бачить, або
    навпаки. Тоді «форма впізнана» і «межі полів відновлено» стали б двома
    різними твердженнями про одне й те саме, і при розходженні ніхто не сказав
    би, яке з них право.

    Знаменник -- саме різаки (рядки від MIN_CUTTER_CHARS), не всі рядки бланка:
    коротка фраза трапляється в тексті випадково, тож брати її в знаменник
    означало б міряти шум.
    """
    cutters = printed_cutters(schema)
    if not cutters:
        return 0, 0
    haystack = _fold_inplace(text or "")
    found = sum(1 for pattern, _n in cutters if pattern.search(haystack))
    return found, len(cutters)


def _accepted_spans(text: str, cutters) -> list:
    """Непересічні входження друкованих рядків у `text`: (початок, кінець,
    номер рядка в бланку), за позицією.

    Довший різак має пріоритет над коротшим на тому самому місці: cutters уже
    відсортовані за довжиною, тож перший, хто зайняв ділянку, її й тримає.
    """
    taken = []
    for pattern, index in cutters:
        for m in pattern.finditer(text):
            s, e = m.span()
            if s == e:
                continue
            if any(s < te and ts < e for ts, te, _n in taken):
                continue
            taken.append((s, e, index))
    taken.sort()
    return taken


def _reorder_printed(pieces):
    """Міняє місцями СУСІДНІ друковані шматки, що стоять у зворотному до
    бланка порядку. `pieces` -- [(текст, номер_у_бланку | None)].

    Навіщо. OCR читає бланк по областях, і два друковані рядки, що на папері
    стоять один під одним, приходять переставленими. Заміряно на 8 з 16 фото:

        'м. Рівне' / 'терміном на' / 'до якого звільнено військовослужбовця)'
        / 'десять' / '(кількість днів прописом)'

    -- у бланку "до якого..." стоїть ПЕРЕД "терміном на". Через це схемний
    патерн `терміном\\s+на\\s+(пропис)\\s*\\(кількість днів` не збігався
    (`днів` = None), а лейбл `місце` мав перед собою "терміном на" замість
    значення. Після обміну виходить рівно розкладка бланка, і обидва поля
    читаються без жодного окремого правила під них.

    Чому міняються ТІЛЬКИ сусідні ДРУКОВАНІ пари: обмін двох сусідніх
    друкованих рядків не може зсунути ЖОДНЕ значення -- між ними нічого
    немає. Сортувати весь список за номерами бланка не можна: значення
    номера не мають, і будь-яке правило "куди їх" було б здогадкою.

    Рівність номерів обміну не дає: рядок, надрукований у бланку двічі
    ("(військове звання, прізвище та ініціали"), несе номер ПЕРШОГО
    входження, тобто про взаємний порядок двох його копій ми нічого не знаємо.
    """
    items = list(pieces)
    for _ in range(len(items)):
        swapped = False
        for k in range(len(items) - 1):
            left, right = items[k], items[k + 1]
            if left[1] is not None and right[1] is not None and left[1] > right[1]:
                items[k], items[k + 1] = right, left
                swapped = True
        if not swapped:
            break
    return items


def _aligned_with_line_break(text: str, start: int, end: int) -> bool:
    """Чи стоїть знайдений друкований рядок ОКРЕМИМ рядком блоку.

    Якщо так -- межа поля вже є, різати нічого. Саме ця перевірка й лишає
    docx-шлях недоторканим.
    """
    before = text[:start].rstrip(" \t")
    after = text[end:].lstrip(" \t")
    return (not before or before.endswith("\n")) and (not after or after.startswith("\n"))


def resegment_text(text: str, cutters) -> list:
    """Список шматків тексту в порядку читання: [значення, лейбл, значення...].

    Порожній список -- «різати нічого» (жодного склеєного друкованого рядка).
    Це не те саме, що список з одного елемента: викликач мусить розрізняти
    «блок лишається як був» і «блок звівся до одного шматка».
    """
    if not text or not cutters:
        return []
    folded = _fold_inplace(text)
    if len(folded) != len(text):
        # Позиції в folded і в text розійшлись (рідкісний Unicode, де .lower()
        # змінює довжину). Різати за такими індексами -- це різати не там,
        # тому чесно не ріжемо взагалі.
        return []
    spans = _accepted_spans(folded, cutters)
    if not spans or all(_aligned_with_line_break(text, s, e) for s, e, _n in spans):
        return []
    pieces, cursor = [], 0
    for s, e, index in spans:
        pieces.append((_trim_orphan_parens(text[cursor:s]), None))
        pieces.append((text[s:e].strip(), index))
        cursor = e
    pieces.append((_trim_orphan_parens(text[cursor:]), None))
    pieces = [(p.strip(), n) for p, n in pieces if p.strip()]
    return [p for p, _n in _reorder_printed(pieces)]


def _trim_orphan_parens(piece: str) -> str:
    """Знімає з КРАЇВ значення дужку, що лишилась без пари.

    Лейбл `місце` надрукований дужкою НАВКОЛО значення: "(вид відпустки та
    найменування населеного пункту," ... "до якого звільнено
    військовослужбовця)". Відрізавши обидві половини як друкований текст, ми
    лишаємо значення всередині відкритої дужки, і OCR, який продублював
    закриваючу, віддає "м. Полтава)" замість "м. Полтава" (заміряно на
    LEAVE-005/009/010.png).

    Знімається ЛИШЕ незбалансована дужка й ЛИШЕ з країв: значення з власними
    парними дужками ("(перервана, відкликаний з відпустки)", "щорічна
    додаткова відпустка (за особливий характер служби)") лишається як є.
    """
    text = piece.strip()
    while text:
        if text[-1] == ")" and text.count(")") > text.count("("):
            text = text[:-1].rstrip()
        elif text[0] == "(" and text.count("(") > text.count(")"):
            text = text[1:].lstrip()
        elif text[0] == ")" and text.count(")") > text.count("("):
            text = text[1:].lstrip()
        else:
            break
    return text


def _fold_inplace(text: str) -> str:
    """Форма для ПОШУКУ, що зберігає позиції символів: гліфи зводяться
    один-до-одного, регістр знижується, пробіли НЕ згортаються.

    Згортання пробілів (як у `_fold`) зсунуло б індекси, і різати вихідний
    текст за знайденими позиціями стало б неможливо. Саме тому шаблон різака
    несе `\\s*` замість того, щоб покладатись на нормалізацію.
    """
    return str(text).translate(_GLYPH_FOLD).lower()


def resegment_by_blank(blocks, schema):
    """Блоки OCR, у яких злиті з даними друковані рядки бланка розрізані на
    окремі блоки. Повертає (нові_блоки, скільки_блоків_змінено).

    Шматок стає ОКРЕМИМ блоком, а не рядком усередині старого, і це головне
    рішення тут: увесь двигун екстракції визначає «значення перед лейблом» як
    ПОПЕРЕДНІЙ БЛОК (`find_block_before_label`), і саме так це працює на docx.
    Зробити шматки рядками одного блоку означало б лишити «значенням» усі
    рядки до лейбла, тобто половину бланка.

    `bbox` у нових блоків -- None НАВМИСНО. Геометрія злитого блоку описує
    область із десяти полів і не описує жодне з них; успадкувати її означало б
    дати `_is_mega_block` і `_geometric_candidate` завідомо неправдиву
    підставу. None вимикає обидва механізми для цих блоків і лишає лінійний
    порядок -- рівно те, на чому docx дає 176/176.

    `page` зберігається: він відповідає за те, щоб «попередній блок» не
    переліз на іншу сторінку.
    """
    cutters = printed_cutters(schema)
    if not cutters or not blocks:
        return blocks, 0
    out, changed = [], 0
    for block in blocks:
        text = block if isinstance(block, str) else (block or {}).get("text", "")
        pieces = resegment_text(text, cutters)
        if not pieces:
            out.append(block)
            continue
        changed += 1
        page = block.get("page") if isinstance(block, dict) else None
        for piece in pieces:
            out.append({"text": piece, "bbox": None, "page": page})
    return out, changed


def is_printed_form_text(candidate, printed) -> bool:
    """True, якщо КОЖЕН рядок кандидата -- друкований рядок бланка.

    "Кожен", а не "хоч один": змішаний кандидат (друкований рядок + вписане
    людиною значення) значенням лишається -- див. межу перевірки в докстрінгу
    модуля.
    """
    if not printed or candidate is None:
        return False
    folded = [f for f in (_fold(ln) for ln in str(candidate).split("\n")) if f]
    if not folded:
        return False
    return all(line in printed for line in folded)

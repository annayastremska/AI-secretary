# Блок, чия висота НЕ ПОЯСНЮЄТЬСЯ кількістю рядків, які ми з нього бачимо,
# найпевніше містить кілька логічних рядків/полів, злитих в один bbox без
# внутрішніх меж, а не одне значення. bbox такого блоку не описує позицію
# ЖОДНОГО окремого рядка всередині нього -- ні для геометричного
# вирівнювання, ні для "рядки в тому самому блоці до лейбла", ні для
# "попередній блок за списком": усі три мовчки візьмуть щось під/над/перед
# УСІМ блоком, а не рядком, де насправді стоїть лейбл.
#
# Міра -- ВИСОТА НА ОДИН РЯДОК блоку проти типової висоти рядка в документі,
# а НЕ повна висота блоку проти медіанної висоти БЛОКУ. Різниця принципова,
# і попередня (повна висота) міра давала виміряний хибний позитив на цілому
# джерелі: у PDF з текстовим шаром PyMuPDF віддає блок-абзац, де "\n" -- це
# СПРАВЖНІ рядки тексту в справжньому порядку читання, тож звичайний
# 6-рядковий абзац бланка (h≈74px) переганяв медіану блоку (≈15px, бо
# більшість блоків однорядкові) у 4.8 раза й оголошувався мега-блоком.
# Наслідок був заміряний: на leave-pdf поля `звання` і `місце` давали 0/16,
# бо їхні лейбли лежать саме в таких абзацах.
#
# Заміряні числа, на яких стоїть поріг (обидва -- LEAVE-001):
#   Surya (png, справжній мега-блок): h=907.5 на 4 рядки = 226.9 px/рядок
#     проти медіани 43.3 px/рядок -> 5.2x, лишається мега-блоком;
#     решта блоків тієї ж сторінки -- 39.8-46.8 px/рядок, тобто ~1.0x;
#   PyMuPDF (pdf, звичайний абзац): h=74.6 на 6 рядків = 12.4 px/рядок
#     проти медіани 15.5 px/рядок -> 0.8x, мега-блоком більше не є.
# Тобто розділення між двома класами -- не на межі, а на порядок.
MEGA_BLOCK_HEIGHT_RATIO = 2.5


def _block_line_height(block):
    """Висота bbox блоку, поділена на кількість НЕПОРОЖНІХ рядків, які ми з
    нього прочитали -- скільки вертикалі припадає на один відомий нам рядок.
    None, якщо геометрії немає (docx)."""
    bbox = block.get("bbox")
    if not bbox:
        return None
    lines = block.get("lines") or []
    return (bbox[3] - bbox[1]) / max(1, len(lines))


def _median_block_height(blocks):
    """Типова висота ОДНОГО рядка в документі (медіана по блоках).

    Назва збережена історично; повертає саме висоту рядка -- див. коментар
    до MEGA_BLOCK_HEIGHT_RATIO про те, чому міряти треба рядок, а не блок."""
    heights = [h for h in (_block_line_height(b) for b in blocks) if h]
    if not heights:
        return None
    heights.sort()
    return heights[len(heights) // 2] or 1.0


def _is_mega_block(block, h_med) -> bool:
    line_h = _block_line_height(block)
    if not line_h or not h_med:
        return False
    return line_h > MEGA_BLOCK_HEIGHT_RATIO * h_med


def _geometric_candidate(blocks, label_i, h_med):
    """Шукає значення за вирівнюванням bbox з блоком лейбла, а не за
    порядком блоків у списку -- research-round-2026-08-12.md.

    Викликається лише коли лейбл ПЕРШИЙ рядок свого блоку (тобто раніше
    значення бралось як "попередній блок за списком" -- саме тут стався
    виміряний збій: сусідній за списком блок опинявся не тим, що сусідній
    ГЕОМЕТРИЧНО). Коли лейбл НЕ перший рядок -- значення вже надійно в
    ТОМУ Ж блоці, геометрія там не потрібна й не викликається (виклик --
    у find_block_before_label). label_i уже перевірений викликом як НЕ
    мега-блок.

    Пріоритет напрямку: (1) той самий рядок, значення ПРАВОРУЧ від лейбла;
    (2) той самий стовпець, значення НАД лейблом; (3) той самий стовпець,
    значення ПІД лейблом. "Над" ПЕРЕД "під" навмисно, не за модулем
    відстані: у цій родині бланків лейбл-примітка в дужках СИСТЕМАТИЧНО
    стоїть ПІД значенням, якому належить (`unit_to_report`,
    "дата повернення", "звання, прізвище" -- усі виміряні приклади),
    ніколи навпаки. Виміряний реальний провал версії "усе за модулем
    відстані": лейбл "(військове звання, прізвище...)" мав правильного
    кандидата НАД собою (ім'я, дист. 7px) і невірного ПІД собою (опис
    посади наступного поля, дист. 0px, впритул) -- ближчий за модулем
    переміг, хоч належав ІНШОМУ полю. "Ліворуч"/лінійний порядок навмисно
    НЕ покривається тут -- це фолбек виклику (попередній блок за списком),
    незмінний відносно попередньої поведінки.

    Кандидати-мега-блоки виключаються так само, як і лейбл-мега-блоки:
    bbox, що охоплює кілька рядків, вирівняється з чим завгодно поруч
    суто випадково (підтверджено реальним багом -- блок ПІБ заявника
    "вирівнювався" зі СУСІДНІМ мега-блоком лише тому, що впритул сидів
    НАД ним усім, а не над конкретним рядком-значенням).

    Повертає ІНДЕКС знайденого блоку або None -- коли жоден блок не має bbox
    (docx -- геометрії немає, попередня лінійна поведінка незмінна) або
    жоден кандидат не пройшов фільтр вирівнювання. Індекс, а не готовий
    текст, бо викликачу потрібна ПОЗИЦІЯ кандидата в документі -- від неї
    відлічують ліву межу значення (_value_lines_after_label_note,
    _extend_to_anchor).

    "Той самий рядок/стовпець" визначається ПЕРЕТИНОМ діапазонів bbox по
    перпендикулярній осі, а не відстанню між ЦЕНТРАМИ блоків. Виміряний
    реальний провал попередньої версії (центр + поріг 0.5*h_med): короткий
    лейбл "(дата повернення)" і довша дата над ним "23" травня 2026 р."
    мають РІЗНУ ширину bbox, тому їхні центри розходяться на ~40px --
    більше за поріг, і геометрично правильний, майже впритул сусід
    відкидався, а випадковий далекий блок (~118px) проходив поріг і
    вигравав. Перетин діапазонів переживає різницю ширини тексту, лишаючись
    чутливим до напрямку (той самий рядок/стовпець, не будь-де)."""
    label_bbox = blocks[label_i].get("bbox")
    if not label_bbox or not h_med:
        return None
    label_page = blocks[label_i].get("page")
    lx1, ly1, lx2, ly2 = label_bbox
    # Скільки ДОТИКУ дозволено вважати "над"/"під", а не перетином.
    # Заміряний реальний провал (LEAVE-006.png, `ПІБ`/`звання` = None): рамка
    # рядка "старший сержант ВЛОХ Святослав Олесьович" (y 643-685) заходить на
    # рамку свого лейбла "(військове звання, прізвище...)" (y 683-727) на ДВА
    # пікселі. Строге `by2 <= ly1` викидало правильного кандидата з РОЗГЛЯДУ
    # ВЗАГАЛІ (він не "праворуч", не "над", не "під"), і "найближчим зверху"
    # ставав номер документа рядком вище. Рамки сусідніх рядків OCR
    # торкаються постійно -- це властивість детектора, а не верстки.
    # Чверть висоти рядка: дотик переживається, справжній сусід по рядку
    # (перетин на цілий рядок) -- ні.
    touch = 0.25 * h_med

    same_row, same_above, same_below = [], [], []
    for i, block in enumerate(blocks):
        if i == label_i or not block.get("bbox") or not block["lines"]:
            continue
        # Кандидат з ІНШОЇ сторінки/кадру виключається завжди: кожна
        # сторінка PDF (і кожен кадр TIFF) рахує bbox з нуля, тому
        # "близькість" між сторінками -- геометричний нуль-сенс, не збіг.
        # Виміряний реальний баг: LEAVE-003.pdf (2 сторінки) -- блок
        # "Командир" зі сторінки 2 опинився "поруч" із лейблом на сторінці 1
        # лише тому, що обидві сторінки рахують y з нуля.
        if block.get("page") != label_page:
            continue
        if _is_mega_block(block, h_med):
            continue
        bx1, by1, bx2, by2 = block["bbox"]
        y_overlap = by1 < ly2 and ly1 < by2
        x_overlap = bx1 < lx2 and lx1 < bx2
        if y_overlap and bx1 > lx2:
            same_row.append((bx1 - lx2, i))
        elif x_overlap and by2 <= ly1 + touch:
            same_above.append((ly1 - by2, i))
        elif x_overlap and by1 >= ly2 - touch:
            same_below.append((by1 - ly2, i))

    for group in (same_row, same_above, same_below):
        if group:
            group.sort(key=lambda t: t[0])
            return group[0][1]
    return None


def _sandwich_value(block_text: str, label_substring: str,
                    oversized_chars=OVERSIZED_CANDIDATE_CHARS):
    """Значення, приклеєне до лейбла в ОДНОМУ суцільному OCR-тексті без
    роздільника -- бланк друкує "ЗНАЧЕННЯ(лейбл-примітка)" одним потоком, а
    Surya не завжди ставить `\\n` на межі поля -- research-round-2026-08-12.md,
    варіант C. Шукає лейбл у ПОВНОМУ тексті мега-блоку (не в одному
    `\\n`-розрізаному "рядку" -- сам `\\n` тут не межа поля, лише випадковий
    артефакт того, де Surya вставила `<br>`: підтверджено реальним випадком,
    де значення для лейбла з одного "рядка" фізично лежить у ПОПЕРЕДНЬОМУ),
    бере текст між НАЙБЛИЖЧОЮ попередньою ")" і початком лейбла.

    Навмисно консервативний -- None означає "не застосовно", НЕ "значення
    відсутнє": якщо немає попередньої ")" (лейбл, найпевніше, перший у
    блоці -- значення в ПОПЕРЕДНЬОМУ окремому блоці, сендвіч тут не
    працює), або кандидат містить ВКЛАДЕНУ "(" (ознака, що OCR десь РАНІШЕ
    в блоці загубила закриваючу дужку, і межа "з'їхала" на поле раніше --
    виміряний реальний випадок: одна втрачена дужка захопила текст трьох
    чужих полів), або кандидат аномально довгий -- відмовляється, а не
    вгадує.

    normalize_ws на ОБОХ аргументах -- ОБОВ'ЯЗКОВО: `hits` (виклик знаходить
    лейбл через find_block_before_label) знаходяться через `phrase_in_text`,
    яка вже нормалізує пробіли (nbsp, подвійний пробіл, перенос рядка
    всередині фрази). Без цього тут `.find()` шукав би лейбл буквально й
    міг НЕ знайти те, що `phrase_in_text` щойно знайшла -- сендвіч мовчки
    відмовлявся б на тих самих OCR-документах, де межа лейбла найчастіше і
    ламається пробілами."""
    text = normalize_ws(block_text).lower()
    label = normalize_ws(label_substring).lower()
    idx = text.find(label)
    if idx == -1:
        return None
    prev_close = text.rfind(")", 0, idx)
    if prev_close == -1:
        return None
    value = text[prev_close + 1:idx].rstrip("(").strip()
    if not value or len(value) > oversized_chars or "(" in value:
        return None
    return value


def _has_unmatched_close_paren(text: str) -> bool:
    """True, якщо в тексті є ")" без відповідної "(" ПЕРЕД нею в ЦЬОМУ Ж
    тексті -- ознака, що справжній початок значення лежить у ПОПЕРЕДНЬОМУ
    блоці. Виміряний реальний випадок: PyMuPDF (текстовий шар PDF) розбив
    "Центральна база зберігання майна (в/ч" / "Т3011)" на ДВА окремі блоки
    рівно на переносі рядка всередині дужки -- значення не мега-блок і не
    склеєне без пробілу, воно просто фізично в іншому блоці, ніж лейбл."""
    depth = 0
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            if depth == 0:
                return True
            depth -= 1
    return False


def _is_printed_label_note(line: str) -> bool:
    """Рядок -- ПОВНА дужкова примітка бланка ("(вид відпустки та...)",
    "(військове звання, прізвище, ім'я та по батькові)"), тобто друкована
    підказка, що ЗАКРИВАЄ попереднє поле, а не текст значення.

    Вимагається і "(" на початку, і ")" в кінці, і збалансованість. Саме
    збалансованість відрізняє примітку від ХВОСТА значення, розірваного
    переносом усередині дужки: "Т3011)" (кінець "Центральна база зберігання
    майна (в/ч Т3011)") має ")" в кінці, але не має "(" на початку -- і його
    підбирає _extend_across_block_boundary, а не ця перевірка."""
    s = line.strip()
    return (s.startswith("(") and s.endswith(")")
            and s.count("(") == s.count(")"))


def compile_value_boundaries(field: dict):
    """Скомпільовані патерни `value_starts_after` зі схеми -- рядки бланка, які
    ЗАКРИВАЮТЬ попереднє поле, але НЕ є дужковою приміткою, тому
    _is_printed_label_note їх не бачить.

    Навіщо окремий ключ, а не ще одна хардкод-евристика: у PDF з текстовим
    шаром PyMuPDF складає в ОДИН блок кілька полів бланка підряд, і межа між
    ними -- звичайний друкований рядок. Заміряно на deployment/pdf, поле
    `purpose`: кандидат перед лейблом "(мета відрядження)" виходив як
        'Термін відрядження “2” днів   з “21” травня 2026 р. по “22” травня 2026 р.'
        'отримання засобів індивідуального'
        'захисту'
    -- тобто ПОВНИЙ рядок терміну відрядження (окреме поле, у якого свій
    regex) приклеювався до мети як частина значення, з провенансом `matched`.
    Дужкової примітки між ними на цьому бланку немає взагалі.

    Патерн, а не літерал: межу утворює саме СТАЛА частина чужого рядка
    ("Термін відрядження"), а змінна (дати, кількість днів) до неї не
    належить. Той самий інваріант, що вже несе `_is_printed_label_note`,
    тільки оголошений схемою, бо він специфічний для бланка."""
    return [re.compile(p, re.IGNORECASE)
            for p in (field.get("value_starts_after") or [])]


def _is_field_boundary_line(line, extra_boundaries=(), printed=()) -> bool:
    """Рядок ЗАКРИВАЄ попереднє поле бланка, тобто значення нашого поля
    починається після нього.

    Три межі, від найслабшої до найсильнішої: дужкова примітка бланка,
    оголошена схемою межа (`value_starts_after`), дослівний друкований рядок
    порожнього бланка. Розклад кожної -- у докстрінгах
    `_is_printed_label_note`, `compile_value_boundaries` і
    `_value_lines_after_label_note`.

    Виділено в окрему функцію тому, що те саме питання ставиться в ДВА боки:
    `_value_lines_after_label_note` шукає межу серед рядків ОДНОГО блоку,
    `_extend_across_pdf_wrap` -- ідучи назад ЧЕРЕЗ межі блоків. Дві копії цієї
    умови розійшлись би, і тоді "де починається значення" залежало б від того,
    чи PyMuPDF поклала його початок у той самий блок."""
    return bool(_is_printed_label_note(line)
                or is_printed_form_text(line, printed)
                or any(p.search(line) for p in extra_boundaries))


def _value_lines_after_label_note(lines, extra_boundaries=(), printed=()):
    """Значення починається ПІСЛЯ останньої друкованої примітки-лейбла (або
    оголошеної схемою межі, див. compile_value_boundaries) серед рядків-
    кандидатів, а не з першого рядка блоку.

    Це той самий інваріант бланка, на якому вже стоїть _sandwich_value
    ("текст між найближчою попередньою ')' і початком лейбла"), лише
    застосований до багаторядкового блоку, а не до суцільного OCR-тексту.

    Навіщо: у PDF з текстовим шаром один блок PyMuPDF нерідко містить
    КІЛЬКА полів бланка з їхніми примітками підряд, напр. (LEAVE-001.pdf)
        '№ 102    від 09.05.2026'
        'рядовий ЛЕМЕШКО Соломія Романівна'
        "(військове звання, прізвище, ім'я та по батькові)"
        'звільнена'
        'щорічна основна відпустка за 2026 рік'
        '(вид відпустки та найменування населеного пункту,'   <- лейбл
    Без цієї межі значення поля "вид відпустки" = ВСІ п'ять рядків до
    лейбла, тобто номер документа й ПІБ приклеюються до відповіді. Перевірка
    еталона це пропускала лише тому, що field-mapping.yaml порівнює цей ключ
    через `compare: contains` -- заміряно на 7 документах leave-pdf.

    `printed` -- друковані рядки ПОРОЖНЬОГО бланка (blank_form.printed_lines).
    Це найсильніша з трьох меж і єдина, що не є евристикою: рядок, який
    дослівно надрукований на бланку, значенням поля не є за визначенням.
    Потрібна вона там, де лейбл РОЗРІЗАНИЙ навпіл, а значення стоїть між
    половинами -- заміряний випадок `місце` (LEAVE-006/008.png): кандидат
    перед лейблом "до якого звільнено військовослужбовця)" виходить як
        '(вид відпустки та найменування населеного пункту,'   <- перша половина
        'м. Івано-Франківськ'                                 <- значення
    Перша половина не є дужковою приміткою (не збалансована), тому
    `_is_printed_label_note` її не бачить, і поле відхилялось цілком як
    "лейбл у значенні".

    Порожній залишок -> рядки НЕ ріжуться: примітка в кінці кандидата це
    частина самого значення ("(перервана, відкликаний з відпустки)"), а не
    межа перед ним."""
    last_note = None
    for k, line in enumerate(lines):
        if _is_field_boundary_line(line, extra_boundaries, printed):
            last_note = k
    if last_note is None or last_note + 1 >= len(lines):
        return lines
    return lines[last_note + 1:]


# Скільки рядків назад максимум шукати оголошений схемою якір. Обмеження, а
# не істина про бланк: якщо якір не знайшовся поруч, ми, найпевніше, шукаємо
# не те -- і мовчки набрати півсторінки гірше, ніж лишити значення як є.
MAX_ANCHOR_LOOKBACK_LINES = 6


def _lines_backwards(blocks, i, j):
    """Рядки документа ПЕРЕД blocks[i]["lines"][j], у зворотному порядку.
    Не виходить за межі СТОРІНКИ: на іншій сторінці "попередній рядок" --
    це низ попередньої сторінки, тобто підписи й печатки, а не продовження
    значення (та сама причина, що й у _geometric_candidate).

    Так само не виходить за межі одного ПОХОДЖЕННЯ блоків (`source`): у PDF,
    де частина сторінок має текстовий шар, а частина -- скан через OCR,
    "попередній рядок" з іншого джерела прийшов іншим механізмом з іншими
    межами. На docx і на чистому OCR-прогоні `source` однаковий у всіх
    блоків, тому ця умова там інертна."""
    page = blocks[i].get("page")
    source = blocks[i].get("source")
    for k in range(j - 1, -1, -1):
        yield blocks[i]["lines"][k]
    for bi in range(i - 1, -1, -1):
        if blocks[bi].get("page") != page or blocks[bi].get("source") != source:
            return
        for line in reversed(blocks[bi]["lines"]):
            yield line


def _extend_to_anchor(blocks, i, start_j, value_lines, anchor,
                      oversized_chars=OVERSIZED_CANDIDATE_CHARS):
    """`strip_prefix` зі схеми -- це не лише те, що треба ЗРІЗАТИ, а й
    оголошення ЛІВОЇ МЕЖІ значення: літерал, одразу після якого значення
    починається ("звільнений", "Видано"). Якщо його немає в кандидаті --
    значення обірване, і бракує саме початку.

    Навіщо: PyMuPDF ріже довгий рядок бланка на межі переносу, і початок
    значення лишається в ПОПЕРЕДНЬОМУ блоці. Заміряно на LEAVE-003/009/015
    (кандидат = 'рік' -- сам лише хвіст "...за 2026 / рік") і LEAVE-014
    (кандидат = '(перервана, відкликаний з відпустки)' -- сама лише
    примітка в дужках, без відпустки, до якої вона належить).

    Добираємо рядки назад, поки не знайдемо якір; не знайшли в межах ліміту
    -- повертаємо кандидата БЕЗ ЗМІН (безпечний відкат, та сама дисципліна,
    що в _extend_across_block_boundary), а не найкращий здогад.

    Зупинка на друкованій примітці-лейблі (_is_printed_label_note) --
    обов'язкова: примітка закриває ПОПЕРЕДНЄ поле, тож значення нашого поля
    почалось після неї за побудовою бланка. Без цієї зупинки документ, де
    якір узагалі не знаходиться, набирав би назад чужі поля -- заміряно на
    LEAVE-001, де якір надрукований в іншому роді ("звільненА" в жіночому
    проти "звільнений" у схемі). САМ рід тепер обробляється (anchor_in_line /
    prefix_match_length), але зупинка лишається: вона потрібна для будь-якого
    ІНШОГО якоря, якого в документі просто немає.

    Працює зі СПИСКОМ рядків і ЯВНИМ start_j (індексом рядка, з якого
    кандидат починається в блоці i), а не з готовим рядком-кандидатом:
    відновлювати позицію підрахунком "\\n" у кандидаті не можна, бо кандидат
    міг бути вже розширений іншим механізмом, і та сама арифметика давала
    ДУБЛЮВАННЯ тексту (виміряно на LEAVE-016: 'відпустка за сімейними
    обставинами (виданий замість анульованого відпустка за сімейними
    обставинами (виданий замість анульованого квитка № 157)')."""
    if not anchor:
        return value_lines
    if any(anchor_in_line(line, anchor) for line in value_lines):
        return value_lines
    prefix = []
    for n, line in enumerate(_lines_backwards(blocks, i, start_j)):
        if n >= MAX_ANCHOR_LOOKBACK_LINES or _is_printed_label_note(line):
            break
        prefix.insert(0, line)
        merged = prefix + value_lines
        if len("\n".join(merged)) > oversized_chars:
            break
        if anchor_in_line(line, anchor):
            return merged
    return value_lines


def _extend_across_block_boundary(blocks, label_block_i, candidate):
    """Якщо candidate має незакриту ")" -- добирає рядки з КІНЦЯ
    попереднього блоку, по одному, поки дужки не збалансуються. Мінімально
    необхідне розширення, а не весь попередній блок цілком: інакше в
    кандидат потрапив би й сторонній текст (напр. "посада, місце роботи"
    перед "Центральна база зберігання майна (в/ч" в тому самому блоці).
    Якщо баланс не досягається навіть з усім попереднім блоком -- повертає
    candidate без змін (безпечний відкат, а не вигаданий текст)."""
    if not _has_unmatched_close_paren(candidate) or label_block_i == 0:
        return candidate
    prev_lines = blocks[label_block_i - 1]["lines"]
    prefix = []
    for line in reversed(prev_lines):
        prefix.insert(0, line)
        merged = " ".join(prefix) + " " + candidate.replace("\n", " ")
        if not _has_unmatched_close_paren(merged):
            # Пробіл, не "\n", на межі злиття: це перенос рядка ВСЕРЕДИНІ
            # одного значення (де опинилась дужка), не межа двох різних
            # значень -- на відміну від "\n".join(prefix) для рядків
            # УСЕРЕДИНІ самого prefix, де перенос може бути змістовним.
            return "\n".join(prefix) + " " + candidate
    return candidate


#: Скільки рядків максимум добирати назад через межу блоку PDF. Обмеження, а
#: не істина про бланк: голова значення, від якої PyMuPDF відрізала хвіст,
#: це один-два рядки, тому якщо межа поля не знайшлась за три -- ми, найпевніше,
#: вже не в тому місці документа, і мовчки набрати півсторінки гірше, ніж
#: лишити кандидата як є.
MAX_PDF_WRAP_LOOKBACK_LINES = 3


def _extend_across_pdf_wrap(blocks, src_i, start_j, value_lines,
                            extra_boundaries=(), printed=(),
                            oversized_chars=OVERSIZED_CANDIDATE_CHARS):
    """Добирає ПОЧАТОК значення, який PyMuPDF відрізала межею блоку.

    Причина (розд. 5.7, заміряно 14.08.2026 на deployment/pdf). Блок
    текстового шару PDF -- це група послідовних рядків, а не абзац
    (ingest.PDF_TEXT_SOURCE), тому один абзац бланка приходить розкладеним на
    два блоки рівно на переносі рядка:

        [блок 3] ... '(військове звання, прізвище ім’я по батькові)'
                     'навідник, 3-тя механізована рота, військова'   <- початок
        [блок 4] 'частина А0000'                                     <- хвіст
        [блок 5] '(посада, місце роботи)' ...                        <- лейбл

    "Попередній блок" перед лейблом -- це блок 4, тобто САМ ХВОСТ значення, і
    поле виходило `частина А0000` з провенансом `matched`: тихо обрізане
    значення з найвищою довірою. Заміряно 11 з 14 документів deployment/pdf.

    Наявні механізми тут не працюють за побудовою: `_extend_across_block_boundary`
    чекає незакритої ")" (дужки тут збалансовані), `_extend_to_anchor` --
    оголошеного схемою `strip_prefix` (у цього поля його немає), і бракує не
    префікса, а СЕРЕДИНИ значення.

    Тому межа шукається тим самим правилом, яким вона й так шукається
    ВСЕРЕДИНІ блоку (`_is_field_boundary_line`), лише йдучи назад ЧЕРЕЗ межі
    блоків: значення поля -- це все між межею попереднього поля й лейблом.
    Правило бланка не змінюється -- знімається лише неправдива межа.

    Обмежене `source == PDF_TEXT_SOURCE` НАВМИСНО, і це головна гарантія:
    на docx межа блоку -- це абзац або клітинка, тобто справжня межа поля, а
    на фото межі відновлює `blank_form.resegment_by_blank` (і навмисно
    занулює `bbox`/`source`). Обидва шляхи цієї функції не бачать, тому їхні
    цифри не можуть змінитися.

    Не знайшли межі в межах ліміту або добір переріс очікуваний розмір поля --
    повертаємо `value_lines` БЕЗ ЗМІН (безпечний відкат, та сама дисципліна,
    що в `_extend_to_anchor` і `_extend_across_block_boundary`).

    Шматки склеюються ПРОБІЛОМ, не "\\n", і з тієї самої причини, що вже
    записана в `_extend_across_block_boundary`: тут перенос рядка -- місце,
    де PyMuPDF розірвала ОДНЕ значення, а не межа двох різних. Практичний
    наслідок: значення на pdf виходить побайтово тим самим, що на docx, тобто
    в `facts.value_code` для БД не з'являється двох різних написань того самого
    факту залежно від формату файлу.
    """
    if blocks[src_i].get("source") != PDF_TEXT_SOURCE:
        return value_lines
    prefix = []
    for n, line in enumerate(_lines_backwards(blocks, src_i, start_j)):
        if (n >= MAX_PDF_WRAP_LOOKBACK_LINES
                or _is_field_boundary_line(line, extra_boundaries, printed)):
            break
        if len(" ".join([line] + prefix + value_lines)) > oversized_chars:
            break
        prefix.insert(0, line)
    if not prefix:
        return value_lines
    # Перший рядок значення -- продовження останнього дібраного шматка, тому
    # вони стають ОДНИМ рядком. Решта рядків значення лишається як була:
    # їхні межі цією правкою не переглядаються.
    return [" ".join(prefix + value_lines[:1])] + list(value_lines[1:])


#: Скільки переставлених друкованих блоків поспіль дозволено пропустити.
#: Обмеження, а не істина про бланк: якщо між лейблом і значенням стоїть
#: більше двох чужих друкованих рядків, ми, найпевніше, вже не в тому місці
#: документа, і мовчки взяти щось звідти гірше, ніж чесно не знайти.
MAX_REORDERED_SKIP = 2


def _previous_value_block(blocks, label_i, label_index, order):
    """Індекс найближчого попереднього блоку, який МОЖЕ бути значенням, або
    None.

    "Може бути" = блок не є друкованим рядком бланка, що на самому бланку
    стоїть ПІСЛЯ нашого лейбла (blank_form.printed_after_label). Такий блок
    опинився перед лейблом лише через порядок читання OCR, і пропустити його
    -- єдиний спосіб дістати значення, яке за ним стоїть.

    Заміряно (LEAVE-003/004/007.png): між "м. Житомир" і лейблом
    "до якого звільнено військовослужбовця)" Surya вставила "терміном на" --
    рядок, надрукований на бланку НИЖЧЕ лейбла. Без пропуску `місце` на цих
    документах виходило `printed_form_text`, тобто чесний нуль замість
    правильного значення, яке лежало на один блок далі.

    Без оголошеного бланка (`order` порожній) поведінка та сама, що була:
    береться рівно попередній блок.
    """
    skipped = 0
    for k in range(label_i - 1, -1, -1):
        lines = blocks[k]["lines"]
        if not lines:
            continue
        if (skipped < MAX_REORDERED_SKIP
                and printed_after_label("\n".join(lines), label_index, order)):
            skipped += 1
            continue
        return k
    return None


def find_block_before_label(blocks, label_substring, denylist=None, anchor=None,
                            boundaries=(), printed=(), order=None,
                            oversized_chars=OVERSIZED_CANDIDATE_CHARS):
    """blocks: результат group_blocks_into_lines() -- список
    {"lines": [...], "bbox": (...)|None}.

    anchor -- необов'язковий літерал ЛІВОЇ МЕЖІ значення (на практиці
    `strip_prefix` зі схеми); див. _extend_to_anchor. None -> поведінка як
    була.
    boundaries -- скомпільовані патерни `value_starts_after` зі схеми
    (compile_value_boundaries); () -> поведінка як була.
    Повертає (значення_або_None, причина), причина:
    matched | no_label | ambiguous_label | denylisted |
    oversized_block_suspect.

    Логіка пошуку:
    - лейбл усередині МЕГА-блоку (_is_mega_block) -- ні лінійна, ні
      геометрична позиція всередині нього не надійна (bbox описує ввесь
      блок, не конкретний рядок). Спершу пробується детермінований
      "сендвіч"-парсер (_sandwich_value) -- значення й лейбл нерідко
      склеєні в ОДИН OCR-текст без розриву; якщо він відмовився (сам по
      собі консервативний) -- `oversized_block_suspect` БЕЗ підказки, а не
      з обрізаним текстом: обрізка сама вгадувала межу поля іншим способом
      і так само помилялась (виміряно емпірично -- research-round-2026-08-12.md,
      варіант A: повний текст документа відновив 5 з 7 полів мега-блоку,
      обрізана підказка -- 1 з 5). Виклик направляє таке поле в LLM-фолбек
      з ПОВНИМ текстом документа;
    - інакше, якщо лейбл не перший рядок свого блоку -- значення це ВСІ
      рядки того ж блоку до лейбла (може бути кілька -- багаторядкове
      значення). Ніколи не змішує рядки з двох різних блоків в одну
      "лінійну" відстань;
    - інакше (лейбл перший рядок свого блоку) -- спершу геометрична
      прив'язка за bbox (_geometric_candidate); коли bbox немає (docx) або
      вирівняного кандидата не знайдено -- лінійний фолбек, як і раніше:
      весь попередній блок за порядком списку.

    Якщо лейбл трапляється в КІЛЬКОХ місцях документа -- це `ambiguous_label`,
    а не "беремо перше входження". Раніше перше входження вигравало мовчки, і
    документ із двома схожими лейблами (звання заявника й звання командира)
    міг дати чуже значення з виглядом повного успіху.

    Кандидат зі ЗВИЧАЙНОГО блоку, аномально довший за очікуване значення
    поля (OVERSIZED_CANDIDATE_CHARS), так само не приймається мовчки як
    "matched" -- та сама проблема (кілька полів без межі), лише не в лейблі,
    а у сусідньому блоці. Повертається `oversized_block_suspect` без
    підказки, з тієї самої причини, що й для мега-блоку.
    """
    low_label = label_substring.lower()
    low_denylist = denylist or set()
    # Геометрія працює лише тоді, коли bbox має КОЖЕН блок. Причина заміряна
    # (LEAVE-003.png): після відновлення меж за бланком (blank_form.
    # resegment_by_blank) частина блоків геометрії не має, і "найближчий
    # вирівняний" рахувався по НАБОРУ З ДІРКАМИ -- лейбл "(вид відпустки..."
    # знайшов "найближчим зверху" ПІБ заявника через півсторінки, бо всі
    # справжні сусіди вибули з розгляду разом із bbox. Дірявий набір гірший
    # за відсутність геометрії: docx без неї дає 176/176.
    geometry_ok = all(b.get("bbox") for b in blocks)
    order = order or {}
    label_index = label_order_index(label_substring, order)

    hits = []
    for i, block in enumerate(blocks):
        for j, line in enumerate(block["lines"]):
            # Межа слова на початку (як у phrase_in_text): лейбл не має
            # співпадати всередині іншого слова.
            if phrase_in_text(line.lower(), low_label):
                hits.append((i, j))

    if not hits:
        return None, "no_label"

    h_med = _median_block_height(blocks)

    # Перевірка мега-блоку -- ДО побудови кандидатів і ДО ambiguous_label:
    # інакше та сама плутанина рядків усередині мега-блоку могла б випадково
    # дати кілька РІЗНИХ "кандидатів" і замаскувати проблему під "лейбл
    # неоднозначний" замість чесного "не можна довіряти позиції".
    #
    # Розділяємо ВСІ хіти на мега- і звичайні, а не дивимось лише на
    # hits[0]: якщо лейбл трапляється і в мега-, і в звичайному блоці
    # одночасно -- це справжня неоднозначність (виправлений баг: раніше
    # `any(...)` перевіряла всі хіти, а брався беззастережно hits[0], тому
    # чистий звичайний блок міг "загубитись" за спиною мега-блоку в іншому
    # місці документа, чи навпаки).
    mega_hits = [(i, j) for i, j in hits if _is_mega_block(blocks[i], h_med)]
    normal_hits = [(i, j) for i, j in hits if not _is_mega_block(blocks[i], h_med)]

    if mega_hits and normal_hits:
        return None, "ambiguous_label"

    if mega_hits:
        sandwich_values = []
        for i, _ in mega_hits:
            block_text = "\n".join(blocks[i]["lines"])
            value = _sandwich_value(block_text, label_substring,
                                    oversized_chars=oversized_chars)
            if value is not None:
                sandwich_values.append(value)
        distinct_sandwich = {v.strip() for v in sandwich_values}
        if len(distinct_sandwich) > 1:
            return None, "ambiguous_label"
        if len(distinct_sandwich) == 1:
            value = sandwich_values[0]
            if _is_denylisted(value, low_denylist):
                return None, "denylisted"
            return value, "matched"
        return None, "oversized_block_suspect"

    candidates = []
    unresolved_hit = False
    for i, j in hits:
        # (блок-джерело, його рядки-кандидати) -- ЄДИНА точка, де вони
        # визначаються, далі ліва межа значення шукається однаково для всіх
        # трьох шляхів. Раніше межа рахувалась лише на шляху "лейбл не
        # перший рядок", і той самий бланк давав чисте значення або значення
        # з приклеєними чужими полями залежно від того, чи PyMuPDF поклав
        # лейбл в окремий блок -- заміряний розкид на LEAVE-004/007/013
        # (лейбл у власному блоці) проти LEAVE-002/005/006 (лейбл разом зі
        # значенням), при тому що бланк той самий.
        if j > 0:
            src_i, src_lines = i, blocks[i]["lines"][:j]
        else:
            geo_i = _geometric_candidate(blocks, i, h_med) if geometry_ok else None
            prev_i = geo_i if geo_i is not None \
                else _previous_value_block(blocks, i, label_index, order)
            if prev_i is not None:
                src_i, src_lines = prev_i, blocks[prev_i]["lines"]
            else:
                # Цей хіт не дав ЖОДНОГО кандидата (лейбл -- перший рядок
                # першого блоку документа, і геометрія теж не спрацювала).
                # Раніше хіт просто мовчки випадав зі списку candidates --
                # якщо лейбл трапляється кілька разів, а цей конкретний хіт
                # міг би дати ІНШЕ значення, ми цього не дізнаємось і
                # ризикуємо видати "matched" за збігом решти хітів, хоча
                # справжньої одностайності не перевірено.
                unresolved_hit = True
                continue

        value_lines = _value_lines_after_label_note(src_lines, boundaries, printed)
        start_j = len(src_lines) - len(value_lines)
        extended = _extend_to_anchor(blocks, src_i, start_j, value_lines, anchor,
                                     oversized_chars=oversized_chars)
        if extended is not value_lines:
            # Якір уже встановив ліву межу значення. Добирати ще й
            # _extend_across_block_boundary НЕ МОЖНА: обидва механізми
            # тягнуть з ПОПЕРЕДНЬОГО блоку, і другий приклеїв би вдруге те,
            # що перший уже взяв -- рівно той клас дублювання, який описаний
            # у _extend_to_anchor.
            candidates.append("\n".join(extended))
        elif j > 0:
            # Добір хвоста через межу блоку лишається лише на шляху "лейбл
            # не перший рядок свого блоку" -- там кандидат за побудовою
            # закінчується рівно перед лейблом, тож незакрита ")" справді
            # означає обрізаний ПОЧАТОК. На шляху "весь попередній блок" цієї
            # гарантії немає, і поведінка тут навмисно лишається як була.
            candidates.append(_extend_across_block_boundary(
                blocks, src_i, "\n".join(value_lines)))
        else:
            # Лейбл -- перший рядок свого блоку, тобто кандидат це ВЕСЬ
            # попередній блок. Саме тут межа блоку могла виявитись не межею
            # поля, а місцем переносу рядка -- див. _extend_across_pdf_wrap
            # (працює лише на текстовому шарі PDF).
            candidates.append("\n".join(_extend_across_pdf_wrap(
                blocks, src_i, start_j, value_lines, boundaries, printed,
                oversized_chars=oversized_chars)))

    if not candidates:
        return None, "no_label"
    if unresolved_hit and len(hits) > 1:
        return None, "ambiguous_label"
    distinct = {c.strip() for c in candidates}
    if len(distinct) > 1:
        return None, "ambiguous_label"

    candidate = candidates[0]
    if _is_denylisted(candidate, low_denylist):
        return None, "denylisted"
    if len(candidate) > oversized_chars:
        return None, "oversized_block_suspect"
    return candidate, "matched"


# --- Валідація значення, прийнятого за версткою бланка -------------------
#
# Проблема (known-weak-spots.md, "[ВІДКРИТО 12.08.2026]"): щойно
# find_block_before_label казала "matched", extract_document приймала значення
# БЕЗУМОВНО і НЕ додавала поле в global_gaps -- тобто LLM-фолбек до нього не
# доходив ніколи, бо маршрутизація дивилась лише на `raw is None`. Реальний
# випадок: `"звільнена(військове звання, прізвище..."` як номер військової
# частини. Баг зі `strip_prefix` за родом (prefix_match_length вище) -- з того
# самого класу.
#
# Що тут перевіряється, і чому саме це:
# - 54% значень з провенансом `matched` -- це `text`/`object_ref`, де ТИПОВА
#   перевірка неможлива в принципі (research-round-2026-08-13.md, 1.2). Тому
#   основна перевірка НЕ типова, а «чи це взагалі значення, а не друкований
#   текст самого бланка»: якщо в кандидаті стоїть лейбл, оголошений цією ж
#   схемою (або заголовок бланка), значення взяте не з того місця. Ця
#   перевірка працює на будь-якому типі;
# - типова перевірка додається лише для `date`/`number` -- єдиних типів, де
#   вона не тавтологічна й де комбінація `matched` + `normalized=None` була
#   можлива й нічим не позначена.
#
# ЖОДНА з перевірок не викидає дані: значення йде в provenance разом із
# причиною (raw_text у build_record), а поле стає прогалиною й отримує другий
# шанс через LLM.

# Скільки перших слів лейбла утворюють "голову", за якою його впізнають у
# кандидаті. Ціле лейбла шукати недостатньо: OCR/верстка обрізають примітку
# ("(військове звання, прізвище..." без "ім'я та по батькові"), і саме
# обрізаний хвіст був у виміряному випадку. Три слова -- бо саме на трьох
# перших словах жоден лейбл двох наявних схем не збігається з жодним реальним
# значенням поля (перевірено прогоном по всіх чотирьох корпусах).
LABEL_HEAD_TOKENS = 3
# Коротка "голова" (одне-два слова) занадто загальна: "дата повернення" чи
# "мета відрядження" можуть законно стояти в описі. Порогом відсікаємо їх.
MIN_LABEL_HEAD_CHARS = 16
# Типи, для яких типова перевірка додає інформацію. text/object_ref свідомо
# НЕ входять (перевіряти нічого), category теж: там роль перевірки виконує
# довідник, і "термін не розпізнано" вже видно в provenance.
TYPE_CHECKED_TYPES = ("date", "number")


def schema_label_heads(schema: dict) -> tuple:
    """«Голови» друкованих лейблів і заголовків, оголошених САМОЮ схемою.

    Джерело -- сама схема, а не окремий список у коді: новий шаблон = новий
    YAML лишається правдою, і перевірка автоматично знає лейбли нового бланка.
    """
    phrases = []
    for field in schema.get("fields") or []:
        if field.get("label_before"):
            phrases.append(field["label_before"])
    ident = schema.get("identification") or {}
    phrases.extend(ident.get("title") or [])
    phrases.extend(ident.get("anchors") or [])

    # Дефолти виведені з двох наявних форм; бланк з іншою типографікою
    # перевизначає їх у власному YAML (R-A1-08), а не в коді.
    head_tokens = schema_extraction_limit(schema, "label_head_tokens",
                                          LABEL_HEAD_TOKENS)
    min_head_chars = schema_extraction_limit(schema, "min_label_head_chars",
                                             MIN_LABEL_HEAD_CHARS)
    heads = set()
    for phrase in phrases:
        tokens = normalize_ws(phrase).lower().split()
        head = " ".join(tokens[:head_tokens])
        if len(head) >= min_head_chars:
            heads.add(head)
    return tuple(sorted(heads))


def validate_block_value(field: dict, raw, label_heads=(), printed=()):
    """(значення, причина) для значення, яке find_block_before_label щойно
    оголосила `matched`.

    Причини відхилення (значення -> None, поле -> global_gaps):
      blank_value          -- лишився placeholder/порожньо після зрізання;
      printed_form_text    -- кандидат ЦІЛКОМ складається з друкованих рядків
                              порожнього бланка (blank_form.py);
      printed_label_in_value -- у кандидаті стоїть лейбл/заголовок цього ж
                                бланка, тобто взято не значення, а верстку;
      type_mismatch        -- поле оголошене date/number, а з кандидата не
                              виходить ні дати, ні числа.
    """
    if raw is None:
        return None, "no_value"
    text = raw if isinstance(raw, str) else str(raw)
    if not text.strip() or is_placeholder(text, field_placeholder_tokens(field)):
        return None, "blank_value"

    # ПЕРЕД перевіркою типу, і це не косметика: незаповнений слот дати
    # ("“_____” ______________20___ р.") не є placeholder-ом (у ньому лишились
    # друковані "20" і "р."), тож без цієї гілки він відхилявся б як
    # `type_mismatch` -- причина, що вказує на не ту ваду й веде поле в
    # LLM-фолбек замість того, щоб визнати бланк порожнім.
    if is_printed_form_text(text, printed):
        return None, "printed_form_text"

    low = text.lower()
    for head in label_heads:
        if phrase_in_text(low, head):
            return None, "printed_label_in_value"

    if field.get("type") in TYPE_CHECKED_TYPES:
        value, confirmed_empty = normalize_field(field, text, {})
        if value is None and not confirmed_empty:
            return None, "type_mismatch"

    return text, "matched"


def validate_regex_value(field: dict, raw, printed=()):
    """(значення, причина) для значення, яке щойно віддав схемний regex.

    Окрема від `validate_block_value`, бо шлях інший і перевірки потрібні НЕ
    всі: regex уже задав форму значення, тому ні `label_heads`, ні перевірка
    типу тут не доречні -- вони або тавтологічні, або відкидали б те, що сам
    патерн визнав правильним.

    Лишаються рівно дві, і обидві -- про порожній бланк:
      blank_value       -- патерн зматчив сам слот ("___"). Значення далі
                           гасила нормалізація, тобто в БД воно не йшло, --
                           але провенанс БРЕХАВ, що поле прочитане;
      printed_form_text -- патерн переліз через перенос рядка й захопив
                           друкований рядок форми. Лікується результат, а не
                           патерн: перехід через `\\n` потрібен, бо в
                           заповнених документах значення стоїть наступним
                           рядком.
    """
    if raw is None:
        return None, "no_value"
    # НЕ рядок -- значить regex з іменованими групами віддав {day,month,year}.
    # Такий результат проходить БЕЗ змін: str() перетворив би словник на його
    # repr ("{'day': '10', ...}"), і нормалізація дати отримала б текст
    # замість частин. Заміряно: саме це обвалило всі три поля-дати
    # (`дата_видачі` 0/16) під час першої версії цієї функції 14.08.2026.
    # Перевірки нижче суто рядкові й до словника не застосовні: порожнечу
    # окремих частин усе одно ловить normalize_date.
    if not isinstance(raw, str):
        return raw, "matched"
    text = raw
    # `not_issued_sentinel` мусить пройти: "документ прямо каже, що ВПД не
    # видавались" (підтверджено-порожнє) -- це не те саме, що "не вдалося
    # прочитати" (прогалина), і різниця має дожити до нормалізації.
    if not text.strip() or is_placeholder(text, field_placeholder_tokens(field)):
        return None, "blank_value"
    if is_printed_form_text(text, printed):
        return None, "printed_form_text"
    return text, "matched"


_WORD_RE = re.compile(r"\S+")


def _lexeme_key(phrase: str) -> str:
    """Лема фрази в нижньому регістрі -- ключ, ОДНАКОВИЙ для всіх словоформ
    ("звільнений" / "звільнена" / "звільнені" -> "звільнений";
    "відрядженому до" / "відрядженій до" -> "відряджений до").

    Без морфології (pymorphy3 недоступний -- lemmatize_phrase повертає None)
    ключем стає сам текст, тобто порівняння деградує до літерального, як було
    до цієї зміни. Це свідома деградація, а не тихий збій: гірший результат
    той самий, що й раніше, і його видно через `no_morphology` в provenance
    полів ПІБ того ж документа."""
    text = normalize_ws(phrase).lower()
    return (lemmatize_phrase(text) or text).strip()


def prefix_match_length(text, prefix):
    """Довжина початкового фрагмента `text`, який є `prefix` -- або ТОЧНИМ
    літералом, або ІНШОЮ СЛОВОФОРМОЮ того самого виразу. None, якщо `text` з
    префікса не починається.

    Навіщо словоформи: `strip_prefix` у схемі -- це ОДНА форма, а бланк друкує
    форму за статтю військовослужбовця. `schemas/leave_ticket.yaml:84` оголошує
    "звільнений", а LEAVE-001 (жінка) має надруковане "звільнена"
    (`надруковано.RELEASED`), тому чисто літеральне зрізання лишало рід у
    значенні основного факту: `підстава` = "звільнена щорічна основна
    відпустка за 2026 рік" замість "щорічна основна відпустка за 2026 рік".
    Це і була єдина помилка корпусу leave/pdf (1 з 176). Клас той самий у
    посвідченні про відрядження: "відрядженому до" (чол.) проти "відрядженій
    до" (жін.) перед лейблом "(пункти призначень)".

    Довжина, а не сам рядок: зрізати треба СТІЛЬКИ, скільки фізично займає
    форма в документі, а не len(prefix) зі схеми -- "звільнена" на символ
    коротша за "звільнений", і арифметика по схемному літералу з'їла б першу
    літеру значення.

    Кількість токенів беремо з ПРЕФІКСА: порівнюється рівно стільки перших
    слів тексту, скільки їх у схемному літералі, тому багатослівний префікс
    не може випадково захопити початок значення."""
    if not text or not prefix:
        return None
    if text.lower().startswith(prefix.lower()):
        return len(prefix)
    token_count = len(prefix.split())
    if not token_count:
        return None
    words = []
    for m in _WORD_RE.finditer(text):
        words.append(m)
        if len(words) == token_count:
            break
    if len(words) < token_count:
        return None
    end = words[-1].end()
    if _lexeme_key(text[:end]) == _lexeme_key(prefix):
        return end
    return None


def anchor_in_line(line, anchor) -> bool:
    """Чи стоїть `anchor` у цьому рядку -- літерально або іншою словоформою.

    Той самий матчер, що й у prefix_match_length, тільки не з початку рядка:
    `_extend_to_anchor` шукає якір у рядках НАЗАД, і він мусив знаходити ті
    самі форми, які потім зріже strip_literal_prefix. Поки ці дві перевірки
    розходились, документ із якорем в іншому роді або не набирав початок
    значення взагалі, або набирав його й не міг зрізати."""
    if not line or not anchor:
        return False
    if phrase_in_text(line.lower(), anchor.lower()):
        return True
    return any(prefix_match_length(line[m.start():], anchor) is not None
               for m in _WORD_RE.finditer(line))


def strip_literal_prefix(text, prefix):
    """Знімає префікс-рядок, якщо він є на початку (регістр ігнорується, інша
    словоформа того самого виразу приймається -- див. prefix_match_length).
    НЕ str.lstrip(prefix) -- lstrip прибирає будь-які символи з НАБОРУ
    символів префікса, а не сам рядок."""
    if not text or not prefix:
        return text
    stripped = text.strip()
    matched = prefix_match_length(stripped, prefix)
    if matched is None:
        return text
    return stripped[matched:].strip()


def _find_rank_run(tokens, rank_alias_lookup):
    """(значення_звання, індекс_початку, індекс_кінця) -- НАЙЛІВІША позиція, з
    якої починається відомий рядок звання, і на ній -- найдовший збіг.
    (None, 0, 0), якщо звання немає ніде.

    Чому не лише префікс (як було): звання шукалось виключно з ТОКЕНА 0, тоді
    як прізвище шукалось СКАНУВАННЯМ по всіх токенах. Ця асиметрія і давала
    заміряний провал `звання` = 0/16 на leave-pdf і 0/14 на trip-pdf: у PDF
    рядок звання+ПІБ приходить у кандидаті разом із сусіднім рядком бланка
    ("№ 102    від 09.05.2026\\nрядовий ЛЕМЕШКО Соломія Романівна"), тож
    токен 0 -- це "№", і префіксний пошук не знаходив звання ніколи, хоча
    ПІБ (скануванням) знаходився нормально.

    Скан ЛІВОРУЧ-ПРАВОРУЧ, а не "найближче до прізвища": у бланку ЗСУ
    порядок завжди "звання ПРІЗВИЩЕ Ім'я По-батькові", і коли токен 0 таки є
    званням (весь шлях docx), найлівіша позиція -- це і є 0, тобто поведінка
    на docx лишається побайтово тією самою."""
    for start in range(len(tokens)):
        for end in range(len(tokens), start, -1):
            # lookup_alias, а не пряме `in`: у документі звання стоїть у тому
            # відмінку, якого вимагає речення бланка ("Видано старшому
            # сержанту"), а довідник містить називний. Точний збіг через це не
            # знаходив навіть "підполковника" -- перевірено.
            hit = lookup_alias(" ".join(tokens[start:end]), rank_alias_lookup)
            if hit is not None:
                return hit, start, end
    return None, 0, 0


def parse_rank_and_name(raw_line, rank_alias_lookup):
    """Токенізація замість одного regex на все: найдовший рядок токенів, що є
    відомим званням, визначає межу; токени ПІСЛЯ нього -- прізвище (ВЕЛИКІ
    ЛІТЕРИ) / ім'я / по батькові за регістром.

    Якщо жоден токен не у ВЕЛИКОМУ регістрі -- повертає всі три поля як
    None, а НЕ "решту токенів за позицією": позиційний фолбек тут давав
    ЗСУНУТІ (не порожні, а тихо неправильні) given_name/patronymic, які
    виглядали як успішний розбір, тому LLM-фолбек для них ніколи не
    спрацьовував (підтверджено тестом). rank при цьому лишається -- його
    визначення не залежить від регістру прізвища.

    Прізвище шукається лише СЕРЕД ТОКЕНІВ ПІСЛЯ ЗВАННЯ (коли звання знайдене),
    а не з початку рядка. Це другий бік тієї самої асиметрії, описаної в
    _find_rank_run, і він теж заміряний: TRIP-012.pdf має гомогліфи в номері
    документа ("№ 25О    від О7.О5.2О2б"), а токен '25О' проходить
    `str.isupper()` -- кирилична "О" є літерою у ВЕЛИКОМУ регістрі. Тому
    прізвищем ставало '25О', ім'ям -- 'від', по батькові -- 'О7.О5.2О2б', і
    все це з провенансом `matched`. Відлік від знайденого звання прибирає
    цілий клас таких збігів: до звання ПІБ бути не може за побудовою бланка.
    """
    if not raw_line or is_placeholder(raw_line):
        return None, {"surname": None, "given_name": None, "patronymic": None}
    tokens = raw_line.split()
    rank_value, _rank_start, rank_end = _find_rank_run(tokens, rank_alias_lookup)
    rank_result = {"code": rank_value[0], "label": rank_value[1]} if rank_value else None
    name_tokens = tokens[rank_end:]
    surname_index = next((k for k, t in enumerate(name_tokens)
                          if t.isupper() and len(t) > 1), None)
    if surname_index is None:
        return rank_result, {"surname": None, "given_name": None, "patronymic": None}

    # Ім'я та по батькові беруться ЛИШЕ з токенів ПІСЛЯ прізвища. Раніше
    # бралася "решта токенів" з обох боків, і будь-який неспожитий токен
    # ЛІВОРУЧ від прізвища зсував поля: звання, відсутнє в довіднику
    # ("старшина ІВАНЕНКО Іван Іванович" -> given_name='старшина',
    # patronymic='Іван'), скорочення поза aliases ("мол. с-т"), або залишок
    # префікса ("Видано:" -> given_name='Видано:'). Підтверджено тестом.
    # У бланках ЗСУ порядок завжди "звання ПРІЗВИЩЕ Ім'я По-батькові", тож
    # усе ліворуч від прізвища -- це звання або сміття, не частина ПІБ.
    after = name_tokens[surname_index + 1:]
    leftover_before = name_tokens[:surname_index]
    return rank_result, {
        "surname": name_tokens[surname_index],
        "given_name": after[0] if after else None,
        "patronymic": after[1] if len(after) > 1 else None,
        # Неспожиті токени ліворуч -- сигнал, що звання не розпізнане або
        # префікс знято неповністю. Значення полів при цьому правильні, але
        # rank, найпевніше, втрачений -- і це має бути видно.
        "_leftover_before_surname": leftover_before or None,
        # Симетричний сигнал ПРАВОРУЧ (R-B1-02): 4-й і подальші токени ПІБ
        # раніше не читались ніде, і «Мустафа кизи» ставало «Мустафа» без
        # жодної різниці у виході -- документ виходив confirmed з чужою
        # ідентичністю особи. Хвіст тепер видно, а розріз after[0]/after[1]
        # при ньому не вважається надійним (див. extract_document).
        "_leftover_after_patronymic": after[2:] or None,
    }


# Роль поля в розборі рядка "звання ПІБ". Перелік ЗАКРИТИЙ навмисно, і це не
# недоробка: до кожної ролі прив'язана морфологічна граммема
# (normalize._ROLE_GRAMMEME), яка й не дає відмінити прізвище як звичайний
# іменник. Якби схема могла оголосити довільну роль, розбір втратив би
# обмежувач і повернувся баг "ПЕТРОВА -> ПЕТРОВ зі статусом normalized" --
# найдорожча тиха помилка в системі, бо в базу йде ІНША людина з виглядом
# успіху. Вільними стають ІМЕНА полів, не роль.
NAME_PART_ROLES = ("rank", "surname", "given_name", "patronymic")
DEFAULT_NAME_GROUP = "__subject__"


def field_part(field: dict) -> str:
    """Роль поля: `part:` зі схеми, інакше саме ім'я поля.

    Фолбек на ім'я лишається свідомо -- дві наявні схеми називають поля
    рівно `rank`/`surname`/`given_name`/`patronymic`, і змушувати їх дописати
    `part:` заради того самого значення означало б зламати їх без користі.
    """
    return field.get("part") or field.get("name")


def name_group_key(field: dict) -> str:
    """До якої ОСОБИ належить поле. Один документ може описувати кількох
    (заявник і командир, що затверджує -- обидва є в наявних бланках), і без
    цього ключа розбір другої особи брав значення першої."""
    return field.get("group") or DEFAULT_NAME_GROUP


def primary_name_group(schema: dict) -> str:
    """Група ОСНОВНОЇ особи документа -- та, чиє поле стоїть у схемі першим.

    Порядок, а не спеціальна назва: якщо схема оголошує групи явно
    (`group: applicant`, `group: commander`), жодна з них не називається
    "__subject__", і перевірка на літерал лишала subject порожнім -- тобто
    основна особа взагалі не доходила до БД. Перше поле = основний суб'єкт,
    решта = додаткові.
    """
    for field in schema.get("fields") or []:
        if field.get("extraction") == "rank_and_name_tokenized":
            return name_group_key(field)
    return DEFAULT_NAME_GROUP


def resolve_name_groups(schema, grouped_blocks, denylist, dictionaries, printed=(),
                        order=None):
    """{group: (rank_result, name_parts, raw_line, label_reason)} -- по одному
    розбору на ОСОБУ, не один на документ.

    Було: єдиний кеш на весь документ, не ключований нічим. Схема з двома
    людьми віддала б у поля командира ПІБ заявника -- не null, а тихо чуже
    значення з провенансом `matched`, і навіть підказка для LLM була б від
    чужого лейбла. Плюс лейбл читався як field["label_before"] з ПЕРШОГО
    такого поля: варто було переставити поля в YAML місцями, і генеричний
    двигун кидав KeyError.
    """
    groups = {}
    oversized_chars = schema_extraction_limit(
        schema, "oversized_candidate_chars", OVERSIZED_CANDIDATE_CHARS)
    for field in schema["fields"]:
        if field.get("extraction") != "rank_and_name_tokenized":
            continue
        groups.setdefault(name_group_key(field), []).append(field)

    resolved = {}
    for group, fields in groups.items():
        # Лейбл несе будь-яке поле групи -- зазвичай те, що описує звання.
        label = next((f["label_before"] for f in fields if f.get("label_before")), None)
        strip = next((f["strip_prefix"] for f in fields if f.get("strip_prefix")), None)
        # Довідник звань -- з поля цієї групи, що має роль rank; .get, а не
        # ["category"], бо схема може оголосити звання не категоріальним.
        rank_field = next((f for f in fields if field_part(f) == "rank"), None)
        rank_lookup = dictionaries.get((rank_field or {}).get("category"), {})

        if not label:
            resolved[group] = (None, {"surname": None, "given_name": None,
                                      "patronymic": None}, None, "no_label")
            continue
        raw_line, label_reason = find_block_before_label(grouped_blocks, label,
                                                         denylist, anchor=strip,
                                                         printed=printed, order=order,
                                                         oversized_chars=oversized_chars)
        if raw_line and strip:
            raw_line = strip_literal_prefix(raw_line, strip)
        rank_result, name_parts = parse_rank_and_name(raw_line, rank_lookup)
        resolved[group] = (rank_result, name_parts, raw_line, label_reason)
    return resolved


def _compile_variants(field_def):
    """(скомпільований_патерн, чи_розширений) для кожного варіанта.

    `\\d` у схемному патерні розширюється до "цифра АБО її гомогліф"
    (homoglyph_tolerant_pattern). Причина -- виміряна: дефект, записаний у
    наборі як `ocr_noise`, насправді ГОМОГЛІФИ, вписані в сам документ
    (кирилична "О" замість 0, "б" замість 6, "З" замість 3, "І" замість 1) --
    ті самі літери є в текстовому шарі .docx, де розпізнавання не
    відбувається взагалі. Тому патерн, який вимагає справжніх цифр, не
    збігається: TRIP-012 має "№ 25О    від О7.О5.2О2б", і
    `\\s+від\\s+\\d{1,2}\\.\\d{1,2}\\.\\d{4}` не матчиться -- разом із
    номером документа втрачалась і дата видачі.

    `\\d` -- це вже декларація автора схеми "тут стоїть число", тож
    розширювати саме її безпечно; схеми лишаються читабельними, а список
    гомогліфів не дублюється в десятку місць."""
    out = []
    for v in field_def.get("regex_variants", []):
        expanded_pattern, was_expanded = homoglyph_tolerant_pattern(v["pattern"])
        out.append((re.compile(expanded_pattern), was_expanded))
    return out


def extract_field_regex(field_def, text: str):
    """Пробує всі відомі варіанти по черзі. Групи стандартизовані за типом
    поля: date -> (day, month, year); інші -> (value).

    Захоплене значення проганяється через `fix_declared_numeric` ЛИШЕ якщо
    патерн справді був розширений (`was_expanded`). Якщо `\\d` у патерні не
    було, автор схеми не оголошував це число -- і перетворювати літери на
    цифри в захопленому тексті не можна (напр. вид відпустки чи мета
    відрядження -- вільний текст, де "б" має лишитись "б")."""
    for pattern, was_expanded in _compile_variants(field_def):
        m = pattern.search(text)
        if m:
            groups = m.groupdict()
            fix = fix_declared_numeric if was_expanded else (lambda x: x)
            if field_def.get("type") == "date":
                return {"day": fix(groups.get("day")),
                        "month": fix(groups.get("month")),
                        "year": fix(groups.get("year"))}, "matched"
            return fix(groups.get("value")), "matched"
    return None, "no_value"


# --- Заземлення значення, згенерованого моделлю --------------------------
#
# Найдорожчий заміряний випадок (LEAVE-011): модель віддала `днів = 17`, хоча
# підрядка "17" у документі немає взагалі (1255 символів), а поле на бланку
# порожнє. `початок`/`кінець`/`повернення` модель чесно лишила None, і вони
# пішли в прогалини -- а вигаданий `днів` НЕ пішов, бо значення є, тип
# сходиться, і жодна перевірка не питала, чи воно взагалі з ЦЬОГО документа.
#
# Витяг -- це вибір фрагмента документа, не генерація. Тому значення, якого в
# документі немає, -- не значення, а здогадка, і місце йому в прогалинах.
# Перевіряються лише типи, де "є в документі" визначається однозначно:
# - number: число мусить бути в документі ЦИФРОЮ або ПРОПИСОМ (на бланку
#   відпускного кількість днів надрукована ЛИШЕ прописом -- "тринадцять", --
#   тому підрядковий пошук "13" тут дав би хибне відхилення);
# - text / object_ref: значення мусить бути підрядком документа після
#   зведення пробілів.
# НЕ перевіряються:
# - category: grammar обмежує вивід КОДОМ довідника ("soldier"), якого в
#   українському тексті документа не буває за побудовою;
# - date: модель повертає {day,month,year} окремими частинами, і місяць
#   буває і словом, і числом -- перевірка тут або тавтологічна, або хибна.
#   Дати натомість закриті перевіркою узгодженості в build_record.
GROUNDED_TYPES = ("number", "text", "object_ref")

_INT_RE = re.compile(r"\d+")


def attested_numbers(text: str) -> set:
    """Числа, ЯВНО присутні в документі -- цифрами або українським прописом
    (включно зі складеними: "двадцять сім"). Використовується, щоб відрізнити
    прочитане число від вигаданого."""
    found = set()
    if not text:
        return found
    normalized = fix_numeric_homoglyphs(normalize_ws(text))
    for m in _INT_RE.finditer(normalized):
        found.add(int(m.group()))
    tokens = re.split(r"[^\w'’ʼ-]+", normalized.lower())
    for k, token in enumerate(tokens):
        first = number_word_value(token)
        if first is None:
            continue
        found.add(first)
        second = number_word_value(tokens[k + 1]) if k + 1 < len(tokens) else None
        if second is not None:
            found.add(first + second)
    return found


def ground_llm_value(field: dict, value, document_text: str, printed=()):
    """(значення, причина) для значення, отриманого від моделі.

    None + `ungrounded_llm_value` означає "в документі цього немає" -- поле
    лишається прогалиною, і це видно, замість тихого правдоподібного числа.
    Значення не губиться: причина йде в provenance, а сире значення --
    в unresolved_values (build_record).

    `printed` перевіряється ОКРЕМО й ПЕРШИМ, бо заземлення тут безсиле за
    побудовою: друкований текст У ДОКУМЕНТІ Є, тобто підрядковий пошук його
    підтверджує. На порожньому бланку посвідчення модель саме так і віддала
    `document_number` = "Додаток 28" -- заміряно 14.08.2026.
    """
    if value is not None and is_printed_form_text(value, printed):
        return None, "printed_form_text"
    if value is None or field.get("type") not in GROUNDED_TYPES:
        return value, None
    if field.get("type") == "number":
        number = number_from_words(value, min_value=field.get("min_value"),
                                   max_value=field.get("max_value"))
        if number is None:
            return None, "ungrounded_llm_value"
        return (value, None) if number in attested_numbers(document_text) \
            else (None, "ungrounded_llm_value")
    text = normalize_ws(str(value)).lower()
    if not text:
        return value, None
    return (value, None) if text in normalize_ws(document_text).lower() \
        else (None, "ungrounded_llm_value")


# --- Режими БЕЗ позитивної опори на друкований підпис поля ---------------
#
# Уся конструкція `blank_form.py` стоїть на ТОЧНОМУ тексті нашого бланка. Якщо
# документ -- інша РЕДАКЦІЯ форми (ті самі поля, перефразовані друковані
# рядки), обидва її механізми мовчки перестають працювати: різак меж полів
# ріже не туди, а негативна перевірка `is_printed_form_text` не відхиляє
# нічого, бо НАШИХ рядків у документі немає.
#
# Для полів із лейблом страховка від цього вже є, і вона позитивна: лейбл --
# це друкований рядок бланка, тож інша редакція дає `no_label` (або
# `ambiguous_label`), поле стає прогалиною й іде в LLM. Перевірено:
# `block_before_label` і `rank_and_name_tokenized` обидва проходять через
# `find_block_before_label`, яка без знайденого лейбла повертає рівно
# `(None, "no_label")`.
#
# Режими нижче такої опори НЕ мають ЖОДНОЇ:
#   * `regex` -- частина патернів схеми чисто формова, без жодного слова
#     бланка ('№\\s*(?P<value>[\\w/\\-]+)\\s+від\\s+\\d{1,2}\\...' у
#     `document_number`, 'з "DD" month YYYY' у датах). У чужій редакції такий
#     патерн збігається з ПЕРШИМ, що схоже за формою -- напр. із номером
#     ЗГАДАНОГО документа замість номера цього;
#   * `rank_and_name_tokenized` -- лейбл у нього є, але сам РОЗБІР рядка
#     ("найдовший префікс токенів, що є званням; далі ВЕЛИКИМИ -- прізвище")
#     від бланка не залежить узагалі, тож на рядку, який лейбл підібрав не з
#     того місця, він однаково віддає правдоподібне ПІБ.
#
# Обидва віддають значення з провенансом `matched`, і документ через це міг
# стати `confirmed` -- тобто тихо підтверджена вигадка. Коли форма НЕ впізнана
# (`form_recognized=False`, вердикт приходить готовим з `identify_template`),
# значення цих режимів не приймаються на віру: поле йде в LLM на перевірку, а
# сам детермінований результат зберігається як відкат і носить провенанс
# `unverified_foreign_edition`, який видно в рев'ю.
UNANCHORED_MODES = ("regex", "rank_and_name_tokenized")

#: Провенанс значення, яке детермінований шлях знайшов, але підтвердити
#: нічим: бланк не впізнаний, а режим позитивної опори не має. Значення НЕ
#: викидається (правило "не губимо дані"), лише перестає виглядати як
#: `matched`.
UNVERIFIED_METHOD = "unverified_foreign_edition"

#: Провенанс поля, чий слот на бланку ДОВЕДЕНО порожній детермінованим
#: сигналом (R2-П5-А, docs/known-weak-spots.md розд. 9 розд. 5.5).
#: Після двокрапки -- сам сигнал: blank_value (у слоті placeholder),
#: printed_form_text (кандидат цілком з друкованих рядків бланка),
#: printed_hint (підказка локалізованої прогалини -- друкований рядок
#: бланка, вписаного значення немає), empty_pattern (схемний доказ, П5-Б).
#:
#: Таке поле НЕ йде в LLM-фолбек, і це не економія навмання: модель бачить
#: ТОЙ САМИЙ OCR-текст, у якому значення немає, а заземлення відкидає все,
#: чого в тексті немає, -- тобто єдина «легальна» відповідь моделі тут null
#: (заміряно: 12B віддала null у 8/8 полів LEAVE-011, її єдина вигадка
#: відкинута заземленням). Скіп ще й БЛОКУЄ клас помилки: категоріальні
#: поля заземленню не підлягають за побудовою (GROUNDED_TYPES без category),
#: і вигадане звання в порожній ПІБ-групі пройшло б у результат.
#:
#: Поле при цьому ЛИШАЄТЬСЯ невирішеним (unknown_fields /
#: unknown_critical_fields у build_record -- як і коли LLM чесно віддавала

#: Ключ схеми: регекс (або список регексів) ПОРОЖНЬОГО СЛОТА цього поля --
#: друкований скелет бланка на місці, де мало б стояти вписане значення
#: (R2-П5-Б, known-weak-spots.md розд. 9 розд. 5.5).
#:
#: Навіщо окремий ключ, а не сигнали П5-А: порожній слот дати в наших
#: документах виглядає як `з “” 20 р.` (порожні лапки) або `з “____”
#: ________ 20___ р.` (підкреслення на бланку) -- це НЕ placeholder у
#: розумінні `_BLANK_FILL_RE` і НЕ літеральний збіг із друкованим рядком,
#: тому жоден сигнал П5-А його не доводить. Заміряно: група «днів + 3 дати»
#: LEAVE-011 коштувала 89-198 с LLM і повертала null у 3 з 4 полів (четверте
#: -- вигадка `duration_days=17`, відкинута заземленням).
#:
#: Знання про форму живе в YAML, не в .py (правило 2 плану покращення):
#: код знає лише «є оголошений скелет порожнечі -- перевір його», а як саме
#: виглядає порожній слот конкретного бланка, оголошує схема.
#:
#: Патерн пишеться так, щоб збігатися ЛИШЕ з порожнім слотом: `_*` між
#: лапками не матчить вписану цифру, тому заповнений документ під нього не
#: підпадає. Валідатор схем (`validate_schema`) вимагає, щоб кожен патерн
#: справді збігався з оголошеним `blank_template:` -- скелет порожнечі
#: ІСНУЄ в порожньому бланку за визначенням, і патерн, який його не бачить,
#: мовчки не діяв би ніколи.
EMPTY_PATTERN_KEY = "empty_pattern"


def empty_slot_patterns(field_def):
    """Скомпільовані патерни порожнього слота поля (порожній список, якщо ключ
    не оголошено). Рядок і список рядків обидва допустимі -- у схемах уже є та
    сама вільність (`title_phrases`), а вимагати список з одного елемента
    означало б шум у YAML."""
    declared = field_def.get(EMPTY_PATTERN_KEY)
    if not declared:
        return []
    if isinstance(declared, str):
        declared = [declared]
    out = []
    for pattern in declared:
        # Та сама толерантність до гомогліфів, що в regex_variants: `\d` у
        # схемному патерні -> "цифра або її гомогліф". Інакше на документі з
        # гомогліфами (TRIP-012) скелет порожнечі не збігся б -- це не
        # небезпечно (поле просто пішло б у LLM), але й не безкоштовно.
        expanded, _was_expanded = homoglyph_tolerant_pattern(pattern)
        out.append(re.compile(expanded))
    return out


def slot_is_provably_empty(field_def, text: str) -> bool:
    """Чи стоїть у документі друкований скелет ПОРОЖНЬОГО слота цього поля."""
    return any(p.search(text) for p in empty_slot_patterns(field_def))


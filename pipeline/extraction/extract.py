def extract_document(schema: dict, ocr_text: str, ocr_blocks: list, dictionaries: dict,
                      llm_extract_batch=None, title_phrases=None,
                      batch_size=4, self_consistency_n=1, form_recognized=True):
    """Повертає {field_name: (сире_значення, reason)}.
    reason: matched | llm | no_value | derived | llm_error:<Тип> |
            unverified_foreign_edition.

    form_recognized -- ГОТОВИЙ вердикт `identify_template`
    (`ident["blank_edition"]["recognized"]`), не власний підрахунок: див.
    UNANCHORED_MODES і коментар до DEFAULT_MIN_BLANK_COVERAGE в
    identification.py. `True` за замовчуванням, щоб викликач, який сигналу не
    має (тест, скрипт), отримував рівно попередню поведінку.

    dictionaries: {category: alias_lookup} -- ПОВНИЙ набір довідників (не
    лише rank), бо build_json_schema_for_fields потребує їх для enum-ів
    категоріальних полів у LLM-групах.

    llm_extract_batch(field_defs, context_text, json_schema) -> {ім'я: значення}
    -- один виклик на ГРУПУ полів. Кожна група у власному try/except: збій
    однієї групи позначає лише ЇЇ поля як llm_error, не чіпає інші групи й
    не втрачає вже отримані детерміновані значення.
    """
    # ВІДНОВЛЕННЯ МЕЖ ПОЛІВ -- ПЕРШИМ, до всього іншого (A3, blank_form.py).
    # Surya віддає області зображення, а не абзаци, тому друковані лейбли
    # бланка приходять склеєними зі значеннями в один рядок. Різання по
    # відомому тексту порожнього бланка повертає ту саму послідовність
    # "лейбл / значення", яку docx має з абзаців, -- і далі весь двигун
    # працює без жодної зміни.
    #
    # `ocr_text` перебудовується ЛИШЕ якщо різання щось змінило, і це не
    # оптимізація: схемні regex-и прив'язані до пробілів між словами
    # ("терміном\\s+на\\s+"), тож без перебудови `днів` лишався б зламаним на
    # тих самих документах, де блоки вже виправлені. Коли різати нічого, текст
    # лишається ТИМ САМИМ рядком, тобто docx/PDF не зачеплені взагалі.
    ocr_blocks, resegmented = resegment_by_blank(ocr_blocks, schema)
    if resegmented:
        ocr_text = "\n".join(_raw_block_text(b) for b in ocr_blocks)

    grouped_blocks = group_blocks_into_lines(ocr_blocks)
    flat_blocks = flatten_blocks(ocr_blocks)
    denylist = {p.strip().lower() for p in (title_phrases or [])}
    label_heads = schema_label_heads(schema)
    # Друковані рядки ПОРОЖНЬОГО бланка цієї форми. Порожній frozenset, якщо
    # схема не оголосила `blank_template:` -- тоді всі перевірки нижче
    # інертні, тобто новий бланк без шаблону поводиться точно як раніше.
    printed = printed_lines(schema)
    # Порядок друкованих рядків бланка -- окремо від їх множини: множина
    # відповідає на "чи це друкований текст", порядок -- на "де він стоїть
    # відносно лейбла" (див. find_block_before_label / printed_after_label).
    blank_order = printed_order(schema)
    fields_by_name = {f["name"]: f for f in schema["fields"]}
    # Межа «кандидат завеликий для значення поля» -- дефолт коду або
    # перевизначення цієї схеми (R-A1-08).
    oversized_chars = schema_extraction_limit(
        schema, "oversized_candidate_chars", OVERSIZED_CANDIDATE_CHARS)
    results = {}
    localized_gaps, global_gaps, hints = [], [], {}

    # Розбір "звання ПІБ" -- один на ОСОБУ, до головного циклу. Раніше це був
    # один лінивий кеш на весь документ (див. resolve_name_groups).
    name_groups = resolve_name_groups(schema, grouped_blocks, denylist, dictionaries,
                                      printed, blank_order)

    for field in schema["fields"]:
        name = field["name"]
        mode = field.get("extraction")

        if mode == "rank_and_name_tokenized":
            # part, а не ім'я поля: схема може називати поля як завгодно
            # (applicant_surname, commander_rank) -- роль оголошується явно.
            part = field_part(field)
            rank_result, name_parts, rank_raw_line, rank_label_reason = \
                name_groups[name_group_key(field)]
            value = rank_result if part == "rank" else name_parts.get(part)
            if (part == "patronymic" and value
                    and name_parts.get("_leftover_after_patronymic")):
                # Після по батькові лишилися токени («Мустафа кизи») --
                # позиційний розріз ненадійний, і віддати after[1] мовчки
                # означало б чужу ідентичність особи зі статусом confirmed
                # (R-B1-02). Поле не вирішується, повний хвіст іде в reason
                # (рев'юер бачить, ЩО саме стояло в документі), рядок -- у
                # підказку LLM, як і для звання поза довідником.
                tail = " ".join([value] + name_parts["_leftover_after_patronymic"])
                results[name] = (None, f"{NAME_TAIL_METHOD}:{tail}")
                hints[name] = rank_raw_line or ""
                localized_gaps.append(name)
            elif value:
                results[name] = (value, "matched")
            elif part == "rank" and name_parts.get("_leftover_before_surname"):
                # Прізвище знайдене, але ліворуч від нього лишились неспожиті
                # токени -- значить там звання, якого немає в довіднику
                # (або скорочення поза aliases). Це інша причина, ніж
                # "рядка не знайдено", і вона підказує, що саме дописати.
                leftover = " ".join(name_parts["_leftover_before_surname"])
                results[name] = (None, f"rank_not_in_dictionary:{leftover}")
                hints[name] = rank_raw_line or ""
                localized_gaps.append(name)
            elif rank_raw_line and is_printed_form_text(rank_raw_line, printed):
                # Локалізована прогалина, чия підказка -- ДРУКОВАНИЙ рядок
                # бланка: лейбл знайдено, «значенням» перед ним стоїть сам
                # бланк, тобто вписаного значення немає (заміряний випадок --
                # порожня ПІБ-група LEAVE-011: підказкою був рядок «Відмітка
                # про постановку на облік...», і 12B чесно віддавала null за
                # 98-372 с). Третій сигнал П5-А: модель не питаємо.
                results[name] = (None, f"{CONFIRMED_EMPTY_SLOT_METHOD}:printed_hint")
            else:
                results[name] = (None, rank_label_reason if rank_label_reason != "matched" else "no_value")
                # рядок знайдено, не вдався лише розбір -> локалізована прогалина
                if rank_raw_line:
                    hints[name] = rank_raw_line
                    localized_gaps.append(name)
                else:
                    global_gaps.append(name)

        elif mode == "block_before_label":
            raw, label_reason = find_block_before_label(
                grouped_blocks, field["label_before"], denylist,
                anchor=field.get("strip_prefix"),
                boundaries=compile_value_boundaries(field), printed=printed,
                order=blank_order, oversized_chars=oversized_chars)
            if raw is not None and field.get("strip_prefix"):
                raw = strip_literal_prefix(raw, field["strip_prefix"])
            if raw is None:
                # Місце не локалізоване -- лейбл відсутній / неоднозначний /
                # кандидат відхилений denylist-ом / мега-блок чи аномально
                # довгий кандидат (`oversized_block_suspect`, коли
                # детермінований "сендвіч"-парсер у find_block_before_label
                # теж відмовився). Підказку не даємо НАВМИСНО в усіх цих
                # випадках: обрізана "підказка" сама вгадувала б межу поля
                # іншим способом і так само помилялась би (виміряно
                # емпірично -- research-round-2026-08-12.md, варіант A:
                # повний текст документа відновив 5 з 7 полів мега-блоку,
                # обрізана підказка -- 1 з 5). Причина зберігається в
                # provenance, щоб "лейбл неоднозначний" не виглядало як
                # "поля просто немає".
                results[name] = (None, label_reason)
                global_gaps.append(name)
            else:
                # "matched" від верстки бланка більше НЕ приймається
                # беззастережно: див. validate_block_value. Відхилений
                # кандидат іде в global_gaps, тобто отримує той самий другий
                # шанс через LLM, що й поле, для якого лейбл не знайшовся --
                # і з тієї самої причини не отримує підказки (відхилений
                # кандидат -- це якраз НЕПРАВИЛЬНИЙ текст).
                value, value_reason = validate_block_value(
                    field, raw, label_heads, printed)
                if value is None and value_reason in PROVEN_EMPTY_REASONS:
                    # Слот знайдено, у ньому -- сам бланк: відповідь відома
                    # детерміновано, модель не питаємо (див.
                    # CONFIRMED_EMPTY_SLOT_METHOD).
                    results[name] = (None,
                                     f"{CONFIRMED_EMPTY_SLOT_METHOD}:{value_reason}")
                else:
                    results[name] = (value, value_reason)
                    if value is None:
                        global_gaps.append(name)

        elif mode == "regex":
            value, reason = extract_field_regex(field, ocr_text)
            if value is not None:
                value, reason = validate_regex_value(field, value, printed)
            if value is None and reason in PROVEN_EMPTY_REASONS:
                # Патерн зматчив сам порожній слот / друкований рядок форми --
                # доведено-порожньо, фолбек не потрібен (те саме правило, що
                # для block_before_label вище).
                results[name] = (None, f"{CONFIRMED_EMPTY_SLOT_METHOD}:{reason}")
                continue
            results[name] = (value, reason)
            if value is None and field.get("llm_fallback") is not False:
                # Regex -- найкрихкіший режим (паттерн пишеться під конкретну
                # верстку бланка), тож саме він найбільше потребує фолбеку.
                # Раніше regex-поля в прогалини не додавались узагалі --
                # найкрихкіший шлях був єдиним без страховки.
                #
                # `llm_fallback: false` -- свідома відмова від фолбеку для поля,
                # ВІДСУТНІСТЬ якого є нормою (позначка скасування документа:
                # 58 з 60 документів набору її не мають). Питати модель про таке
                # поле означає просити вигадати значення, а не прочитати його.
                global_gaps.append(name)

        elif mode == "derived_from":
            # обробляється в build_record-етапі, тут лише позначка
            results[name] = (None, "derived")

        elif mode == "llm":
            results[name] = (None, "no_value")
            global_gaps.append(name)

        else:
            results[name] = (None, "no_value")

    # СХЕМНИЙ ДОКАЗ ПОРОЖНЕЧІ (П5-Б). Один прохід ПІСЛЯ головного циклу, а не
    # гілка в кожному режимі -- з тієї самої причини, що й прохід `unverified`
    # нижче: правило тут ОДНЕ («оголошений скелет порожнечі стоїть у тексті ->
    # питати модель нема про що»), і розписане по трьох режимах воно розійшлося
    # б при наступній зміні будь-якого з них. Заміряна користь саме від
    # мода-агностичності: у групі «днів + 3 дати» LEAVE-011 три поля -- regex,
    # а `actual_return_date` -- block_before_label, і без цього проходу
    # четверте поле тягнуло б виклик моделі за собою.
    #
    # Умова `value is None` обов'язкова: скелет порожнечі й вписане значення
    # можуть стояти в документі одночасно (двосторінковий бланк, друга
    # незаповнена копія полів) -- знайдене значення важливіше за доказ
    # порожнечі, інакше правка ЗАБИРАЛА Б дані.
    for field in schema["fields"]:
        name = field["name"]
        if not field.get(EMPTY_PATTERN_KEY):
            continue
        value, reason = results.get(name, (None, "no_value"))
        if value is not None or (reason or "").startswith(
                CONFIRMED_EMPTY_SLOT_METHOD):
            continue
        if not slot_is_provably_empty(field, ocr_text):
            continue
        results[name] = (None, f"{CONFIRMED_EMPTY_SLOT_METHOD}:empty_pattern")
        # З прогалин ПРИБИРАЄМО: сюди поле потрапило зі свого режиму до того,
        # як доказ порожнечі був перевірений.
        if name in localized_gaps:
            localized_gaps.remove(name)
        if name in global_gaps:
            global_gaps.remove(name)
        hints.pop(name, None)

    # ФОРМА НЕ ВПІЗНАНА -> значення режимів без опори перестають бути `matched`.
    # Один прохід ПІСЛЯ головного циклу, а не гілка в кожному режимі: правило
    # тут одне («опори немає -> на віру не беремо»), і розписане по трьох
    # місцях воно розійшлося б при наступній зміні будь-якого з них.
    #
    # `unverified` -- відкат, а не дубль: якщо LLM не віддасть нічого (або її
    # значення не заземлиться), поле повертає детермінований результат із
    # провенансом UNVERIFIED_METHOD. Без цього перевірка ПЕРЕТВОРЮВАЛАСЬ БИ на
    # знищення даних: `run_group` на порожній відповіді пише (None, "no_value"),
    # тобто чуже формулювання бланка коштувало б нам усіх полів цих режимів.
    unverified = {}
    if not form_recognized:
        for field in schema["fields"]:
            name = field["name"]
            if field.get("extraction") not in UNANCHORED_MODES:
                continue
            value, reason = results.get(name, (None, "no_value"))
            if value is None or reason != "matched":
                continue
            unverified[name] = (value, UNVERIFIED_METHOD)
            results[name] = (value, UNVERIFIED_METHOD)
            if name not in global_gaps and name not in localized_gaps:
                # Саме global_gaps: підказка тут була б шкідлива за тією самою
                # логікою, що й для відхиленого кандидата -- ми не знаємо, чи
                # знайдене місце взагалі те, тож у LLM іде ПОВНИЙ текст.
                global_gaps.append(name)

    if llm_extract_batch is None:
        return results

    def run_group(batch_names, context_text):
        json_schema, field_defs = build_json_schema_for_fields(schema, dictionaries, batch_names)
        try:
            samples = [llm_extract_batch(field_defs, context_text, json_schema)
                       for _ in range(max(1, self_consistency_n))]
        except Exception as exc:
            for name in batch_names:
                # Збій моделі не має ЗАБИРАТИ те, що детермінований шлях уже
                # знайшов: непідтверджене значення чесніше за порожнє поле,
                # доки провенанс каже, що воно непідтверджене.
                results[name] = unverified.get(
                    name, (None, f"llm_error:{type(exc).__name__}"))
            return
        for name in batch_names:
            voted, split = majority_vote([s.get(name) for s in samples if isinstance(s, dict)])
            if voted is None:
                # `unverified` порожній для всіх звичайних прогонів, тому це
                # рівно попередня поведінка всюди, крім чужої редакції бланка.
                results[name] = unverified.get(name, (None, "no_value"))
                continue
            # Заземлення ДО прийняття значення: значення, якого в документі
            # немає, -- це здогадка, не витяг (див. ground_llm_value).
            # Контекст перевірки -- ПОВНИЙ текст документа, а не context_text
            # групи: для локалізованої прогалини контекст -- лише фрагмент, і
            # правильне значення з іншого місця документа хибно вважалось би
            # вигаданим.
            grounded, ungrounded_reason = ground_llm_value(
                fields_by_name.get(name, {}), voted, ocr_text, printed)
            if grounded is None:
                results[name] = unverified.get(name, (None, ungrounded_reason))
                continue
            # llm_split_vote -- голоси розділились навпіл, переможець
            # обраний фактично випадково; для рев'юера це має виглядати
            # інакше, ніж одноголосний результат.
            results[name] = (voted, "llm_split_vote" if split else "llm")

    # Локалізовані прогалини: контекст -- лише знайдений фрагмент. Групуємо за
    # САМОЮ підказкою, а не просто по batch_size: інакше поля з РІЗНИМИ
    # підказками потрапляли в один виклик, усі підказки склеювались в один
    # контекст без прив'язки "яка кому належить", і LLM могла приписати
    # підказку одного поля іншому.
    hint_groups = {}
    for name in localized_gaps:
        hint_groups.setdefault(hints.get(name, ""), []).append(name)
    for hint, names in hint_groups.items():
        for batch_names in chunk_fields(names, batch_size):
            run_group(batch_names, hint or ocr_text)

    # нелокалізовані: контекст -- увесь документ, іншого немає
    for batch_names in chunk_fields(global_gaps, batch_size):
        run_group(batch_names, ocr_text)

    return results

# -*- coding: utf-8 -*-
"""Живий лічильник часу відповіді чата.

Нащо він. Сторінка «Статистика» досі показувала лише СТАЛІ числа — стан бази
і виміряну якість. На питання «а швидко це працює?» відповіді на екрані не
було зовсім, хоча час відповіді — головна річ, яку людина відчуває сама.
Тепер він міряється на живому чаті й змінюється, поки людина розмовляє.

Три рішення, які варто пояснити.

**Медіана, а не середнє.** Наші яруси різняться на два порядки: правила
відповідають за 0.04 с, модель — за 3-45 с. Одна довга відповідь моделі
задирає середнє так, що воно перестає описувати хоч що-небудь. Медіана
показує типовий хід, а 90-й процентиль окремо — наскільки погано буває в
найгіршому десятку. Дві цифри разом не брешуть; середнє саме — брехало б.

**У пам'яті процесу, а не на диску й не в базі** (рішення Ані 27.08). База —
зона Андрія і для нас тільки на читання, а файл стану — це ще один файл, який
хтось мусить чистити. Кільцевий буфер на останні `_KEEP` ходів не має ні
того, ні того ризику. Ціна: після перезапуску сервісу цифри починаються з
нуля, тому на сторінці прямо написано «з моменту запуску», а не «за весь час».

**Рахуємо ВСІ ходи, включно з відмовами й падінням бази.** Спокуса міряти
лише «успішні» відповіді хибна: людина чекає однаково, і відмова, яку система
обдумувала 40 с, — це така сама погана метрика, як і повільна відповідь.

Персональних даних тут не зберігається взагалі: у буфері лежать числа
(тривалість у секундах) і назва дороги. Ні питання, ні відповіді.
"""
import threading
import time
from collections import Counter, deque

#: Скільком ходів тримаємо. 500 -- це і кілька годин демо, і кілька хвилин
#: під приладом (measure_chat робить 124 питання): достатньо, щоб медіана
#: була стабільна, і достатньо мало, щоб буфер не важив нічого.
_KEEP = 500

_lock = threading.Lock()
_durations = deque(maxlen=_KEEP)
_roads = Counter()
#: Момент запуску процесу -- він же момент, з якого цифри чесні.
_started_at = time.time()
_total = 0


def record(seconds, road=None):
    """Один хід чата: скільком він тривав і якою дорогою пішов.

    Викликається з `answer()` -- тобто рівно один раз на хід, і для успіху,
    і для відмови, і для падіння бази.
    """
    global _total
    with _lock:
        _durations.append(float(seconds))
        _total += 1
        if road:
            _roads[str(road)] += 1


def _percentile(values, share):
    # Найближчий ранг, без інтерполяції: на 500 значеннях різниця з
    # «правильним» лінійним процентилем менша за похибку самого заміру,
    # а читати такий код може будь-хто.
    if not values:
        return None
    ordered = sorted(values)
    idx = min(len(ordered) - 1, max(0, int(round(share * (len(ordered) - 1)))))
    return ordered[idx]


def _sec(value):
    """Секунди для показу людині.

    Округлення до 0.1 с не годиться: правила відповідають за 0.04 с, і на
    екрані виходило «0.0 с» -- людина читає це як зламаний лічильник, а не як
    «швидко». Тому під секундою -- два знаки, над секундою -- один: там друга
    цифра однаково нічого не значить (у заміру є черга Gradio і мережа).
    """
    if value is None:
        return None
    return round(value, 2) if value < 1 else round(value, 1)


#: Скільком точок має сенс малювати. 60 на 200 пікселів -- приблизно три
#: пікселі на точку: видно і форму, і окремий шпиль.
def _thin(values, limit):
    tail = values[-limit:]
    return [round(v, 3) for v in tail]


def snapshot():
    """Стан лічильника для сторінки статистики.

    `n` -- скільком ходів у буфері (не за весь час: буфер кільцевий), `total`
    -- скільком їх було з запуску. Обидва числа потрібні: медіана рахується
    по буферу, а «скільком питань уже поставили» -- це total.
    """
    with _lock:
        values = list(_durations)
        total, roads = _total, dict(_roads)
    median = _percentile(values, 0.5)
    p90 = _percentile(values, 0.9)
    return {
        "n": len(values),
        "total": total,
        "median_s": _sec(median),
        "p90_s": _sec(p90),
        "slowest_s": None if not values else _sec(max(values)),
        # Ряд для крихітного графіка на сторінці. Не весь буфер: 500 точок
        # на 200 пікселів -- це шум, у якому не видно нічого. Беремо рівно
        # стільку, скільки пікселів має сенс, підряд із кінця (останні ходи
        # цікавіші за перші) і у природному порядку часу.
        "series": _thin(values, 60),
        "by_road": roads,
        "since": time.strftime("%Y-%m-%dT%H:%M:%S",
                               time.localtime(_started_at)),
        "window": _KEEP,
    }


def reset():
    """Тільки для тестів: інакше лічильник тягнеться між тестами одного
    процесу й перевірки читають чужі числа."""
    global _total
    with _lock:
        _durations.clear()
        _roads.clear()
        _total = 0

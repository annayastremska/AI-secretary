def test_polite_words_are_not_sent_to_the_database_as_surnames(no_db,
                                                              monkeypatch):
    """Знахідка при написанні щита: «Дякую» йде в базу як кандидат у прізвище.

    Список службових слів (`STOP_CAPS`) неповний, тому будь-яке слово з
    великої літери -- «Дякую», «Тільки», «Покажіть» -- перетворюється на
    запит `ILIKE '%Дяку%'`. Сьогодні це нічого не знаходить і тому невидиме;
    після правки блоку C (терплячіший пошук) стане видимим одразу.

    Тест фіксує НАМІР: службове слово не має доходити до бази взагалі.
    Поки доходить -- він рахує звернення й тому червоний за призначенням,
    тільки коли звернень більше нуля.
    """
    calls = []
    monkeypatch.setattr(chat_app.db, "find_people",
                        lambda **kw: calls.append(kw) or [])
    for word in ("Дякую", "Тільки", "Добре"):
        chat_app.extract_name(word)
    assert calls, ("якщо звернень нема -- слово вже відфільтроване, і цей "
                   "тест треба переписати на assert not calls")
    # Поріг, а не нуль: фіксуємо ТЕПЕРІШНІЙ стан, щоб правка C його зменшила,
    # а не збільшила. Кожне слово дає до чотирьох спроб (обрізання по літері).
    assert len(calls) <= 12, len(calls)



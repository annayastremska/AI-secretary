"""Щит: те, що за звітом Дениса 27.08 ПРАЦЮЄ і має вижити після правок.

Денис поставив розділ «Що працює добре» останнім і написав чому: «це не
ввічливість, це список того, що легко зламати випадково, поки лагодите решту».
Цей файл — той список, перекладений у тести, і написаний **до** правок. Порядок
жорсткий: щит зелений → тільки тоді правки. Інакше про поломку дізнається Денис
на четвертому прогоні, а не ми на другій хвилині.

Розбір причин і план — `docs/tasks/2026-08-27_harness-research-plan.md`.

## Головне про цей файл: кожен тест названий разом із тим, ЧИМ його можна зламати

Правка одного блоку ламає інший не випадково, а закономірно: обидва живуть в
одній функції. Тому в кожному тесті стоїть рядок «ламається правкою…» — це не
коментар для краси, а те, що я мушу перечитати перед кожною правкою.

Найяскравіша пара, знайдена саме при написанні щита:

  * п. 22 (одруківка «3 ротті» → «такого підрозділу немає», підказки немає) і
  * п. 27 (**«5 рота» → «такого підрозділу немає», і це ПРАВИЛЬНО**)

ідуть **однією дорогою** — обидва дають `subdivision_unknown`. Тобто «додати
підказку "можливо, ви мали на увазі 3-тю роту?"» неминуче торкається того місця,
де відмова чесна. Якщо підказка почне вгадувати, «5 рота» перетвориться на
«можливо, 3-тя рота?» — тобто найкраща відповідь у звіті стане вгадуванням.

## Що тут НЕ перевіряється, і чому

Без бази й без моделі: п. 26 (документ під відповіддю той самий) і п. 29 (стан
прив'язаний до дати) вимагають живих даних, п. 28 і 30 — моделі. Вони йдуть у
живий прогін, і критерії на них — у плані, розділ 13. Тут лише те, що
детерміноване: регулярки, вибір дороги, тексти відмов.

Запуск:
    python -m pytest demos/upload_app/tests/test_denys_shield.py -q
"""

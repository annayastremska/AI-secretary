# ── п. 23. Формат дати вільний, але недійсна дата НЕ виправляється ──────────

@pytest.mark.parametrize("question", [
    "Скільком осіб у відпустці 10.10.2026?",
    "Скільком осіб у відпустці 2026-10-10?",
    "ХТО У ВІДПУСТЦІ НА 2026-10-10?",
    "хто у відпустці на 2026-10-10",
])
def test_date_formats_and_caps_are_recognised(question):
    """п. 23: «10.10.2026», ISO і капс дають ту саму дату.

    Ламається правкою блоку A (дві дати = період): вона переписує рівно цю
    функцію, і найлегше при цьому втратити одноденні форми.
    """
    on_date, date_from, _ = tiers.extract_dates(question)
    assert (on_date or date_from) == datetime.date(2026, 10, 10), question


@pytest.mark.parametrize("question", [
    "Скільком осіб у відпустці 2026-02-30?",
    "Хто був у відрядженні 31.02.2026?",
    "Скільком осіб у відпустці 31 лютого 2026?",
])
def test_impossible_date_is_refused_not_silently_dropped(question):
    """п. 23: недійсна дата -- ЯВНА відмова.

    Історія цього тесту -- головна причина, чому щит пишеться до правок.
    Спершу він стояв тут як `xfail`: Денис похвалив відповідь «це недійсна
    дата», а в коді такого тексту не було взагалі -- `fromisoformat` кидав
    неперехвачений ValueError із правилового ярусу, питання падало далі до
    моделі, і правильну відповідь давала вона. Тобто сильна сторона була
    ПОБІЧНИМ ЕФЕКТОМ падіння.

    Правка блоку A (дві дати = період) те падіння прибрала -- і разом із ним
    прибрала б ту відповідь: питання пішло б у підрахунок із датою
    «сьогодні». Тому відмова стала явною поведінкою: шаблон `date_invalid`.

    Обидві форми, цифрова й словесна: «31 лютого» доти тихо ставало ВСІМ
    лютим, тобто відповіддю на інше питання.
    """
    assert tiers.impossible_dates(question), question
    tid, _ = tiers.rules_route(question)
    assert tid == "date_invalid", (question, tid)
    # І сам витяг дат не падає й не вигадує день
    on_date, _, _ = tiers.extract_dates(question)
    assert on_date is None


@pytest.mark.parametrize("question,expected", [
    ("Хто у відпустці 28 лютого 2026?", datetime.date(2026, 2, 28)),
    ("Хто був у відпустці 6 травня 2026?", datetime.date(2026, 5, 6)),
])
def test_valid_written_dates_still_work(question, expected):
    """ПЕРЕВІРКА НА ПОБІЧНУ ШКОДУ від гейта недійсних дат: дійсні словесні
    дати мусять і далі працювати. Найлегший спосіб зламати -- відмовляти на
    всьому, де є день і назва місяця."""
    assert not tiers.impossible_dates(question)
    on_date, date_from, _ = tiers.extract_dates(question)
    assert (on_date or date_from) == expected



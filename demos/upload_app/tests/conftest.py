"""Спільна підготовка тестів апки.

Ці тести НЕ входять у прилад пайплайна (eval/tests, 296 тестів) -- вони
живуть окремо і ганяються окремо: `python -m pytest demos/upload_app/tests`.

Три речі, які мусять статися ДО імпорту модулів апки:
  1. CHAT_MODEL_PATH -> свідомо неіснуючий шлях: тести не мають вантажити
     ваги 4B (задача каже: модель локально не запускати; без ваг чат чесно
     живе на правилах -- саме цей режим і тестуємо);
  2. CHAT_TRACE_PATH -> тимчасовий файл (див. нижче);
  3. корінь репозиторію в sys.path, щоб `import demos.upload_app...`
     працював незалежно від того, звідки запущено pytest.
"""
import os
import sys
import tempfile

# до будь-якого імпорту tiers/app: MODEL_PATH читається при імпорті модуля
os.environ["CHAT_MODEL_PATH"] = os.path.join("nonexistent", "no-model.gguf")

# СЛІД ТЕСТІВ -- ОКРЕМО ВІД БОЙОВОГО.
#
# Знайдено 28.08 на сервері: після прогону набору `trace_lookup.py --check`
# сказав «ЗЛАМАНО: відповідей без джерела 2, технічних збоїв 4». Насправді це
# були самі тести: вони навмисно перевіряють відповідь «база недоступна»
# (підставні реквізити -> OperationalError) і відповідь без блоку джерела.
# Тобто набір писав у той самий `logs/chat-trace.jsonl`, який читає прилад, і
# прилад після цього кричав про поломку, якої з людиною не було.
#
# Ціна такої плутанини висока: це прилад, яким я приймаю роботу. Прилад, що
# міряє власні тести, гірший за відсутній -- йому перестають вірити саме тоді,
# коли він скаже правду. Тому шлях сліду в тестах свій, і `--check` на сервері
# лишається про живі ходи.
os.environ["CHAT_TRACE_PATH"] = os.path.join(
    tempfile.gettempdir(), "ai-secretary-tests-trace.jsonl")

_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.dirname(os.path.abspath(__file__)))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

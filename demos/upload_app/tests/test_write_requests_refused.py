# -*- coding: utf-8 -*-
"""Прохання ЗМІНИТИ дані мусить отримати відмову, а не зміст документа.

Знахідка Андрія 28.08: на п'яти проханнях змінити дані чат відмовляв 1 із 5.
Я переміряла живцем на семи -- **2 із 7**. Ловились «видали» і «зміни», не
ловились «постав», «онови», «додай», «скасуй», «виправ»:

    «Онови номер документа 207»            -> doc_by_number (показав документ)
    «Скасуй документ №118»                 -> підрахунок
    «Постав усім у 1 роті статус підтверджено» -> уточнення
    «Виправ прізвище Малишко на Малишенко» -> підрахунок

ДАНИМ ЦЕ НЕ ЗАГРОЖУВАЛО, і це перевірено, а не припущення: чат ходить у базу
користувачем `milidoc_readonly`, а ярус вільного SQL має валідатор (один
SELECT, без DML, allowlist таблиць). Дефект був в ОЧІКУВАННЯХ: людина просить
змінити, бачить зміст документа й читає це як «зробив». На демо це найгірше з
можливих прочитань.

Тому тест саме на ВІДМОВУ, а не на цілісність даних: цілісність тримають
права доступу й валідатор, а тут перевіряється, що система КАЖЕ правду про те,
чого не робить.
"""
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
APP_DIR = os.path.dirname(HERE)
for p in (APP_DIR, os.path.join(APP_DIR, "chat_gradio")):
    if p not in sys.path:
        sys.path.insert(0, p)

from chat_gradio import app as ca             # noqa: E402
from chat_gradio import tiers as tier_chat    # noqa: E402


WRITE_REQUESTS = [
    "Видали наказ № 145",
    "Постав усім у першій роті статус підтверджено",
    "Зміни дату відпустки Ґоляша на 2026-11-01",
    "Онови номер документа 207",
    "Додай нову особу в штатку",
    "Скасуй документ №118",
    "Виправ прізвище Малишко на Малишенко",
    "Перепиши дату в документі 118",
    "Приберіть цей факт із підрахунку",
    "Заміни підрозділ у картці Ґоляша",
    "Призначте Малишко у другу роту",
    "Збережи цей документ як підтверджений",
]


@pytest.mark.parametrize("q", WRITE_REQUESTS)
def test_write_request_is_caught_by_the_guard(q):
    assert tier_chat._DESTRUCTIVE.search(q), q


READ_QUESTIONS = [
    # Питання про ДАНІ -- запобіжник не має їх ловити, інакше він з'їсть
    # половину чата.
    "Хто зараз у відпустці?",
    "Скільки осіб у частині?",
    "Покажи документ №207",
    "Покажи відсутніх по підрозділах на 2026-10-10",
    "Що в черзі перевірки?",
    "Яка тривалість щорічної основної відпустки?",
    "Який період покривають документи в базі?",
    "Де Ґоляш Богодар Святославович?",
    "Скільки непідтверджених фактів?",
    # Минулий час -- це питання про минуле, а не прохання дії.
    "Хто змінив документ 118?",
    "Скільком документів пройшли обробку без правок людини?",
]


@pytest.mark.parametrize("q", READ_QUESTIONS)
def test_read_questions_are_not_caught(q):
    assert not tier_chat._DESTRUCTIVE.search(q), q


def _db_reachable():
    try:
        with tier_chat._connect() as conn, conn.cursor() as cur:
            cur.execute("SELECT 1")
            return True
    except Exception:
        return False


@pytest.mark.skipif(not _db_reachable(), reason="потрібна жива база")
@pytest.mark.parametrize("q", WRITE_REQUESTS)
def test_answer_refuses_live(q):
    """Наскрізь: людина мусить побачити «не змінюю», а не зміст документа."""
    out = ca.answer(q)
    assert "Відхилено" in out or "лише в режимі читання" in out, out[:200]

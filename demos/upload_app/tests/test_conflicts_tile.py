def test_payload_has_both_numbers():
    """Два числа, а не одне (моя поправка, яку Аня прийняла).

    «Конфліктів: 2» -- напівправда: з двох наявних пар одна законна (№118
    анульований, №131 виданий замість нього). Тому друге число -- скільком
    парам записана підстава заміни.
    """
    c = stats.conflicts()
    assert set(c) >= {"pairs", "with_supersession", "rows", "how", "error"}, c


def test_unavailable_db_says_not_measured_not_zero():
    """База недоступна -> `pairs` None, а не 0.

    Нуль тут -- найдорожча брехня на цій сторінці: він читається як «усе
    чисто», тобто рівно навпаки до правди. Ловимо на неможливому DSN.
    """
    c = stats.conflicts(dsn="postgresql://nobody@127.0.0.1:1/none")
    assert c["pairs"] is None, c
    assert c["with_supersession"] is None, c
    assert c["error"], c
    assert c["rows"] == [], c


def test_every_number_has_how():
    """Цифра без джерела не показується -- правило продукту, на якому нас уже
    ловив Денис."""
    c = stats.conflicts(dsn="postgresql://nobody@127.0.0.1:1/none")
    assert c["how"] and len(c["how"]) > 20, c["how"]
    #: «Чим зміряно» мусить називати сам замір, а не бути гаслом: що саме
    #: рахується (накладання періодів) і звідки взялось (запит по базі).
    #: Слово «перетин» тут більше не шукається -- підпис скорочений на прохання
    #: Ані, і тест мусить тримати ЗМІСТ, а не ту редакцію, під яку його писали.
    low = c["how"].lower()
    assert "накладання" in low and "запит по базі" in low, c["how"]


def test_wording_does_not_call_a_lawful_replacement_a_conflict():
    """Формулювання: «пар, що перетинаються», а не «конфліктів».

    Причина рівно одна й вона в базі: №131 виданий ЗАМІСТЬ анульованого №118.
    Це законна заміна, і назвати її конфліктом означає показати гостям
    неправду про власні дані.
    """
    page = io.open(os.path.join(APP_DIR, "static", "stats.html"),
                   encoding="utf-8").read()
    sec = page[page.index("conflict"):]
    assert "перетинаються" in sec, "плитка мусить казати «перетинаються»"
    #: Слово «конфлікт» у назві плитки лишається (так просив Андрій, і воно
    #: зрозуміле), але поруч мусить стояти пояснення, що це не вирок.
    assert "заміни" in sec or "підстав" in sec, sec[:600]



def test_tile_never_writes_to_the_database():
    """База -- зона Андрія, і для нас тільки на читання. Перевіряємо текстом
    запиту, бо це єдиний спосіб перевірити «не пише», не пишучи."""
    src = io.open(os.path.join(APP_DIR, "stats.py"), encoding="utf-8").read()
    sql = _conflicts_sql(src).upper()
    for word in ("INSERT", "UPDATE", "DELETE", "DROP", "ALTER", "TRUNCATE"):
        assert word not in sql, word


def _conflicts_sql(src):
    """САМ ТЕКСТ ЗАПИТУ, без прози навколо. Окремо, бо ним користуються
    п'ять тестів.

    Береться літерал `sql = \"\"\"...\"\"\"`, а не вся функція. Причина -- своя
    ж помилка: перший варіант брав функцію цілком, і тест «не пише в базу»
    падав на власному докстрингу, де слова INSERT/UPDATE названі як те, що
    заборонено. Тобто тест перевіряв прозу, а не код -- рівно та підміна, від
    якої він і мусить страхувати.
    """
    body = src[src.index("def conflicts("):]
    body = body[:body.index("\ndef ", 10)]
    start = body.index('sql = """') + len('sql = """')
    return body[start:body.index('"""', start)]

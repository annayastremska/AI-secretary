def test_conflicts_are_per_person_not_global():
    """Найважливіший критерій: перетин рахується в межах ОДНОЇ особи.

    Якщо цю умову з запиту прибрати, плитка покаже сотні «конфліктів» на
    штатці з 153 людей -- бо у жовтні у відпустці одночасно десятки, і це
    норма. Тест тримає умову в тексті запиту, бо перевірити її на живій базі
    означало б залежати від бази в наборі тестів.
    """
    src = io.open(os.path.join(APP_DIR, "stats.py"), encoding="utf-8").read()
    sql = _conflicts_sql(src)
    #: Пари склеюються по одному об'єкту -- саме це й означає «одна особа».
    assert "a.object_id = b.object_id" in sql, sql



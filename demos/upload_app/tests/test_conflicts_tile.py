def test_touching_periods_are_not_a_conflict():
    """День-у-день -- не перетин: документ, що починається наступного дня після
    завершення попереднього, суперечності не створює. У запиті це строга
    нерівність, і саме її найлегше зробити нестрогою «щоб напевно»."""

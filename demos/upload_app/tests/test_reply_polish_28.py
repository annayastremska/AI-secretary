# -*- coding: utf-8 -*-
"""Три правки подачі відповіді за прогоном Ані 28.08.

1. **Назва акта — не жирним і без огризка слова.** На екрані було
   «**Про соціальний і правовий захист військовослужбовців та чл…**»: половина
   слова «членів», та ще й жирним. Жирним у відповіді виділяється цифра або
   головне твердження, а назва документа — це посилання, не висновок.
   Обрізка приходить із бази (`doc_title` зберігається обрізаним на 58
   символів, з реальним «…»), тому виправляємо показ, а не дані.

2. **«Чому це відповідь: …» — приміткою над міткою ходу**, а не абзацом між
   цитатою норми й твердженням «це дослівна цитата». Це службове знання про
   те, як склалась відповідь, і всередині тексту воно розриває головне.

3. **«Покажи відсутніх по підрозділах» мусить називати людей.** Відповідь була
   «3-тя механізована рота: 1 особа. Разом: 1 особа.» — на питання «покажи
   ХТО» прилітало «скільком».

Сирий текст відповіді для пунктів 1 і 2 змінюється по-різному, і це важливо:
назву міняє сам ланцюг (пункт 1), а «Чому це відповідь» переїжджає ЛИШЕ на
рендері (пункт 2) — у сирому тексті рядок лишається на місці, тому слід, тести
й вимір довжини бачать те саме.
"""
import os

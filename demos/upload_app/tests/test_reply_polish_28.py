import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
APP_DIR = os.path.dirname(HERE)
for p in (APP_DIR, os.path.join(APP_DIR, "chat_gradio")):
    if p not in sys.path:
        sys.path.insert(0, p)

from chat_gradio import app as ca                    # noqa: E402
from chat_gradio import normative_chain as nc        # noqa: E402
from chat_gradio import tiers as tier_chat           # noqa: E402


# ── 1. Назва акта ────────────────────────────────────────────────────────────


@pytest.mark.parametrize("title,want", [
    # Живий приклад із прогону.
    ("Про соціальний і правовий захист військовослужбовців та чл…",
     "Про соціальний і правовий захист військовослужбовців…"),
    ("Про затвердження Положення про військово-лікарську експерт…",
     "Про затвердження Положення про військово-лікарську…"),
    # Три точки замість символа «…» -- та сама обрізка іншим написанням.
    # «щось» відкидається як недописане, а слідом і «та»: сполучник без свого
    # іменника читається як недоробка. Спершу я чекала тут «Про інформацію та…»
    # -- і саме це формулювання Аня і назвала негарним у живому прогоні.
    ("Про інформацію та щось...", "Про інформацію…"),
    # Ціла назва не чіпається взагалі.
    ("Про інформацію", "Про інформацію"),
    ("Кримінальний кодекс України", "Кримінальний кодекс України"),
    # Порожнє й None не валять рендер.
    ("", ""),
    (None, ""),
])
def test_clean_title(title, want):
    assert nc._clean_title(title) == want


def test_clean_title_never_leaves_a_dangling_separator():
    """Кома перед «…» читається як обрив на середині думки."""
    assert nc._clean_title("Про щось, і ще щось,…") == "Про щось, і ще щось…"


# ── 2. «Чому це відповідь» -- у примітки ─────────────────────────────────────


def test_why_line_becomes_a_note():
    text = ("Доповідаю: Про інформацію (№ 2657-XII), Стаття 1 / 1\n"
            "«якась дослівна цитата»\n"
            "Чому це відповідь: у тексті є потрібне.\n"
            "Це дослівна цитата з чинного документа; перевірено, "
            "що вона є в тексті.\n\n"
            "<details class=\"src\"><summary>джерело</summary>"
            "звернення: abc123</details>")
    out = ca.render_reply(text)
    # Пояснення пішло в примітку...
    assert 'class="note note--info"' in out
    assert "у тексті є потрібне" in out
    # ...і НЕ лишилось абзацом у тілі відповіді.
    assert "Чому це відповідь" not in out
    # Примітка стоїть НАД міткою ходу -- порядок читання зверху вниз.
    assert out.index("у тексті є потрібне") < out.index('class="req-id"')


def test_why_prefix_matches_what_the_chain_writes():
    """Літерал живе у двох файлах. Розійшлись би мовчки, а симптом був би
    «примітка знову стала абзацом»."""
    src = open(os.path.join(APP_DIR, "chat_gradio", "normative_chain.py"),
               encoding="utf-8").read()
    assert f'f"{ca._WHY_PREFIX}' in src or f'"{ca._WHY_PREFIX} ' in src, (
        ca._WHY_PREFIX)


def test_raw_answer_still_contains_the_why_line():
    """Переїжджає рівно те, що бачить око: сирий текст не змінюється, бо на
    ньому тримаються слід, тести й вимір довжини."""
    raw = "Чому це відповідь: причина."
    assert ca._WHY_PREFIX in raw


# ── 3. Розклад по підрозділах називає людей ──────────────────────────────────


def test_breakdown_renderer_asks_for_names():
    """Перевірка на КОДІ, а не на базі: гілка шаблону мусить кликати той самий
    помічник, що решта шаблонів про стан, а не мати власну копію переліку."""

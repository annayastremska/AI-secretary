# ── Регістр назви акта після «Доповідаю:» ────────────────────────────────────


def test_document_title_keeps_its_capital_letter():
    """Побічний ефект правки «назва не жирна», зловлений живим прогоном.

    Правило «після Доповідаю: -- з малої» писалось під РЕЧЕННЯ («12 осіб у
    відпустці») і для них правильне. Але перший рядок нормативної відповіді --
    це назва акта, і вона поїхала як «про соціальний і правовий захист…».
    """
    out = ca._as_report("Про соціальний і правовий захист… (№ 2011-XII), "
                        "Стаття 10-1 / 1\n«цитата»")
    assert "Доповідаю: Про соціальний" in out, out


@pytest.mark.parametrize("text,starts", [
    # Звичайні речення -- як було, з малої.
    ("12 осіб у відпустці.", "Доповідаю: 12 осіб"),
    ("Такої дати не існує.", "Доповідаю: такої дати"),
    ("Розклад по підрозділах — відсутні:", "Доповідаю: розклад по"),
])
def test_sentences_still_go_lowercase(text, starts):
    assert ca._as_report(text).startswith(starts)


def test_identifier_shapes_recognised():
    for head in ("Назва (№ 550-XIV), Стаття 1",
                 "Назва (НД ТЗІ 1.4-001-2000), Розділ 2",
                 "Назва (наказ № 606 від 20.11.2017), Пункт 3"):
        assert ca._CITED_DOC_HEAD.search(head), head
    # Дужки з чимось іншим посиланням не роблять.
    assert not ca._CITED_DOC_HEAD.search("Розклад (відпустка або відрядження):")

# -*- coding: utf-8 -*-
"""Теми нормативного корпусу: зіставлення й відповідь «що я знаю».

## Нащо цей модуль

На «які є нормативні тексти» чат віддавав таблицю на 44 рядки з колонками
`id | validity | uploaded_on | title_line`, де замість назв стояли перші рядки
тексту актів: «МІНІСТЕРСТВО ОБОРОНИ УКРАЇНИ», «НОРМАТИВНИЙ ДОКУМЕНТ», «3».
Дані при цьому чисті -- у базі всі 44 документи мають осмислений `doc_title`;
сміття робив SQL шаблону, який брав `split_part(text_content, E'\\n', 1)`,
бо на час його написання полів `doc_identifier`/`doc_title` ще не існувало.

Але головне не в назвах. Перелік документів **не є відповіддю** на питання
«що ти знаєш»: людині потрібно знати, ПРО ЩО можна питати. Це те саме правило
форми відповіді, яке вже прибрало 3977 символів переліку до 641, тільки
доведене до кінця: не коротший перелік, а інша відповідь.

## Чому перелік ТЕМ, а не мітки документів

Перша версія дизайну була ручною: тема дописується кожному документу. Аня
відкинула її одним реченням -- «нормативні доки ж будуть додаватися, тому ти
не можеш до них завжди дописувати назви». Тому робота лежить на переліку тем
(`normative_topics.yaml`, ~8 тем), а зіставлення робиться автоматично, за
словами з номера, назви й початку тексту.

Наслідки, які варто назвати вголос:

* документ, залитий завтра, отримує тему без жодної правки;
* документ може попасти в КІЛЬКА тем -- це навмисно: для питання «про що можна
  питати» кілька тем корисніші за одну;
* документ, який не ліг ні в одну тему, попадає в «інше», і «інше»
  **називається числом у відповіді**, а не ховається. Плюс тест падає, коли
  частка «іншого» перевищує поріг із того самого файла. Тобто застарілий
  перелік тем видно двічі -- людині й наборові.

## Чого тут НЕ робиться

* нічого не пишеться в базу: теми не зберігаються, вони обчислюються під час
  відповіді. Запис у базу був би міграцією в чужій зоні перед демо;
* початок тексту документів читається ЛИШЕ для зіставлення й ніколи не
  друкується (тест `test_render_does_not_print_document_text`);
* дублі актів (44 записи = 40 різних актів) і обрізані `doc_title` не
  виправляються: це заливка корпусу, зона Андрія. Ми лише кажемо про це правду.
"""
import io
import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
TOPICS_PATH = os.path.join(os.path.dirname(HERE), "normative_topics.yaml")

#: Скільком символів початку тексту дивимось при зіставленні. 1200 -- заміряне
#: значення: на ньому 43 із 44 документів отримують тему (на одній лише назві
#: -- 39, бо довгі `doc_title` збережені обрізаними, з реальним «…»).
HEAD_CHARS = 1200

#: Скільком прикладів питань показуємо в одній відповіді. Три -- стільком,
#: скільком людина прочитає, не гублячи перелік тем над ними.
EXAMPLES_SHOWN = 3

_CACHE = {}


def _data():
    if "data" not in _CACHE:
        with io.open(TOPICS_PATH, encoding="utf-8") as fh:
            _CACHE["data"] = yaml.safe_load(fh.read()) or {}
    return _CACHE["data"]


def load():
    """-> перелік тем у порядку файла. Порядок = порядок показу."""
    out = []
    for t in _data().get("topics") or []:
        # `>-` у YAML склеює рядки регулярки через пробіл -- прибираємо всі
        # пробіли й переноси, бо в самій регулярці пробіли записані як \s.
        match = re.sub(r"\s+", "", t.get("match") or "")
        out.append({"title": (t.get("title") or "").strip(),
                    "match": match,
                    "ask": [q.strip() for q in (t.get("ask") or []) if q.strip()]})
    return out


def max_other_share():
    return float(_data().get("max_other_share", 0.15))


def other_title():
    return (_data().get("other_title") or "інше").strip()


def chips():
    """Готові кнопки на екрані вітання -- питання по нормативці.

    Рішення Ані 28.08: приклади питань у самій відповіді зайві, натомість три
    з них ідуть у дефолтні кнопки чата. Так вони під рукою завжди, а не лише
    тоді, коли людина спитала про склад корпусу.

    Питання беруться з цього ж файла й мусять бути серед `ask` якоїсь теми --
    інакше кнопка розійшлася б із перевіркою «приклад має відповідь у корпусі»,
    і в чаті з'явилась би готова кнопка в порожнечу. Рівно на цьому ми вже
    горіли з попередніми кнопками: вони питали про травень, якого в базі немає.
    """
    return [q.strip().rstrip("?") + "?"
            for q in (_data().get("chips") or []) if q.strip()]


def _compiled():
    if "compiled" not in _CACHE:
        _CACHE["compiled"] = [(t["title"], re.compile(t["match"], re.I))
                              for t in load()]
    return _CACHE["compiled"]


def topics_of(ident, title, head=""):
    """-> перелік тем документа (може бути порожній = «інше»).

    Зіставляється склеєне «номер + назва + початок тексту»: назви в базі
    бувають обрізані, і тоді слово з хвоста назви знаходиться лише в тексті.
    """
    hay = " ".join(x for x in (ident, title, head) if x)
    if not hay.strip():
        return []
    return [name for name, rx in _compiled() if rx.search(hay)]


def fetch_rows():
    """Нормативні документи з полями, потрібними для зіставлення й показу.

    Живе тут, а не в шаблоні каталогу: шаблон віддає рядки, а тут вони
    потрібні ще й приладу (тест частки «іншого») -- дві копії SQL розійшлися б.
    """
    try:
        from . import tiers as _t
    except ImportError:                      # запуск як скрипта
        import tiers as _t
    with _t._connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT doc_identifier, doc_title, validity, "
                "       left(COALESCE(text_content, ''), %s) AS head "
                "  FROM documents WHERE domain = 'normative' ORDER BY id",
                (HEAD_CHARS,))
            return cur.fetchall()


def _acts(n):
    """«1 акт», «4 акти», «5 актів» -- узгодження числа з іменником.

    Написано після того, як у живій відповіді з'явилось «4 акт(и)». Дужки в
    тексті для людини -- це видима недороблена робота, а відповідь чата читає
    не програміст.
    """
    n = int(n)
    tail, hundred = n % 10, n % 100
    if tail == 1 and hundred != 11:
        word = "акт"
    elif tail in (2, 3, 4) and hundred not in (12, 13, 14):
        word = "акти"
    else:
        word = "актів"
    return f"{n} {word}"


def _act_key(row, index=0):
    """Чим відрізняється АКТ від ЗАПИСУ.

    У 44 записах лише 40 різних актів: наказ № 606, № 550-XIV, наказ № 402 і
    № 1153/2008 залиті по двічі. Подавати 44 як «44 різних акти» -- неправда,
    тому кажемо обидва числа. Ключ -- номер акта, а без номера -- назва.

    Документ БЕЗ номера й назви рахується як окремий акт (ключ за позицією), а
    не викидається: інакше «різних актів» вийшло б МЕНШЕ, ніж їх насправді, і
    ми зробили б із власного незнання неправдиве число. Незнання про документ
    -- не підстава вважати його копією іншого.
    """
    ident = (row.get("doc_identifier") or "").strip()
    title = (row.get("doc_title") or "").strip().lower()
    return ident or title or f"без-ознак-{index}"


def render(rows):
    """-> рядки відповіді «що є в нормативному корпусі».

    Відповідь -- теми з числами й приклади питань. Ані таблиці, ані переліку
    документів: перелік не відповідає на питання «про що можна питати», і саме
    це побачила Аня.
    """
    rows = list(rows or [])
    if not rows:
        return ["Нормативних документів у базі немає."]

    acts = {_act_key(r, i) for i, r in enumerate(rows)}
    by_topic = {}
    other = 0
    for r in rows:
        names = topics_of(r.get("doc_identifier"), r.get("doc_title"),
                          r.get("head") or "")
        if not names:
            other += 1
            continue
        for n in names:
            by_topic[n] = by_topic.get(n, 0) + 1

    lines = []
    head = f"нормативних документів у базі: {len(rows)}"
    if acts and len(acts) != len(rows):
        # Розбіжність -- вголос. Ховати її означало б показати кращу цифру,
        # ніж є.
        #
        # ФОРМУЛЮВАННЯ ВАЖЛИВЕ, і перше було неправдою. Я написала «залиті
        # двічі» -- і перевірка це не підтвердила: файли різні за хешем (тобто
        # дедуплікація за файлом відпрацювала правильно), а в парі наказу № 606
        # копії відрізняються переліком змін -- одна згадує наказ № 398 від
        # 04.11.2020, друга ні. Це РІЗНІ РЕДАКЦІЇ того самого акта, і тримати
        # обидві законно. Незаконно інше: не знати, яка чинна.
        #
        # Тому кажемо те, що знаємо точно: записів більше, ніж актів, і яка
        # версія чинна -- не встановлено. Поля для цього в базі є
        # (`validity`, `superseded_by_doc_id`) і вони не заповнені -- це зона
        # заливки корпусу, не наша.
        extra = len(rows) - len(acts)
        head += (f", з них різних актів {len(acts)}: "
                 f"{_acts(extra)} {'присутній' if extra % 10 == 1 and extra % 100 != 11 else 'присутні'}"
                 " у двох версіях, і яка з них чинна — не встановлено")
    lines.append(head + ".")
    lines.append("Теми, про які можна питати "
                 "(документ може стосуватись кількох):")
    for t in load():
        n = by_topic.get(t["title"], 0)
        if n:
            lines.append(f"- {t['title']} — {n}")
    if other:
        lines.append(f"- {other} {'документ' if other == 1 else 'документів'} "
                     f"без теми: {other_title()}")

    # Приклади питань у ВІДПОВІДІ не друкуються: рішення Ані 28.08 -- «це
    # зайве», вони переїхали в готові кнопки на екрані вітання (`chips()`).
    # Там вони під рукою завжди, а не лише коли людина спитала про корпус.

    unclear = [r for r in rows if (r.get("validity") or "") != "current"]
    if unclear:
        # Формулювання через двокрапку, а не «у N документів»: місцевий
        # відмінок після числа вимагає узгодження («у 1 документі», «у 2
        # документах»), і будь-який один літерал буде неграмотним для частини
        # чисел. Тут число стоїть окремо й узгоджувати нічого не треба.
        lines.append("Документів, чинність яких не підтверджена: "
                     f"{len(unclear)} — система її сама не встановлює.")
    return lines

#: Одиниця нормативного акта, названа в питанні: «пункт 1», «стаття 10-1»,
#: «частина друга», «абзац третій». Саме ці слова відрізняють прохання
#: процитувати НОРМУ від прохання процитувати наш обліковий документ.
_NORM_UNIT = re.compile(
    r"\bпункт\w*\b|\bстатт\w*\b|\bстаття\b|\bчастин\w+\b|\bабзац\w*\b|"
    r"\bрозділ\w*\b|\bдодат\w*\b", re.IGNORECASE)


#: Слова, які означають САМЕ нормативний акт і нічого іншого. «Наказ» сюди
#: НЕ входить навмисно: наказ про відрядження -- це наш обліковий документ, і
#: на «наведи дослівно текст наказу про відрядження» правильна відповідь --
#: чесна відмова про OCR, а не пошук у корпусі законів. Перша версія брала
#: широкий `_NORMATIVE`, і саме на цьому прикладі впала.
_ACT_WORD = re.compile(r"\bзакон\w*\b|\bстатут\w*\b|\bкодекс\w*\b|"
                       r"\bположенн\w*\b|\bнорматив\w*\b", re.IGNORECASE)


def _asks_for_a_norm(question):
    """Чи прохання дослівного тексту стосується НОРМИ, а не нашого документа.

    Три ознаки, кожна достатня й кожна однозначна:
      * названий ідентифікатор акта (`№ 2011-XII`, `НД ТЗІ …`);
      * названа одиниця акта («пункт 1», «стаття 10-1», «абзац третій»);
      * слово, яке може означати лише акт («закон», «статут», «кодекс»).

    Питання про НАШІ документи (квиток, наказ про відрядження) сюда не
    підпадають -- там відмова про OCR правдива, і замінювати її пошуком у
    корпусі законів означало б відповідати не на те питання.
    """
    q = question or ""
    if tier_chat.is_act_identifier(q):
        return True
    if _NORM_UNIT.search(q):
        return True
    return bool(_ACT_WORD.search(q))


#: Шапка нормативної відповіді в історії: «… (№ 2011-XII), Стаття 10-1 / 2».
#: Звідси беруться акт і стаття, на які посилається наступна репліка словом
#: «цієї».
_PREV_ACT = re.compile(r"\((№[^)]{1,40}|НД\s+ТЗІ[^)]{1,30}|наказ[^)]{1,40})\)"
                       r"\s*,\s*(Стаття\s+[\d\-]+|Розділ\s+[\d\-.]+)")

#: «пункт 1», «пункту 3» -- номер потрібної одиниці в питанні.
_ASKED_POINT = re.compile(r"пункт(?:у|ом|і)?\s+(\d+(?:-\d+)?)", re.IGNORECASE)


#: Ознака того, що ланцюг ВІДМОВИВ: жодного кандидата ворота не пропустили.
_CHAIN_REFUSED = "жодне не відповідає на питання прямо"


def _map_from_previous(question, history, answer):
    """Карта документа з ПОПЕРЕДНЬОГО ходу, коли на цьому ланцюг відмовив.

    Другий хід прогону Андрія 28.08: «я не питаю за скільки часу, я питаю
    послідовність моїх дій, куди і як» -> відмова. Ворота відкинули кандидатів
    по одному, і правильно: жоден фрагмент окремо на все питання не
    відповідає. Але потрібний документ ВІДОМИЙ -- його назвала відповідь ходом
    раніше, і в її блоці джерела стоїть «документ: запис №252 у базі».

    Ланцюг історії не бачить (і не мусить), тому добір живе тут. Пошуку не
    потрібно: запис документа точний, одиниці беруться за меткою.

    -> доповнена відповідь або та сама, якщо додати нічого.
    """
    if not tier_chat.is_procedure_question(question):
        return answer
    if _CHAIN_REFUSED not in (answer or ""):
        return answer
    for msg in reversed(history or []):
        if not isinstance(msg, dict) or msg.get("role") != "assistant":
            continue
        prev = tier_chat._history_text(msg.get("content")) or ""
        doc_id = tier_chat._doc_record_id(prev.splitlines())
        addr = tier_chat._quoted_address(prev.splitlines())
        if not (doc_id and addr):
            continue
        lines = tier_chat._outline_lines(
            tier_chat._fetch_sibling_units(doc_id, addr), addr)
        if not lines:
            return answer
        # Кажемо ВГОЛОС, що документ узятий із попереднього ходу: інакше це
        # виглядало б так, ніби система знайшла його на це питання.
        head = ("Прямої відповіді одним пунктом немає. Але документ із "
                "попередньої відповіді описує порядок цілком:")
        block = "\n\n" + head + "\n" + "\n".join(lines[1:])
        # КАРТА ЙДЕ ПЕРЕД БЛОКОМ ДЖЕРЕЛА, а не в кінець тексту.
        #
        # Перша версія дописувала в кінець -- і карта сідала ПІД «джерелом»,
        # тобто після згортки, де її ніхто не читає. Я цього спершу не
        # побачила, бо в перевірці різала вивід по «<details» і сама ж
        # відрізала те, що перевіряла.
        at = answer.find("\n\n<details")
        if at == -1:
            return answer.rstrip() + block
        return answer[:at].rstrip() + block + answer[at:]
    return answer


def _direct_unit_answer(question, history=None):
    """Пункт акта ПРЯМО ЗА МЕТКОЮ, без пошуку. -> текст або None.

    Прогін Андрія 28.08, другий хід: «як звучить пункт 1 цієї статті?» Слово
    «цієї» посилається на попередній хід, а нормативний ланцюг історії не
    бачить -- він пішов шукати «пункт 1 цієї статті» по всьому корпусу й
    знайшов пункт 1 статті 10-1 ІНШОГО закону (№ 3551-XII, про ветеранів), ще
    й із позначкою «слабко перетинається з питанням». Відповідь чесна за
    формою й не та за змістом.

    Тут пошуку не потрібно взагалі: якщо відомі акт і стаття, пункт дістається
    за меткою одиниці -- детерміновано, за мілісекунди, без моделі й без
    порогу. Акт і стаття беруться або з самого питання (людина їх назвала), або
    з попередньої відповіді в історії.

    None означає «цією дорогою не пройшли» -- далі працює ланцюг, як і раніше.
    """
    m = _ASKED_POINT.search(question or "")
    if not m:
        return None
    point = m.group(1)
    ident = article = None
    # 1. Акт і стаття, названі в самому питанні.
    own = _PREV_ACT.search(question or "")
    if own:
        ident, article = own.group(1).strip(), own.group(2).strip()
    else:
        art = re.search(r"статт[іяю]\s+([\d\-]+)", question or "", re.I)
        if art:
            article = f"Стаття {art.group(1)}"
        idm = re.search(r"(№\s*\d+[-/][\w\d]+|НД\s+ТЗІ\s*[\d.\-]+)",
                        question or "")
        if idm:
            ident = idm.group(1).strip()
    # 2. Чого не назвали -- беремо з попередньої нормативної відповіді.
    if not (ident and article):
        for msg in reversed(history or []):
            if not isinstance(msg, dict) or msg.get("role") != "assistant":
                continue
            prev = _PREV_ACT.search(tier_chat._history_text(msg.get("content")))
            if prev:
                ident = ident or prev.group(1).strip()
                article = article or prev.group(2).strip()
                break
    if not (ident and article):
        return None
    try:
        from . import normative_chain as _nc
    except ImportError:
        import normative_chain as _nc
    label = f"{article} / {point}"
    row = _nc._unit_by_label(ident, label)
    if not row or not (row.get("text") or "").strip():
        return None
    text = row["text"].strip()
    return ("\n".join([
        f"{_esc(ident)}, {_esc(row['label'])}",
        f"«{_esc(text)}»",
        "Це дослівна цитата з документа: одиниця взята за адресою, без "
        "пошуку.",
    ]) + _fmt_source_block(
        [f"нормативний акт: {ident}", f"адреса: {row['label']}",
         "дістано прямо за меткою одиниці (без пошуку й без моделі)"],
        "пункт за адресою"))


def rules_route(question):
    """Порядок перебору: діагностика → довідник → цитата → підрахунок → відмова.
    Явні сутності підрахунку (№, дата, «хто…») мають пріоритет — див. шапку."""
    low = question.lower()
    p = rules_params(question)
    if any(w in low for w in DIAG_WORDS):
        return "діагностика"
    # явне прохання про дослівний текст — цитата, навіть якщо в питанні є №
    #
    # АЛЕ НЕ ТОДІ, КОЛИ ПРОСЯТЬ НОРМУ. «Як звучить пункт 1 цієї статті?» --
    # прохання дослівного тексту, і воно потрапляло сюди, тобто в відмову
    # «цитувати накази не береться». А нормативні акти ми саме цитуємо, і
    # зробили це ходом раніше (прогін Андрія 28.08: дві суперечливі відповіді
    # в одній розмові).
    #
    # Ознаки нормативного питання: слово про одиницю акта (стаття, пункт,
    # частина, абзац), нормативний маркер або названий ідентифікатор акта.
    # Дорога «цитата» лишається для НАШИХ документів -- там відмова правдива.
    if any(w in low for w in QUOTE_WORDS) and not _asks_for_a_norm(question):
        return "цитата"
    if p["intent"] and (p["doc_number"] or p["date"] or p["name"]
                        or p["intent"] == "зведення_по_підрозділах"
                        or low.startswith("хто")):
        return "підрахунок"
    if any(w in low for w in REF_WORDS) and db.search_reference(question):
        return "довідник"
    # «скільки…» без розпізнаного intent — усе одно спроба підрахунку:
    # dispatch_count поверне None, і питання піде далі як «цитата»
    if p["intent"] or "скільки" in low or "кільк" in low:
        return "підрахунок"
    return "відмова"



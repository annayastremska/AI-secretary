#: Розпаковка контенту історії Gradio -- ОДНА копія, у `tiers.py`.
#:
#: Переїхала туди 27.08: історію тепер читають два місця -- перенесення слотів
#: тут і маршрутизатор на моделі там. Дві копії розійшлися б мовчки, а симптом
#: був би той самий, що вже раз ловили: історія «не читається» без помилки.
_history_text = tier_chat._history_text


# ── Перенесення слотів між ходами ───────────────────────────────────────────
#
# Замість склеювати попереднє питання з поточним в один рядок і сподіватись,
# що модель візьме потрібну половину (саме там 4B стабільно брала дату з
# ПЕРШОГО рядка), модель бачить РІВНО ОДНЕ питання, а порожні слоти
# добираються кодом з попереднього ходу. Детерміновано й без здогадок про
# те, «схоже це на уточнення чи ні».

# Які слоти взагалі має сенс тягнути для кожного наміру. Завдяки цьому
# «Хто у відпустці за квитком №301?» після питання з датою НЕ успадкує ту
# дату: для документ_за_номером date не в списку.
INTENT_SLOTS = {
    # `state` -- ВИМІР (відпустка / відрядження / обидва). Його тут не було, і
    # це давало найгіршу з можливих помилок -- підміну метрики без жодного
    # слова про підміну. Живий приклад Ані 28.08:
    #   «Хто зараз у відрядженні?» -> 1 особа (вимір deployment, правильно)
    #   «а завтра?»                -> 13 осіб «поза частиною (відпустка або
    #                                 відрядження)» -- дата успадкувалась, а
    #                                 вимір ТИХО розширився до обох.
    # Людина читає це як «за добу стало 13 у відрядженні». Дата переносилась,
    # бо вона у слотах; вимір -- ні, бо його у слотах не було взагалі.
    "хто_відсутній": ("date", "subdivision", "state"),
    "хто_повертається": ("date", "subdivision"),
    "зведення_по_підрозділах": ("date",),
    "документи_людини": ("name",),
    "документ_за_номером": ("doc_number",),
}
SLOT_KEYS = ("intent", "date", "subdivision", "name", "doc_number", "state",
             # МІСЦЕ -- слот від 29.08: без нього репліка «а хто ще там?»
             # після питання про Житомир не має чого успадкувати.
             "place")
STATE_RE = re.compile(r"<!--slots:(.*?)-->", re.S)


def _state_marker(params):
    """Розпізнані слоти -- у саме повідомлення бота, прихованим HTML-коментарем.
    Так зберігається принцип «стану не тримаємо, все читається з history»:
    окремий gr.State не потрібен, а користувач цього не бачить."""
    keep = {k: params.get(k) for k in SLOT_KEYS}
    # «-->» усередині значення (могло прийти з питання через модельний слот)
    # закрило б HTML-коментар достроково і вивалило решту в розмітку.
    # Заміна на > ЛИШЕ всередині JSON-рядка: json.loads поверне той
    # самий текст, а в коментарі послідовності «-->» більше немає.
    payload = json.dumps(keep, ensure_ascii=False).replace("-->", "--\\u003e")
    return f"\n<!--slots:{payload}-->"


# Питання складається практично лише з числа: «а 22?», «22», «а 15-го?»,
# «а 22 числа?». Саме така вимога і рятує від хибних спрацювань: у «а по 2
# роті?» після числа стоїть іменник, тож воно сюди не підходить і 2-м числом
# не стане.
BARE_DAY_RE = re.compile(
    r"^\W*(?:а|і|й|та|ну)?\s*(\d{1,2})\s*(?:-?[гґ]о|-?[ає]|числа)?\s*[?!.]*$")


#: ВІДНОСНА дата від попереднього ходу: «а наступного дня», «через 2 дні»,
#: «днем раніше». Це не те саме, що BARE_DAY_RE (там названо число) і не те
#: саме, що «завтра» (те від СЬОГОДНІ, і його вміє extract_date).
_NEXT_DAY_RE = re.compile(
    r"наступн\w*\s+дн\w*|на\s+наступний\s+день|днем\s+пізніше|"
    r"на\s+день\s+пізніше", re.IGNORECASE)
_PREV_DAY_RE = re.compile(
    r"попередн\w*\s+дн\w*|днем\s+раніше|на\s+день\s+раніше|"
    r"день\s+до\s+того|за\s+день\s+до\s+цього", re.IGNORECASE)
_IN_N_DAYS_RE = re.compile(r"через\s+(\d{1,2})\s*(?:дн|дoб|доб)", re.IGNORECASE)

#: Маркер «дата тут ВІДНОСНА» -- ширший за форми, які ми вміємо порахувати.
#: Потрібен як СТРАХОВКА: якщо форму не порахували, дату не переносимо
#: буквально, а віддаємо хід тому ярусу, що читає розмову. Інакше «а
#: наступного дня» тихо відповідає за той самий день.
_RELATIVE_DATE_HINT = re.compile(
    r"наступн|попередн|через\s+\d+\s*(?:дн|тижн|місяц|доб)|"
    r"днем\s+(?:раніше|пізніше)|післязавтра|позавчора|"
    r"на\s+день\s+(?:раніше|пізніше)", re.IGNORECASE)


def _shift_from_prev(question, prev_date):
    """«а наступного дня» після відповіді за 2026-10-10 -> 2026-10-11.

    Знайдено власною регресією 28.08. Доти цей зсув робила МОДЕЛЬ: репліка не
    давала дати, слотів після дороги каталогу не було, дата лишалась порожньою,
    хід ішов у гілку уточнення й там його рятував модельний маршрутизатор із
    розмовою -- за 15 с. Коли дорога каталогу почала лишати слоти, порожня дата
    зникла: перенесення підставляло ТОЙ САМИЙ день, і «а наступного дня»
    відповідало за 2026-10-10, не сказавши, що нічого не зсунуло.

    Тому зсув робиться тут, детерміновано й за частки секунди. Форми, яких
    немає в переліку, лишають дату порожньою (див. `_RELATIVE_DATE_HINT`) --
    тоді хід, як і раніше, дістається моделі.
    """
    if not prev_date:
        return None
    base = extract_date(prev_date if isinstance(prev_date, str)
                        else str(prev_date))
    if not base:
        return None
    try:
        day = datetime.date.fromisoformat(base)
    except ValueError:
        return None
    text = question or ""
    m = _IN_N_DAYS_RE.search(text)
    if m:
        return (day + datetime.timedelta(days=int(m.group(1)))).isoformat()
    if _NEXT_DAY_RE.search(text):
        return (day + datetime.timedelta(days=1)).isoformat()
    if _PREV_DAY_RE.search(text):
        return (day - datetime.timedelta(days=1)).isoformat()
    return None


def _refine_day(question, prev_date):
    """«а 22?» після відповіді за 23 травня -> 2026-05-22.

    День без місяця extract_date розпізнати не може, тому доти дата
    успадковувалась цілком: на «а 22?» чат відповідав за попереднє число і
    навіть не показував, що не зрозумів. Місяць і рік беремо з попередньої
    дати -- людина уточнює день у межах уже названого місяця.
    """
    if not prev_date:
        return None
    m = BARE_DAY_RE.match((question or "").strip().lower())
    if not m:
        return None
    try:
        base = datetime.date.fromisoformat(prev_date)
        return str(base.replace(day=int(m.group(1))))
    except ValueError:
        return None          # 31 квітня і подібне -- не вигадуємо


def _last_user_question(history):
    """Попереднє питання -- як позначений контекст для наміру.

    Береться останнє питання, у якому намір ВЗАГАЛІ Є: ланцюжок уточнень
    («а 23 травня?» -> «а 22?») інакше давав моделі для контексту такий самий
    безнамірний рядок, і успадковувати їй було нізвідки -- на «а 22?» намір
    злітав на дефолтний. Якщо з наміром не знайшлось, беремо просто останнє.
    """
    questions = [
        _history_text(m.get("content")).strip()
        for m in (history or [])
        if isinstance(m, dict) and m.get("role") == "user"
        and _history_text(m.get("content")).strip()
    ]
    for text in reversed(questions):
        if rules_params(text)["intent"]:
            return text
    return questions[-1] if questions else None


def _params_input(question, history):
    """Вхід для витягу параметрів: два ПОЗНАЧЕНІ рядки, а не склеєний текст.

    Саме позначення вирішило обидві поломки склейки на 4B: модель перестала
    брати дату з першого рядка (тепер сутності явно з «Поточне:») і почала
    успадковувати намір там, де в питанні його немає (з «Попереднє:»).
    Перевірено: з prev=«хто повертається» намір хто_повертається, з
    prev=«хто відсутній» -- хто_відсутній, дата в обох з поточного рядка.
    """
    prev = _last_user_question(history)
    if not prev:
        return question
    return f"Попереднє: {prev}\nПоточне: {question}"


def _read_state(history):
    """Слоти з останньої відповіді бота, де вони були."""
    for m in reversed(history or []):
        if not isinstance(m, dict) or m.get("role") != "assistant":
            continue
        found = STATE_RE.search(_history_text(m.get("content")))
        if found:
            try:
                return json.loads(found.group(1))
            except ValueError:
                return None
    return None


def _drop_invented_name(params, question):
    """Модель бачили на тому, що підставляє «Петренко» з прикладу в
    системному промпті (з датами та сама історія -- тому дата тепер береться
    ЛИШЕ з правил, див. answer()). Ім'я, перших
    чотирьох літер якого немає в питанні, -- вигадане (перевірка префіксом,
    бо ПІБ у питанні стоїть у відмінку: «про Усика» -> «Усик»)."""
    n = (params.get("name") or "").strip()
    if n and n[:4].lower() not in question.lower():
        params = dict(params)
        params["name"] = None
    return params


def _carry_over(params, prev):
    """Порожні слоти -- з попереднього ходу, але лише ті, що доречні наміру."""
    if not prev:
        return params
    out = dict(params)
    if not out.get("intent"):
        out["intent"] = prev.get("intent")
    for slot in INTENT_SLOTS.get(out.get("intent"), ()):
        if not out.get(slot):
            out[slot] = prev.get(slot)
    return out


def _answers_clarification(question):
    """Чи це справді ВІДПОВІДЬ на уточнення, а не нове питання.

    Уточнення завжди просить конкретну сутність -- дату або людину. Тому
    відповіддю вважаємо лише репліку, що цю сутність несе. Інакше людина,
    яка після «За яку дату рахувати?» ставить наступне питання («а скільки
    у відпустці?»), потрапляла в глухий кут: репліку зараховували як
    відповідь, дати в ній не було, а повторно перепитувати вже не можна --
    і замість відповіді йшла жорстка відмова.
    """
    return bool(extract_date(question) or extract_doc_number(question)
                or extract_name(question))


def _merge_clarification(question, history):
    """Попередня відповідь бота — уточнення? Склеїти з питанням до нього.
    Стану не тримаємо: все читається з history. Друге уточнення заборонене.

    Другий випадок -- коротке допитування без власного наміру («а 23
    травня?», «а по 2 роті?»): rules_params на ньому самому дає intent=None.
    Тоді шукаємо назад останнє повідомлення користувача, де намір був явний,
    і клеїмо їх -- інакше роутер/екстрактор параметрів бачать лише «а 23
    травня?» і підставляють дефолтний намір замість того, що мав на увазі
    користувач.

    Склейка лишилась ТІЛЬКИ для випадку «бот спитав -- людина відповіла»:
    там відповідь справді не має сенсу окремо від питання бота. Колишню
    другу гілку (склейка коротких уточнень через regex-гейт _is_followup)
    прибрано -- її замінило перенесення слотів (_carry_over вище). Гейт
    пропускав лише ISO-дати й номери, тож найприродніші форми («а 23
    травня?», «а по 2 роті?») повз нього не проходили, а те, що проходило,
    4B все одно псувала, беручи дату з першого рядка склеєного тексту."""
    msgs = []
    for m in history or []:
        role = m.get("role") if isinstance(m, dict) else None
        content = _history_text(m.get("content")) if isinstance(m, dict) else ""
        if role in ("user", "assistant") and content:
            msgs.append((role, content))
    if (msgs and msgs[-1][0] == "assistant"
            and msgs[-1][1].startswith(CLARIFY_MARK)
            and _answers_clarification(question)):
        prev_user = next((c for r, c in reversed(msgs[:-1]) if r == "user"), "")
        return f"{prev_user}\n{question}", True
    return question, False


def _as_report(text):
    """«Доповідаю: …» перед першим рядком відповіді. Уточнення лишається
    уточненням (це запит, не доповідь), решта — доповідь по формі."""
    if text.startswith(CLARIFY_MARK) or text.startswith(REPORT_MARK):
        return text
    head, sep, tail = text.partition("\n")
    # ВЛАСНУ НАЗВУ З МАЛОЇ НЕ ПИШЕМО.
    #
    # Правило «після Доповідаю: -- з малої» писалось під речення («12 осіб у
    # відпустці»), і на них воно правильне. Але перший рядок нормативної
    # відповіді -- це НАЗВА ДОКУМЕНТА з його номером у дужках, і після правки
    # 28.08 (назва більше не жирна) вона поїхала на екран як «про соціальний і
    # правовий захист військовослужбовців… (№ 2011-XII)». Назва акта -- власна
    # назва, і з малої вона читається як недогляд.
    #
    # Ознака точна й перевірна: рядок несе ідентифікатор акта в дужках. Це не
    # речення, а посилання, тому регістр лишається як у документі.
    if not _CITED_DOC_HEAD.search(head):
        head = head[0].lower() + head[1:] if head[:1].isupper() else head
    return f"{REPORT_MARK}: {head}{sep}{tail}"


#: Перший рядок відповіді -- посилання на акт: назва плюс його номер у дужках
#: («… (№ 2011-XII), Стаття 10-1 / 1»). Саме наявність номера в дужках
#: відрізняє посилання від речення.
_CITED_DOC_HEAD = re.compile(r"\((?:№|НД\s|наказ)[^)]{2,60}\)")


# ── Додаткові дороги нашої апки: каталог SQL-шаблонів і ярус 2 ──────────────
#
# Викликаються, коли сім функцій не впорались (dispatch повернув None) або
# маршрут -- «відмова». Порядок -- маршрутизація з tiers.py + vector_route.py:
# спершу каталог query_catalog.yaml правилами (SQL написаний людиною,
# звірений з базою), потім ВЕКТОРНИЙ ярус (найближчий шаблон за прикладами
# каталогу, мілісекунди, без моделі -- етап 3 плану), потім
# модель-класифікатор у ЗАКРИТИЙ перелік шаблонів того ж каталогу, потім
# вільний SELECT під рейками (read-only сесія, валідатор, LIMIT 200,
# таймаут 5 с, SQL у згортці).
# Не склалось -- None, і вище лишається чесна відмова.


def _fmt_source_block(source_lines, route_label):
    # html.escape замість самодільного replace("<", "&lt;"): & без
    # екранування дозволяє протягнути &lt;script&gt; як текст, який
    # наступний innerHTML-прохід перетворить назад на тег
    body = "<br>".join(_esc(s) for s in source_lines)
    return ("\n\n<details class=\"src\"><summary>джерело</summary>"
            + body + f"<br>дорога: {route_label}</details>")


def _catalog_tier(question):
    """Каталог шаблонів (правила з tiers.py: регекси, звірений SQL) -> текст
    або None. Детерміновано, без моделі."""
    progress.stage("rules")
    try:
        routed = tier_chat.rules_route(question)
    except Exception:
        routed = None
    if not routed:
        return None
    tid, params = routed
    try:
        text, source = tier_chat.run_template(tid, params)
    except Exception:
        return None
    # ДВІ РЕЧІ В ПИТАННІ -- сказати, що відповідаю про одну (блок F).
    #
    # Живе тут, а не в `run_template`: там немає тексту питання, а рішення
    # «це порівняння» приймається саме по тексту. Декомпозиції запиту немає й
    # до демо не буде -- але мовчання прибрано: тиха відповідь на половину
    # питання гірша за уточнення, бо перевірити її людина не може.
    note = tier_chat.two_entities_note(question, _answered_about(params))
    if note:
        text = text.rstrip() + "\n" + "\n".join(note)
    return (text + _fmt_source_block(source, f"каталог шаблонів ({tid})")
            + _slots_of_catalog(tid, params))


#: Шаблони каталогу -> намір старої дороги підрахунку. Потрібно рівно для
#: ПЕРЕНЕСЕННЯ слотів у наступний хід: `_carry_over` тягне слоти за наміром.
_CATALOG_INTENT = {
    "count_by_state_on_date": "хто_відсутній",
    "count_by_state_period": "хто_відсутній",
    "list_by_state": "хто_відсутній",
    "count_by_state_in_subdivision": "хто_відсутній",
    "list_by_state_in_subdivision": "хто_відсутній",
    "absent_breakdown_on_date": "зведення_по_підрозділах",
    "subdivision_breakdown": "зведення_по_підрозділах",
    "returning_on_date": "хто_повертається",
    "person_status": "документи_людини",
    "doc_by_number": "документ_за_номером",
}


def _slots_of_catalog(tid, params):
    """Слоти ходу, який відповів ДОРОГОЮ КАТАЛОГУ -- у те саме приховане поле,
    що й на старій дорозі підрахунку.

    Відсутня ланка, знайдена живим прогоном 28.08. Маркер слотів дописувала
    ЛИШЕ стара дорога (`route == "підрахунок"`), тому діалог, що почався на
    каталозі, лишав наступний хід без пам'яті взагалі:

        «Хто зараз у відрядженні?» -> каталог (`list_by_state`), слотів немає
        «а завтра?»                -> переносити нічого, вимір падає в дефолт
                                      `absent` -> 1 особа стає 13.

    Тобто це не «модель не пам'ятає»: половина доріг просто не залишала по
    собі сліду для наступного ходу. Перенесення в один бік уже було
    (`_read_state` читає будь-який маркер) -- бракувало запису.

    Порожній рядок для шаблонів, яких немає в `_CATALOG_INTENT`: намір
    вигадувати не будемо, а слот без наміру `_carry_over` однаково не візьме.
    """
    p = params or {}
    intent = _CATALOG_INTENT.get(tid)
    if not intent:
        # НАСЕЛЕНИЙ ПУНКТ зберігаємо навіть БЕЗ наміру.
        #
        # Свого наміру в `INTENTS` місце не має навмисно: цей перелік --
        # закрита схема відповіді МОДЕЛІ, і додати туди значення означало б
        # новий замір маршрутизації перед демо. А слот потрібен уже: без нього
        # репліка «а хто ще там?» не має чого успадкувати.
        #
        # Намір лишається порожнім, і це чесно: перенесення слотів за наміром
        # (`_carry_over`) місця не торкається, його читає окрема гілка в
        # `answer()` -- рівно по слоту `place`.
        if tid == "list_by_place" and p.get("place"):
            return _state_marker({"place": p["place"]})
        return ""
    date = p.get("on_date") or p.get("date_from")
    return _state_marker({
        "intent": intent,
        "date": str(date) if date else None,
        "subdivision": p.get("subdivision"),
        "name": p.get("name"),
        "doc_number": p.get("doc_number"),
        # Вимір -- головне, чого тут бракувало.
        "state": p.get("state"),
        # Пункт -- щоб «а хто ще там?» працювало й після відповіді про місце.
        "place": p.get("place"),
    })


def _answered_about(params):
    """Про що саме склалась відповідь -- людською мовою, для рядка про дві речі.

    Технічні імена параметрів тут не годяться: рядок читає людина, і `on_date`
    у ньому був би тією самою внутрішньою кухнею, на яку скаржився Денис (п. 25).
    """
    p = params or {}
    for key, label in (("on_date", "дата"), ("date_from", "початок періоду"),
                       ("doc_number", "документ"), ("subdivision", "підрозділ"),
                       ("name", "особа")):
        if p.get(key):
            return f"{label} {p[key]}"
    return "перше зі згаданого"


def _vector_tier(question):
    """Векторний ярус (chat_gradio/vector_route.py, задача 3.3): питання ->
    найближчий шаблон каталогу за прикладами, мілісекунди, без моделі.
    Вектори дають лише id шаблону -- параметри витягуються правилами
    (tiers.params_for_template). None -> питання їде далі (модель -> ярус
    2): нижче порога, ярус вимкнено (немає ваг) або обов'язковий параметр
    не витягся."""
    progress.stage("vector")
    # агрегати (середнє, мін/макс...) каталог не вміє -- те саме правило,
    # що в rules_route: пропустити в ярус 2, а не тягнути в схожий шаблон
    if tier_chat._AGGREGATE.search(question.lower()):
        return None
    try:
        tid, score = tier_vector.vector_route(question)
    except Exception:
        return None
    if tid is None or tid not in tier_chat._CATALOG:
        return None
    t = tier_chat._CATALOG[tid]
    if tid == "smalltalk":
        # розмовний маршрут (задача 3.5): фіксована відповідь кодом --
        # без SQL, без бази і без моделі («дякую» не їде в 27B на 43 с)
        return (_esc(t["refusal"].strip())
                + _fmt_source_block(
                    [f"шаблон каталогу: smalltalk ({t['title']})",
                     "SQL немає: розмовна фраза, відповідь фіксована кодом"],
                    f"розмовний маршрут (вектори, бал {score:.2f})"))
    try:
        params = tier_chat.params_for_template(tid, question)
    except Exception:
        return None
    if params is None:
        return None
    try:
        text, source = tier_chat.run_template(tid, params)
    except Exception:
        return None
    return text + _fmt_source_block(
        source, f"каталог шаблонів, обрано векторним ярусом "
                f"({tid}, бал {score:.2f})")


# Позначка «модельна відмова»: питання не про дані бази -- ярус 2 після
# цього не пробуємо (нема сенсу платити ще один виклик моделі за SELECT,
# якому нема з чого вийти).
_MODEL_REFUSED = object()

#: Назви успадкованих параметрів -- людською мовою. Технічні імена (`on_date`,
#: `date_from`) у відповіді читались би як помилка: це рівно п. 25 звіту
#: Дениса, де назовні вилазить внутрішня кухня.
CARRIED_LABEL = {
    "state": "стан (відпустка / відрядження)",
    "on_date": "дата",
    "date_from": "початок періоду",
    "date_to": "кінець періоду",
    "subdivision": "підрозділ",
    "name": "прізвище",
    "doc_number": "номер документа",
}


def _model_catalog_tier(question, history=None):
    """Друга спроба ярусу 1: модель-класифікатор у ЗАКРИТИЙ перелік шаблонів
    каталогу (tiers.model_route). Модель лише обирає шаблон і параметри --
    SQL і текст відповіді лишаються кодом. -> текст, _MODEL_REFUSED або None
    (None = далі пробуємо ярус 2)."""
    if not (model_available() and tier_chat._get_model() is not None):
        return None
    progress.stage("model_catalog")
    try:
        routed = tier_chat.model_route(question, history)
    except Exception:
        return None
    if not routed:
        return None
    tid, params = routed
    if tid == "відмова":
        return _MODEL_REFUSED
    if tid == "вільний_sql":
        return None
    try:
        text, source = tier_chat.run_template(tid, params)
    except Exception:
        return None
    # УСПАДКОВАНЕ З РОЗМОВИ -- ВИДИМИМ РЯДКОМ, перед джерелом.
    #
    # Правило продукту, а не зручність: якщо дата чи стан узяті з попереднього
    # питання, людина мусить це бачити. Інакше вона читає впевнену відповідь і
    # не знає, що система дописала половину питання за неї -- а це саме той
    # клас помилок, який неможливо перевірити оком (п. 1 і п. 11 звіту: «зріз
    # злетів», а на екрані два числа виглядають як брехня).
    #
    # Список приходить від маршрутизатора вже перевіреним кодом: там лишились
    # тільки ті назви, що справді є у параметрах і НЕ названі в самому питанні.
    carried = (params or {}).get("_carried") or []
    if carried:
        text += ("\n\n⚠️ узято з попереднього питання: "
                 + ", ".join(_esc(CARRIED_LABEL.get(c, c)) for c in carried)
                 + ". Якщо мали на увазі інше — напишіть це в питанні.")
    return text + _fmt_source_block(
        source, f"каталог шаблонів, обрано моделлю-класифікатором ({tid})")


def _tier2_tier(question):
    """Ярус 2: вільний SELECT під рейками (read-only, валідатор, LIMIT 200,
    таймаут 5 с, SQL у згортці) -> текст або None.

    Ярус УВІМКНЕНИЙ за домовленістю із замовницею: немає підходящого шаблона --
    модель складає запит сама, під рейками. Вимикається лише явно
    (`CHAT_FREE_SQL=0`), якщо на конкретному показі потрібні лише перевірені
    шаблони. Рейки й причини -- біля прапорця `FREE_SQL_ENABLED` у tiers.py."""
    if not tier_chat.FREE_SQL_ENABLED:
        return None
    if not (model_available() and tier_chat._get_model() is not None):
        return None
    progress.stage("tier2")
    try:
        text, source = tier_chat.tier2_answer(question)
    except Exception:
        return None
    # ОЗНАКА -- ДЖЕРЕЛО, а не перший рядок тексту.
    #
    # Тут стояло `text.startswith("Відповідь на нешаблонний запит")`, і 29.08 я
    # цей рядок прибрала з подачі (він казав людині «перевірте джерело у
    # згортці» замість самої відповіді). Перевірка перестала спрацьовувати
    # МОВЧКИ: ярус віддавав правильну відповідь, ця гілка її не впізнавала й
    # повертала None, а питання падало у відмову. Тобто косметична правка
    # подачі вимкнула цілий ярус.
    #
    # Джерело для цього надійніше за текст: його ставить сам `tier2_answer`
    # першим рядком src, і воно не залежить від того, як складена відповідь.
    marker = "НЕШАБЛОННИЙ ЗАПИТ"
    if text and any(marker in str(x) for x in (source or [])):
        return ("⚠️ нешаблонний запит: SQL склала модель, виконано "
                "read-only з валідатором\n" + text
                + _fmt_source_block(source, "ярус 2 (вільний SELECT)"))
    return None


# Ярус 2 при відмові вмикається лише для питань, які взагалі схожі на
# питання про дані бази: «Яка погода завтра?» не має платити хвилину
# модельного часу за спробу скласти SELECT, якому нема з чого вийти.
_DBISH = re.compile(
    r"відпуст|відрядж|документ|наказ|факт|званн|особ|людей|осіб|черг|"
    r"переві|підрозділ|баз[аіи]|скільки|хто\b|реєстр", re.I)


#: Номер звернення у ВІДПОВІДІ бота (та сама форма, що ставить `_with_request_id`).
_PREV_ID = re.compile(r"звернення:?\s*([0-9a-f]{6})")


def _how_previous_answer_was_made(history):
    """«Звідки ти це знаєш?» без імені -> як склалась ПОПЕРЕДНЯ відповідь.

    п. 18 звіту Дениса: на це питання чат відповідав тим самим текстом, що на
    питання про погоду в Києві («не лягає на жодну з доріг»). Він же назвав
    чому це погано: для обліку особового складу «звідки цифра» -- нормальне
    робоче питання.

    ДАНІ ДЛЯ ВІДПОВІДІ ВЖЕ Є. Кожен хід пише машинний слід (`trace.py`): дорога,
    шаблон, SQL шаблону, скільком рядків повернула база, скільком це тривало.
    Бракувало лише дороги до нього -- і саме її просив Денис: «щоб по скріну
    можна було автоматично прогнати аналіз».

    Ключ -- номер звернення з ПОПЕРЕДНЬОЇ відповіді бота: він у ній видимим
    рядком. Немає номера або сліду -- кажемо це прямо, а не вигадуємо.
    """
    prev = None
    for m in reversed(history or []):
        if not isinstance(m, dict) or m.get("role") != "assistant":
            continue
        found = _PREV_ID.search(_history_text(m.get("content")) or "")
        if found:
            prev = found.group(1)
            break
    if not prev:
        return ("Не можу показати, як склалась попередня відповідь: у розмові "
                "немає жодної моєї відповіді з номером звернення. Спитайте "
                "щось про облік, і я покажу шлях відповіді."
                + footer("походження відповіді"))
    row = trace.find(prev)
    if not row:
        return (f"Сліду для звернення {prev} немає — можливо, апку "
                f"перезапускали після того ходу. Номер лишається дійсним для "
                f"журналу." + footer("походження відповіді"))
    lines = [f"**Доповідаю:** ось як склалась попередня відповідь "
             f"(звернення {prev})."]
    lines.append(f"**Дорога:** {_esc(row.get('road') or 'не визначена')}.")
    steps = [st for st in (row.get("steps") or []) if st.get("template")]
    if steps:
        st = steps[0]
        lines.append(f"**Шаблон:** {_esc(st.get('title') or '')} "
                     f"({_esc(st.get('template'))}).")
        if st.get("params"):
            lines.append("**Параметри:** "
                         + _esc(json.dumps(st["params"], ensure_ascii=False,
                                           default=str)) + ".")
        if st.get("rows") is not None:
            lines.append(f"**Рядків із бази:** {st['rows']}.")
    else:
        lines.append("**Шаблон:** цією дорогою запит до бази не робився "
                     "(правила, довідка або уточнення).")
    if row.get("seconds") is not None:
        lines.append(f"**Тривало:** {row['seconds']} с.")
    lines.append("Повний слід цього ходу: "
                 f"`python demos/upload_app/trace_lookup.py {prev}`.")
    return "\n".join(lines) + footer("походження відповіді")


def _extra_tiers(question, history=None):
    """Порядок доріг (етап 3 плану): каталог правилами → ВЕКТОРИ (найближчий
    шаблон за прикладами, мс) → модель-класифікатор у закритий перелік →
    вільний SELECT (ярус 2). Векторний ярус стоїть ДО гейта _DBISH: він
    безкоштовний, а розмовні фрази («дякую») інакше не дійшли б до свого
    маршруту. Модельна «відмова» зупиняє перебір: питання не про дані бази,
    ярус 2 не смикаємо."""
    # ПИТАННЯ ПРО ДОКАЗ БЕЗ ІМЕНІ -- перед усіма ярусами.
    #
    # «Звідки ти це знаєш?» не має ні шаблона, ні імені, тому всі яруси його
    # пропускали й лишалась відмова -- та сама, якою чат відповідає на питання
    # про погоду (п. 18 звіту). Відповідь тут не в базі, а в СЛІДІ попереднього
    # ходу, і тому вона потребує історії, а не шаблона.
    if tier_chat.is_evidence_question(question) and not rules_params(
            question)["name"]:
        return _how_previous_answer_was_made(history)

    out = _catalog_tier(question)
    if out is not None:
        return out
    out = _vector_tier(question)
    if out is not None:
        return out
    if not _DBISH.search(question):
        return None
    out = _model_catalog_tier(question, history)
    if out is _MODEL_REFUSED:
        return None
    if out is not None:
        return out
    return _tier2_tier(question)



# Явно деструктивні прохання ріжемо правилами ще ДО моделі: чат нічого не
# змінює в базі за визначенням (read-only), і чесно про це каже.
#: РОЗШИРЕНО 28.08 за знахідкою Андрія й власним заміром.
#:
#: Він поміряв на п'яти проханнях змінити дані: відмовила там, де мусила, 1 із
#: 5. Я переміряла на семи, живцем: **2 із 7**. Ловились «видали» і «зміни»,
#: не ловились «постав», «онови», «додай», «скасуй», «виправ» -- і тоді
#: «Онови номер документа 207» їхало в `doc_by_number` і показувало документ,
#: а «Скасуй документ №118» -- у підрахунок.
#:
#: ДАНИМ ЦЕ НЕ ЗАГРОЖУВАЛО, і це перевірено, а не припущення: чат ходить у базу
#: користувачем `milidoc_readonly`, а ярус вільного SQL має валідатор (один
#: SELECT, без DML, allowlist таблиць). Тобто дефект був у ОЧІКУВАННЯХ: людина
#: просить змінити, бачить у відповідь зміст документа й читає це як «зробив».
#: На демо це найгірше з можливих прочитань.
#:
#: Дієслова перелічені явно, у наказовій формі, і кожне -- прохання ДІЇ над
#: даними. Форми на «-в/-ла» («хто змінив документ?») сюди не входять: це
#: питання про минуле, а не прохання.
_DESTRUCTIVE = re.compile(
    r"вида[лл]|знищ|очист|drop\b|delete\b|truncate\b|update\b|insert\b|"
    r"зміни\s|встанов\s|підтверд[иь]\b|"
    r"\bпостав(?:те|мо)?\b|\bонови(?:те|мо)?\b|\bоновіть\b|"
    r"\bдодай(?:те|мо)?\b|\bскасуй(?:те|мо)?\b|\bвиправ(?:те|мо|и|іть)?\b|"
    r"\bперепиши(?:те|мо)?\b|\bзапиши(?:те|мо)?\b|\bзбережи(?:те|мо)?\b|"
    r"\bпризнач(?:те|мо|и|іть)?\b|\bзаміни(?:те|мо)?\b|"
    # «Приберіть» -- через «і», і саме на ньому впала перша версія
    # (`прибери(те|мо)?` такої форми не має). Наказовий спосіб в українській
    # дає і «-и», і «-іть», тому обидві гілки перелічені явно.
    r"\bприбер(?:и|іть|імо)\b",
    re.I)


def _month_span(text):
    """-> (номер місяця, позиція його назви) або (None, None).

    Позиція потрібна, щоб узяти день, який стоїть саме ПЕРЕД місяцем."""
    low = text.lower()
    for stem, num in MONTHS.items():
        at = low.find(stem)
        if at >= 0:
            return num, at
    return None, None


def extract_dates(question):
    """-> (on_date, date_from, date_to) як date або None.

    «зараз»/«сьогодні» -> сьогодні; ISO-дата; «6 травня [2026]» -> день;
    «у травні [2026]» -> місяць-період. Рік не назвали -- поточний рік
    (дефолт не вигадуємо з нічого: це явне правило, і воно ж озвучується
    датою зрізу у відповіді)."""
    low = question.lower()
    today = datetime.date.today()

    # ДВІ дати в питанні -- це період, а не зріз на першій із них.
    #
    # Було `re.search` (перший збіг) із поверненням `(d, None, None)`, тому
    # «з 2026-05-10 по 2026-10-10» ставало одним днем -- сім разів із семи у
    # перевірці Дениса перед демо. Причина, як він і припустив, одна й та сама,
    # що ламає порівняння двох сутностей: береться перший параметр, решта
    # відкидається без жодного слова.
    #
    # Перевернутий період повертається ЯК Є (`from > to`): мовчки поміняти межі
    # означало б відповісти на інше питання й не сказати про це. Назвати це
    # мусить той, хто рендерить.
    #
    # Замір Андрія на цій функції: дві дати = період, 4/8 -> 8/8.
    found = []
    for mm in re.finditer(r"\d{4}-\d{2}-\d{2}", question):
        try:
            found.append((mm.start(), datetime.date.fromisoformat(mm.group(0))))
        except ValueError:
            # Недійсна дата («2026-02-30») -- НЕ виняток і не дата.
            #
            # Доти тут стояв `fromisoformat` без try, і виняток летів
            # НЕПЕРЕХВАЧЕНИМ просто з правилового ярусу. Денис у п. 23 звіту
            # отримав правильну відповідь «це недійсна дата» саме тому, що
            # правила падали й питання йшло далі, до моделі. Тобто похвалена
            # поведінка була випадковою.
            #
            # Тепер падіння немає, але тиха втрата дати була б ГІРШОЮ за
            # падіння: питання «скільком у відпустці 2026-02-30» отримало б
            # відповідь про сьогодні. Тому недійсні дати збираються окремо, і
            # правиловий ярус відмовляє по них явно -- див. `impossible_dates`.
            pass
    for mm in re.finditer(r"\b(\d{1,2})\.(\d{1,2})\.(\d{4})\b", question):
        try:
            found.append((mm.start(), datetime.date(
                int(mm.group(3)), int(mm.group(2)), int(mm.group(1)))))
        except ValueError:
            pass
    found.sort()
    dates = [d for _pos, d in found]

    # «наступного дня після X» -- інакше віддається сам X (п. 2 звіту: питали
    # про 11-те, отримували 10-те). «Наступного дня» БЕЗ дати навмисно не
    # обробляється: її нема звідки взяти, і «сьогодні+1» був би вгадуванням.
    if dates and re.search(r"наступн\w*\s+дн\w*\s+(?:після|за)", low):
        return dates[0] + datetime.timedelta(days=1), None, None
    # Односторонні межі: «не пізніше X» -- це верхня МЕЖА, а не точка
    # (п. 3 звіту: «закінчується не пізніше 20-го» читалось як «саме 20-го»).
    if len(dates) == 1 and re.search(r"не\s+пізніше", low):
        return None, None, dates[0]
    if len(dates) == 1 and re.search(r"не\s+раніше", low):
        return None, dates[0], None
    if len(dates) >= 2:
        # ПОРІВНЯННЯ -- НЕ ПЕРІОД, і це знайдено власною ж правкою.
        #
        # Правка блоку A («дві дати = період») зробила з «порівняй 1 і 2
        # вересня» діапазон 01..02 -- тобто відповідь на ТРЕТЄ питання, якого
        # ніхто не ставив. До правки відповідь була про 1 вересня (п. 16
        # звіту), після -- про період; обидві неправильні, але друга гірша,
        # бо виглядає правдоподібніше.
        #
        # Тому при словах порівняння беремо ПЕРШУ дату як зріз, а те, що друга
        # відкинута, каже `two_entities_note` у відповіді.
        if is_comparison(question):
            return dates[0], None, None
        return None, dates[0], dates[1]
    if len(dates) == 1:
        return dates[0], None, None

    month, month_at = _month_span(low)
    # Рік -- ЧОТИРИ цифри, будь-які, а не лише «20xx».
    #
    # Було `\b(20\d{2})\b`, і на «1 січня 1990» цей регекс року просто НЕ
    # БАЧИВ: підставлявся поточний, тобто чат тихо відповідав про іншу дату.
    # Я цю саму помилку вже виправляла того дня -- але в app.extract_date, а
    # справжній шлях питання після сусідньої правки йде сюди. Дві правки
    # одного дня погасили одна одну, і це знайшов другий адверсарний прохід,
    # не я.
    year_m = re.search(r"\b(1[89]\d{2}|20\d{2}|21\d{2})\b", question)
    year = int(year_m.group(1)) if year_m else today.year
    if month:
        # День -- ЛИШЕ той, що стоїть безпосередньо перед назвою місяця.
        #
        # Було `\b(\d{1,2})(?:-?го)?\s+[а-яіїєґ]*` по всьому питанню, тобто
        # перша ж пара «цифра + слово». На «Хто відсутній у 2 роті 28 серпня
        # 2026?» днем ставало **2** (з «2 роті»), і чат упевнено відповідав
        # про 2 серпня -- інша дата, інші люди, з виглядом правильної
        # відповіді. Знайдено живим прогоном 26.08, коли стара дорога
        # навчилась підрозділам.
        day_m = re.search(r"(\d{1,2})(?:-?го)?\s+$", low[:month_at])
        day = None
        if day_m and 1 <= int(day_m.group(1)) <= 31:
            day = int(day_m.group(1))
        if day:
            try:
                return datetime.date(year, month, day), None, None
            except ValueError:
                pass
        first = datetime.date(year, month, 1)
        last = (datetime.date(year + (month == 12), month % 12 + 1, 1)
                - datetime.timedelta(days=1))
        return None, first, last

    if "зараз" in low or "сьогодні" in low or "на даний момент" in low:
        return today, None, None

    # Відносні вирази. Без них «рік тому» тихо ставало СЬОГОДНІ, і чат на
    # питання про минуле впевнено віддавав сьогоднішній перелік (ворожий
    # прохід 26.08). Той самий клас, що «1 січня 1990» -> поточний рік.
    if "вчора" in low or "учора" in low:
        return today - datetime.timedelta(days=1), None, None
    if "позавчора" in low:
        return today - datetime.timedelta(days=2), None, None
    m = re.search(r"(\d+)?\s*(рік|року|роки|років|місяц\w*|тижн\w*|"
                  r"тиждень|дн\w*|день)\s+тому", low)
    if m:
        count = int(m.group(1) or 1)
        unit = m.group(2)
        if unit.startswith(("рік", "року", "роки", "років")):
            days = 365 * count
        elif unit.startswith("місяц"):
            days = 30 * count
        elif unit.startswith(("тижн", "тиждень")):
            days = 7 * count
        else:
            days = count
        return today - datetime.timedelta(days=days), None, None
    if "минулого року" in low:
        return None, datetime.date(today.year - 1, 1, 1), \
               datetime.date(today.year - 1, 12, 31)
    if "минулого місяця" in low:
        first = datetime.date(today.year, today.month, 1)
        last_prev = first - datetime.timedelta(days=1)
        return None, datetime.date(last_prev.year, last_prev.month, 1), last_prev
    return None, None, None


def extract_state(question):
    low = question.lower()
    # Обидва стани в одному питанні («у відпустці І у відрядженні») -- це
    # питання про відсутніх узагалі. Доти вигравав перший `if`, і відповідь
    # тихо була лише про відпустки (ворожий прохід 26.08).
    if re.search(r"відпуст", low) and re.search(r"відрядж", low):
        return "absent"
    if re.search(r"відпуст", low):
        return "leave"
    if re.search(r"відрядж", low):
        return "deployment"
    if re.search(r"відсутн|поза частин", low):
        return "absent"
    return None


#: ІДЕНТИФІКАТОР НОРМАТИВНОГО АКТА -- не номер нашого облікового документа.
#:
#: Знайдено прогоном Андрія 28.08: «процитуй пункт 1 документа (№ 2011-XII)»
#: отримало «не знайшла документа з номером №2011 у базі». Цифри збігаються
#: випадково: `№ 2011-XII` -- це номер ЗАКОНУ, а 2011 у нас був би номером
#: відпускного квитка. Питання про акт поїхало шукати обліковий документ.
#:
#: Форми беруться з живої бази (`documents.doc_identifier`, 44 нормативних):
#:   № 2011-XII, № 550-XIV, № 3543-XII   -- закони, римський хвіст
#:   № 1153/2008, № 80/94-ВР             -- укази й постанови, рік через слеш
#:   НД ТЗІ 1.4-001-2000                 -- нормативні документи ТЗІ
#:   наказ № 606 від 20.11.2017          -- накази з датою видання
#:
#: Наші ж номери -- це просто цифри (207, 1077, 118) і подекуди з шумом OCR
#: («№ 3О4» з літерою О), і про них є окрема чесна відмова.
_ACT_IDENT = re.compile(
    r"""№\s*\d+\s*(?:                 # номер, за яким іде ознака АКТА:
            -\s*[IVXLC]+\b            #   римський хвіст: 2011-XII
          | /\s*\d{2,4}\b             #   рік через слеш: 1153/2008
        )
      | НД\s+ТЗІ\s*[\d.\-]+           # НД ТЗІ 1.4-001-2000
      | наказ\w*\s*№\s*\d+\s*від\s*\d # наказ № 606 від 20.11.2017
    """, re.IGNORECASE | re.VERBOSE)


def is_act_identifier(question):
    """Чи в питанні названий ІДЕНТИФІКАТОР нормативного акта (а не номер
    нашого документа)."""
    return bool(_ACT_IDENT.search(question or ""))


def extract_doc_number(question):
    """Номер НАШОГО облікового документа з питання. -> рядок або None.

    Ідентифікатор нормативного акта тут навмисно НЕ повертається: інакше
    питання про закон їде в шаблон «документ за номером» і отримує впевнене
    «такого номера в базі немає» -- відповідь про іншу сутність.
    """
    # «№ 109», «документ 204», «документі №473»
    if is_act_identifier(question):
        return None
    m = re.search(r"№\s*([\w\d]+)", question)
    if m:
        return m.group(1)
    m = re.search(r"документ[а-яіїєґ]*\s+(\d+)", question, re.I)
    if m:
        return m.group(1)
    return None



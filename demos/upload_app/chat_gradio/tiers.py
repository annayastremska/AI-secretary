def _names_with_count(params, n):
    """Перелік осіб ПОРУЧ ІЗ ЧИСЛОМ -- або рядок про те, як його отримати.

    Вимога Ані 28.08: «модель має повертати не тільки число, а і перелік людей
    по пунктах». Причина продуктова, а не косметична: «1 особа у відпустці» без
    прізвища неможливо перевірити, а секретареві потрібне саме прізвище, щоб
    подзвонити.

    ГОЛОВНЕ ТУТ -- ЗВІРКА. Перелік бере дані ІНШИМ запитом (`list_by_state`),
    ніж число (`count_by_state_on_date`), а це рівно те місце, де в п. 12 звіту
    розійшлись «9 людей» і «10 рядків». Тому кількість імен порівнюється з
    числом, і розбіжність КАЖЕТЬСЯ вголос. Тихо показати перелік, довший за
    власну цифру, -- значить покласти суперечність на один екран.
    """
    if not n:
        return []
    if n > NAMES_WITH_COUNT:
        return [f"Поіменно не показую: {_people(n)} — це задовгий перелік. "
                f"Спитайте «покажи поіменно», якщо потрібні прізвища."]
    day = params.get("on_date") or params.get("date_from")
    if not day:
        return []
    try:
        t = _CATALOG["list_by_state"]
        rows = _run_template_sql(t["sql"], {
            "dims": params.get("dims"),
            "date_from": params.get("date_from") or day,
            "date_to": params.get("date_to") or day})
    except psycopg.Error:
        # Перелік -- додаткове знання. Немає його -- число лишається числом,
        # а не перетворюється на збій.
        return []
    if not rows:
        return []
    out, seen = ["Поіменно:"], set()
    for r in rows:
        # `.get`, а не `[...]`: форма рядка залежить від шаблону, і перелік --
        # додаткове знання, яке не має права валити основну відповідь. Зловив
        # власний тест: фікстура підмінила виконавця запиту, і рядки прийшли
        # від іншого шаблона.
        nm = _esc(r.get("name") or "")
        if not nm or nm in seen:
            continue
        seen.add(nm)
        out.append(f"- {nm} — {_esc(DIM_LABEL.get(r['dim'], r['dim']))}"
                   f", {_fmt_period(r)} ({_doc_ref(r)})")
    if len(seen) == 0:
        return []
    if len(seen) != n:
        out.append(f"⚠️ у переліку {_people(len(seen))}, а число вище — {n}. "
                   f"Це розбіжність між двома запитами, і я її не приховую: "
                   f"перевірте документи-джерела нижче.")
    return out



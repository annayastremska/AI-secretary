#: Рядки, що ВИГЛЯДАЮТЬ як дата, але датою не є. Дві форми -- ті самі, що
#: читає `extract_dates`: ISO і «дд.мм.рррр».
_DATE_SHAPED = (re.compile(r"\d{4}-\d{2}-\d{2}"),
                re.compile(r"\b(\d{1,2})\.(\d{1,2})\.(\d{4})\b"))


def _impossible_written_date(question):
    """«31 лютого 2026» -> рядок для повідомлення, або None.

    Словесна форма недійсної дати виглядає інакше, ніж цифрова, але дефект той
    самий: `extract_dates` тихо віддає ВЕСЬ місяць (2026-02-01 — 2026-02-28),
    тобто відповідає на інше питання й не каже про це. Для людини різниця між
    «за 31 лютого» і «за весь лютий» велика.
    """
    low = (question or "").lower()
    month, month_at = _month_span(low)
    if not month:
        return None
    m = re.search(r"(\d{1,2})(?:-?го)?\s+$", low[:month_at])
    if not m:
        return None
    day = int(m.group(1))
    if not 1 <= day <= 31:
        return None
    year_m = re.search(r"\b(\d{4})\b", low[month_at:])
    year = int(year_m.group(1)) if year_m else datetime.date.today().year
    try:
        datetime.date(year, month, day)
    except ValueError:
        return f"{day} {low[month_at:month_at + 12].split()[0]} {year}"
    return None


#: ПОПРАВКА до попереднього ходу, а не нове питання. Знайдено живим прогоном
#: Ані 28.08: після «Хто зараз у відрядженні?» → «а завтра?» (вимір розширився
#: до обох) вона написала «я питала про відрядження» -- і чат поїхав у
#: нормативний пошук, бо в репліці є слово «відрядження», а нормативного
#: корпусу воно теж стосується. 82.9 с і цитата про відрядження до державних
#: органів замість перерахунку того самого питання іншим виміром.
#:
#: Форми беруться ЯВНИМ переліком, а не «репліка з назвою виміру без наміру»:
#: широке правило забрало б назад «скільки максимум термін щорічної
#: відпустки?» у підрахунок людей -- рівно той дефект блоку E, який уже
#: закритий. Поправка мусить бути названа словами, інакше це не поправка.
_CORRECTION_RE = re.compile(
    r"(?:^|\W)(?:я\s+(?:пита\w+|каза\w+|мала?\s+на\s+увазі|мав\s+на\s+увазі)"
    r"|мене\s+цікав\w+|мова\s+(?:була\s+)?про|(?:й|і)шлося\s+про"
    r"|ні,?\s*(?:я\s+)?про|не\s+про\s+\w+,?\s*а\s+про)", re.IGNORECASE)


def is_correction(question):
    """Чи це ПОПРАВКА до попереднього ходу («я питала про відрядження»).

    Поправка не має власного наміру й власної дати: вона міняє РІВНО одну
    річ у питанні, яке вже прозвучало. Тому обробляється переносом слотів, а
    не як нове питання: намір, дата й підрозділ беруться з попереднього ходу,
    а те, що названо тут (вимір), бʼє успадковане."""
    return bool(_CORRECTION_RE.search(question or ""))


#: Слова, які означають ПОРІВНЯННЯ двох речей, а не діапазон. Різниця
#: принципова: «з 1 по 2 вересня» -- один період, «порівняй 1 і 2 вересня» --
#: два окремі питання.
_COMPARE_RE = re.compile(
    r"порівн\w*|відрізня\w*|різниц\w*|більше\s+чи\s+менше|"
    r"менше\s+чи\s+більше|більше,?\s+ніж|у\s+кого\s+більше|"
    r"стало\s+більше", re.IGNORECASE)


def is_comparison(question):
    """Чи питання просить ПОРІВНЯТИ дві речі."""
    return bool(_COMPARE_RE.search(question or ""))


def two_entities_note(question, answered_about):
    """Рядок «відповідаю про одне з двох» -- або [].

    Блок F звіту Дениса (п. 16-17): чотири різні формулювання порівняння дали
    чотири рази ту саму половину відповіді, і жодного слова про те, що друга
    половина відкинута. Він же звів це до правила: «береться перший параметр,
    решта відкидається без жодного слова».

    Декомпозиції запиту тут НЕМА і до демо не буде -- це окрема робота. Але
    МОВЧАННЯ прибрати треба вже: тиха відповідь на половину питання гірша за
    уточнення, бо перевірити її людина не може.
    """
    if not is_comparison(question):
        return []
    return [f"⚠️ у питанні дві речі для порівняння, а я відповідаю про одну: "
            f"{answered_about}. Порівнювати два значення я поки не вмію — "
            f"спитайте окремо про друге."]


def impossible_dates(question):
    """-> список рядків із питання, які схожі на дату, але датою не є.

    Навіщо окремою функцією. `extract_dates` тепер недійсну дату просто
    пропускає -- інакше `date.fromisoformat('2026-02-30')` летів би
    неперехваченим винятком із правилового ярусу (саме це й було до 27.08).
    Але тиха втрата дати ГІРША за падіння: «скільком у відпустці 2026-02-30»
    отримало б відповідь про сьогодні, з датою зрізу й джерелом, тобто
    впевнену відповідь на інше питання.

    Тому недійсна дата -- це не «немає дати», а окремий факт про питання, і
    правила по ньому ВІДМОВЛЯЮТЬ. Той самий принцип, що вже діє для номера
    документа з літерою О (`doc_number_warning`): ввід не виправляємо й
    схожого не підставляємо, а називаємо місце, де система не впевнена.
    """
    bad = []
    for mm in _DATE_SHAPED[0].finditer(question or ""):
        try:
            datetime.date.fromisoformat(mm.group(0))
        except ValueError:
            bad.append(mm.group(0))
    for mm in _DATE_SHAPED[1].finditer(question or ""):
        try:
            datetime.date(int(mm.group(3)), int(mm.group(2)), int(mm.group(1)))
        except ValueError:
            bad.append(mm.group(0))
    written = _impossible_written_date(question)
    if written:
        bad.append(written)
    return bad


def is_corpus_question(question):
    """Чи питання про САМ КОРПУС («що є в базі», «який період покривають»).

    Одна функція на два місця -- правила й дорогу «довідник». Доти умова
    жила лише в правилах, і коли модель відправляла питання в «довідник»,
    відповідь про склад бази прилітала на будь-що: «як отримати пароль для
    Wifi» отримало перелік документів по домейнах. Тобто гейт був у одному
    місці, а спрацьовував за двома.

    Гейт вузький навмисно: слово про покриття/склад ПЛЮС слово про базу або
    документи. «Який період відпустки у Ґоляша» під це не підпадає -- там про
    особу, а не про корпус.
    """
    low = (question or "").lower()
    if (re.search(r"покрива\w*|покритт\w*|який\s+період", low)
            and re.search(r"баз\w*|документ\w*|корпус\w*", low)):
        return True
    if re.search(r"(що|шо)\s+(взагалі\s+)?(є|лежить|міститься)\s+"
                 r"(у|в)\s+баз", low):
        return True
    if re.search(r"скільк\w*\s+(?:усього\s+)?документ", low):
        return True
    # Питання про ТЕМИ -- теж про корпус, а не про зміст норми: дорога
    # «довідник» не має цитувати закон у відповідь на «а на які теми вони».
    # Але ВІДПОВІДАЄ на нього інший шаблон, ніж на «що є в базі», тому сама
    # умова живе окремою функцією (`is_topic_question`).
    if is_topic_question(question):
        return True
    return False


#: ПИТАННЯ ПРО ПОСЛІДОВНІСТЬ ДІЙ, а не про окреме число чи означення.
#:
#: Знайдено прогоном Андрія 28.08: «як подати рапорт про щорічну відпустку» дало
#: цитату з пункту 1 (строки), а на «я питаю послідовність моїх дій, куди і як»
#: прийшла відмова. Ворота відкинули кандидатів ПО ОДНОМУ, і це правильно:
#: жоден фрагмент окремо на все питання не відповідає.
#:
#: Пошук теж не винен -- документ знайдений той, що треба. Винне те, скільком
#: одиниць ми віддаємо людині.
_PROCEDURE = re.compile(
    r"як\s+(?:подати|оформити|отримати|звернутися|діяти|це\s+зробити)"
    r"|послідовн\w*|порядок\s+ді\w*|як\w*\s+кроки|"
    r"куди\s+(?:і|та)\s+як|що\s+робити|з\s+чого\s+почати|"
    r"процедур\w*|як\s+це\s+(?:робиться|відбувається)",
    re.IGNORECASE)

#: Скільком пунктів карти показуємо і скільком символів на рядок. Ті самі
#: причини, що в `RAW_ROWS_SHOWN`: карта -- допомога, а не інвентаризація.
OUTLINE_UNITS_SHOWN = 12
OUTLINE_LABEL_CHARS = 90

#: Звідки беруться адреса й запис документа: рядок джерела, який пише сам
#: ланцюг («документ: запис №252 у базі, адреса 1. Строки подання рапорту»).
_REC_ID = re.compile(r"запис\s*№\s*(\d+)\s*у\s*базі")
#: Адреса обмежується `<` і переносом рядка, а НЕ кінцем рядка.
#:
#: Перша версія брала `(.+?)\s*$` -- і в живому прогоні захопила півблока
#: джерела разом: «1. Строки подання рапорту<br>збіг лем питання й цитати:
#: 0.75<br>карта документа…». Причина в тому, що в готовій відповіді джерело
#: склеєне в ОДИН рядок через `<br>`, а мій тест подавав його окремими
#: елементами переліку -- тобто перевіряв форму, якої не буває.
_REC_ADDR = re.compile(r"адреса\s+([^<\n]+)")


def is_procedure_question(question):
    """Чи питання про ПОСЛІДОВНІСТЬ дій. -> bool.

    Вузько навмисно: звичайне нормативне питання («яка тривалість щорічної
    відпустки») карти не отримує -- там одна цитата і є відповідь, а карта
    роздула б її без користі.
    """
    return bool(_PROCEDURE.search(question or ""))


def _doc_record_id(source_lines):
    """Номер ЗАПИСУ документа з рядків джерела. -> int або None.

    Саме запис, а не номер акта: у внутрішніх інструкцій частини
    (`doc_identifier IS NULL`) номера акта немає взагалі, а запис є завжди.
    """
    for line in source_lines or []:
        m = _REC_ID.search(str(line))
        if m:
            return int(m.group(1))
    return None


def _quoted_address(source_lines):
    """Адреса одиниці, з якої взято цитату. -> рядок або None."""
    for line in source_lines or []:
        if "адреса" in str(line):
            m = _REC_ADDR.search(str(line))
            if m:
                return m.group(1).strip()
    return None


def _fetch_sibling_units(doc_id, label):
    """Сусідні одиниці ТОГО САМОГО рівня в тому самому документі.

    Сусіди беруться за `parent_label` наведеної одиниці, а не «всі одиниці
    документа». Різниця видна на законі: у «Стаття 10-1 / 2» батько -- «Стаття
    10-1», тому сусіди це пункти ТІЄЇ САМОЇ статті. Без цього карта закону
    була б переліком сотень статей і не допомогла б нікому.

    Для внутрішньої інструкції батька немає (`NULL`), і тоді сусіди -- пункти
    верхнього рівня, тобто рівно та послідовність, яку людина й просила.
    """
    try:
        with _connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    WITH q AS (
                      SELECT parent_label FROM document_units
                       WHERE document_id = %s AND label = %s LIMIT 1)
                    SELECT u.label, u.text
                      FROM document_units u, q
                     WHERE u.document_id = %s
                       AND u.parent_label IS NOT DISTINCT FROM q.parent_label
                     ORDER BY u.ord
                    """, (doc_id, label, doc_id))
                return cur.fetchall()
    except Exception:
        # Карта -- додаткове знання. Немає її -- цитата лишається цитатою.
        return []


def _outline_lines(rows, quoted_label):
    """Рядки карти документа. -> перелік рядків (порожній = карти не буде).

    Порожньо повертається у трьох випадках, і кожен свідомий:
      * наведеної одиниці серед сусідів немає -- отже адреса не та, і карта
        малювалась би не до тієї цитати;
      * сусідів менше двох -- карта з одного пункту не карта;
      * рядків немає взагалі.
    """
    units = [r for r in (rows or [])
             if not (r.get("text") or "").lstrip().startswith("# ")]
    labels = [(r.get("label") or "").strip() for r in units]
    if len(units) < 2 or (quoted_label or "").strip() not in labels:
        return []
    out = [f"Цей документ описує порядок цілком, {_units_word(len(units))}:"]
    for lab in labels[:OUTLINE_UNITS_SHOWN]:
        short = lab if len(lab) <= OUTLINE_LABEL_CHARS \
            else lab[:OUTLINE_LABEL_CHARS].rstrip() + "…"
        mark = " ← щойно наведено" if lab == (quoted_label or "").strip() else ""
        out.append(f"- {_esc(short)}{mark}")
    if len(labels) > OUTLINE_UNITS_SHOWN:
        out.append(f"- і ще {len(labels) - OUTLINE_UNITS_SHOWN} пунктів")
    out.append("Питайте будь-який пункт — наведу дослівно.")
    return out


def _units_word(n):
    """«шістьма пунктами» -- узгодження числа з іменником в орудному."""
    tail, hundred = n % 10, n % 100
    if tail == 1 and hundred != 11:
        word = "пунктом"
    elif tail in (2, 3, 4) and hundred not in (12, 13, 14):
        word = "пунктами"
    else:
        word = "пунктами"
    return f"{n} {word}"


def is_topic_question(question):
    """Чи питання про ТЕМИ корпусу («а на які теми вони», «про що ці документи»).

    Знайдено прогоном Ані 28.08: після переліку нормативних текстів репліка
    «а на які теми вони» поїхала дорогою цитати й видала фрагмент «10. Наукові
    звіти за темами…» з акта про діловодство. Цитата дослівна, навіть із
    позначкою «слабко перетинається з питанням», -- але це відповідь не на те
    питання.

    Окремо від `is_corpus_question` навмисно: «що є в базі» відповідає шаблон
    складу бази (`documents_count`), а «на які теми» -- шаблон тем
    (`normative_list`). Перша версія повернула це одним гейтом, і продовження
    розмови отримало склад бази по домейнах замість тем -- краще за цитату, але
    так само не відповідь.

    Гейт вузький: слово про ТЕМИ або «про що», і при цьому в питанні не
    названо номера документа. «На яку тему наказ №118?» сюди не підпадає --
    там питання про конкретний документ. «Яка процедура оформлення відпустки?»
    теж ні: там немає ні слова «тема», ні «про що».
    """
    low = (question or "").lower()
    if re.search(r"(?:^|\W)(?:а\s+)?(?:на\s+)?як\w*\s+тем\w+", low) or \
            re.search(r"(?:^|\W)про\s+що\s+(?:вони|це|ці|тут)", low):
        return not extract_doc_number(question or "")
    return False


#: Питання про ДОКАЗ: «звідки ти це знаєш», «на підставі чого», «чим
#: підтверджено». Виділено в функцію, бо про це питають ДВА місця: правила
#: (коли в питанні є ПІБ -- тоді відповідає шаблон походження факту) і дорога
#: без імені (тоді відповідь -- як склалась ПОПЕРЕДНЯ відповідь, а це знає лише
#: слід ходу, тобто потрібна історія розмови).
_EVIDENCE = re.compile(
    r"звідки (?:ти )?(?:це )?(?:знаєш|відомо)|чому (?:ти )?(?:вважаєш|"
    r"думаєш)|на підстав|яким чином|чим підтвер|доказ", re.IGNORECASE)


def is_evidence_question(question):
    return bool(_EVIDENCE.search(question or ""))


def rules_route(question):
    """-> (template_id, params) або None, якщо правила не впізнали питання."""
    low = question.lower()
    # ГЕЙТ НЕДІЙСНОЇ ДАТИ -- найперший, до всього іншого.
    #
    # Раніше, ніж будь-який підрахунок, бо будь-який підрахунок із втраченою
    # датою підставить «сьогодні» й відповість упевнено не на те питання.
    # Рівно те, чого Денис похвалив у п. 23, -- тільки тепер це поведінка, а
    # не побічний ефект падіння.
    if impossible_dates(question):
        return "date_invalid", {}
    on_date, date_from, date_to = extract_dates(question)
    state = extract_state(question)
    doc_number = extract_doc_number(question)
    today = datetime.date.today()

    if doc_number and re.search(r"документ|наказ|квит|посвідч|№", low):
        return "doc_by_number", {"doc_number": doc_number}

    if re.search(r"черг|перевірк|рев'?ю", low) and re.search(r"скільки|що|яких", low):
        return "review_queue_count", {}

    if "непідтвердж" in low or "не підтвердж" in low:
        return "unconfirmed_count", {}

    if re.search(r"скільки\s+документів", low):
        return "documents_count", {}

    # ПИТАННЯ ПРО КОРПУС -- окрема дорога, не дорога нормативного ланцюга
    # (погоджено з Андрієм 28.08). п. 15 звіту Дениса: «Який період покривають
    # документи в базі?» ішло в «довідник» і отримувало «у базі поки немає
    # нормативних документів» -- при 44 таких документах.
    # ТЕМИ -- перед складом бази. Обидва питання «про корпус», але відповідають
    # на них різні шаблони, і склад бази по домейнах не є відповіддю на «на які
    # теми вони».
    if is_topic_question(question):
        return "normative_list", {}

    if is_corpus_question(question):
        return "documents_count", {}

    # Агрегати, яких у каталозі немає (середнє, мін/макс, суми) -- правила
    # не хапають: такі питання йдуть одразу в ярус 2 (див. answer у app.py).
    if _AGGREGATE.search(low):
        return None

    # ГЕЙТ ПІДРОЗДІЛІВ -- перед підрахунками, і саме тут.
    #
    # Дефект, знайдений верифікатором етапу 3 (25.08) приладом заміру
    # роутера: «Скільки людей у 2 роті зараз у відпустці?» правила вели у
    # `count_by_state_on_date`, тобто чат впевнено віддавав число ПО ВСІЙ
    # ЧАСТИНІ на питання про підрозділ. Векторний ярус маршрутизував це
    # питання правильно (`subdivision_blocked@0.943`), але до нього справа
    # не доходила: правила стоять першими і питання вже «впізнали».
    # Це псування правдивості, не швидкості: неправильне число з виглядом
    # правильного гірше за відмову (CLAUDE.md).
    #
    # Чому гейт стоїть тут, а не на самому початку функції: маркер
    # підрозділу сам по собі не робить питання питанням про підрозділ --
    # «яка процедура оформлення відпустки у підрозділі» це нормативний
    # пошук, і глушити його відмовою було б новою помилкою. Блокуємо лише
    # там, де підрозділ поєднаний із ПІДРАХУНКОМ або ПЕРЕЛІКОМ людей, бо
    # саме таку відповідь база дати не може: зв'язку особа-підрозділ у ній
    # немає (штатка -- зона Андрія, її ще нема).
    # ГЕЙТ ЗАПЕРЕЧЕННЯ -- перед усіма підрахунками стану, включно з
    # підрозділами: «хто НЕ у відпустці» це інше питання, а не те саме з
    # мінусом. Стоїть тут, бо нижче питання вже «впізнають» як звичайний
    # підрахунок і заперечення губиться (ворожий прохід 26.08).
    if state and _NEGATED_STATE.search(low) and _COUNT_OR_LIST.search(low):
        return "count_not_in_state", {"dims": STATE_DIMS[state],
                                      "state": state,
                                      "on_date": on_date or today}

    if _SUBDIVISION.search(low) and _COUNT_OR_LIST.search(low):
        # Штатка в базі з 25.08 (300 осіб, вимір `subdivision`), тому питання
        # про підрозділ тепер ВІДПОВІДНЕ. Доти тут стояла чесна відмова -- і
        # вона перестала бути чесною в ту саму хвилину, коли Андрій залив
        # штатку: система заперечувала б власні дані.
        #
        # Три випадки, і різниця між ними принципова:
        #   - підрозділ названий і він У ШТАТЦІ -> рахуємо по ньому;
        #   - підрозділ названий, але такого немає -> ЧЕСНА ВІДМОВА, не нуль
        #     (нуль читався б як «там нікого», а насправді немає підрозділу);
        #   - підрозділ не названий («по підрозділах», «по ротах») -> розклад.
        # Порівняння, суперлатив і «дві роти разом» -- це питання на РОЗКЛАД,
        # а не про одну роту. Ворожий прохід 26.08 дав три різні неправди:
        # «у якій роті найбільше» -> відмова «такого підрозділу немає»;
        # «у 1 більше, ніж у 2?» -> цифра лише по 1-й; «у 2 і 3 разом» ->
        # цифра лише по 3-й. Усі три виглядали як відповідь на питання.
        if re.search(r"найбільш|найменш|більше|менше|порівня|котр|яка з|"
                     r"у якій\s+(?:рот|взвод|підрозділ)|"
                     r"\d\s*(?:-?[а-яіїєґ]{1,2})?\s*(?:та|і|й|,)\s*\d\s*"
                     r"(?:-?[а-яіїєґ]{1,2})?\s*рот|разом", low):
            st = state or "absent"
            return "subdivision_breakdown", {"dims": STATE_DIMS[st],
                                             "state": st,
                                             "on_date": on_date or today}
        want = extract_subdivision(question)
        if want == "невідомий":
            return "subdivision_unknown", {}
        # Параметри збираємо ТУТ, а не лишаємо шаблону: гейт стоїть ДО блоку
        # `if state:`, тому dims/on_date ще не порахованi. Без них run_template
        # падає, питання їде на стару дорогу і та просить назвати дату -- саме
        # це й було при першій спробі (перевірено на сервері).
        st = state or "absent"
        common = {"dims": STATE_DIMS[st], "state": st,
                  "on_date": on_date or today}
        if want:
            # «Хто…» -- це питання на ПЕРЕЛІК, і підрозділ цього не змінює.
            # Доти гейт віддавав усе в підрахунок, і на «хто у 2 роті у
            # відпустці» людина отримувала цифру: формально правда, але не
            # відповідь -- прізвища потрібні, щоб подзвонити.
            if re.search(r"^хто\b|хто\s|список|покажи|перелік", low):
                return "list_by_state_in_subdivision", dict(common,
                                                            subdivision=want)
            return "count_by_state_in_subdivision", dict(common,
                                                         subdivision=want)
        return "subdivision_breakdown", common

    # ПИТАННЯ ПРО ДОКАЗ -- окремий шаблон, і він мусить вигравати в картки
    # особи. «Звідки ти знаєш», «чому ти вважаєш», «на підставі чого» -- це
    # питання не про людину, а про ПОХОДЖЕННЯ факту: спосіб отримання,
    # упевненість і всі документи-джерела. Доти такі питання йшли на стару
    # дорогу й отримували перелік документів -- відповідь на інше питання
    # (блок 4 перевірки, 26.08).
    if is_evidence_question(question):
        name = extract_name(question)
        if name:
            return "fact_provenance", {"name": name,
                                       "name_pattern": name_pattern(name)}

    # ГЕЙТ НОРМАТИВКИ -- теж ПЕРЕД підрахунками, і теж через живий дефект.
    #
    # Фінальний адверсарний прохід 25.08: «За скільки днів подавати рапорт на
    # відпустку?» давало «7 осіб у відпустці» -- з джерелом, тобто з виглядом
    # правдивої відповіді. Причина проста: у питанні є «скільк» і «відпустку»,
    # отже правила бачили підрахунок стану. Питання ж не про людей, а про
    # ПРОЦЕДУРУ: відповідь на нього -- у нормативному документі.
    #
    # Друга половина того самого дефекту: нормативні питання каталог не
    # впізнавав ЗОВСІМ і вони їхали на стару дорогу «довідник», яка на нашій
    # базі мертва (`search_reference` завжди повертає []) і казала «у базі
    # немає нормативних документів» -- при 41 такому документі. Тобто система
    # заперечувала те, що сама ж мала.
    #
    # Тому: маркер нормативки -> нормативні шаблони каталогу, і НЕ підрахунок.
    if _NORMATIVE.search(low):
        # ПЕРЕЛІК ДОКУМЕНТІВ -- НЕ ВІДПОВІДЬ НА ЗМІСТОВЕ ПИТАННЯ.
        #
        # Було: будь-яке «які…» з нормативним маркером віддавало
        # `normative_list`. Тому «Які завдання виконує Національна гвардія за
        # законом про неї?» отримало ПЕРЕЛІК 44 документів на 3977 символів за
        # 0.09 с (звернення c5ea96, Аня позначила «дивна відповідь»). Питання
        # про ЗМІСТ, відповідь -- інвентаризація.
        #
        # Тепер перелік вимагає ДВОХ ознак: слова про документи І маркера
        # нашого корпусу («є в базі», «у нас», «зберігаються») -- або прямого
        # наказу перелічити. Інакше це змістове питання, і на нього відповідає
        # цитата.
        #
        # Межа перевірена на формах, де вона й ламається: «Які накази видаються
        # в апараті головнокомандувача» -- це питання з РЕАЛЬНОГО акта, а не про
        # наш корпус, тому має йти в зміст, хоч і містить слово «накази».
        if re.search(r"перелічи|перелік|список", low):
            return "normative_list", {}
        if (re.search(r"\bякі\b|які\s+саме", low)
                and re.search(r"документ|\bакт[иі]?\b|наказ|норматив|закон",
                              low)
                and re.search(r"\bє\b|в\s+баз|у\s+баз|у\s+нас|зберіга|"
                              r"завантаж|корпус", low)):
            return "normative_list", {}
        return "normative_search", {"query": question}

    # ГЕЙТ НОРМИ-ПРАВА: питання про те, що людині ПОЛОЖЕНО, а не про те, хто
    # де є. Другий адверсарний прохід обійшов гейт нормативки синонімом:
    # «Скільки днів відпустки надається щорічно?» -> «7 осіб у відпустці» за
    # 0.02 с. У питанні немає слова «наказ» чи «процедура», зате є «скільк» і
    # «відпустки» -- і правила бачили підрахунок людей.
    #
    # Ознака тут інша, ніж у гейті нормативки: не назва документа, а ДІЄСЛОВО
    # права («надається», «положено», «передбачено») або слово «тривалість»,
    # «норма». Відповідь на таке -- у нормативному акті, не в підрахунку.
    # МЕЖА ГЕЙТА, без якої правка була б гіршою за дефект.
    #
    # «Скільки днів залишилось у відпустці Іваненка?» -- це ОБЛІК, не норма: у
    # питанні є конкретна особа, і відповідь у базі, а не в нормативному акті.
    # Гейт стоїть ПЕРЕД дорогою особи, тому без цієї умови він з'їв би всі
    # питання «скільки днів у відпустці <ПІБ>» і почав відповідати нормативкою
    # на питання про людину -- так само впевнено, лише в інший бік.
    if _ENTITLEMENT.search(low) and not extract_name(question):
        return "normative_search", {"query": question}

    # ГЕЙТ ЗАПЕРЕЧЕННЯ «без документів». Другий прохід: «Хто відсутній БЕЗ
    # документів?» давав перелік тих, у кого документи Є -- заперечення просто
    # ігнорувалось, і відповідь була рівно протилежною питанню.
    #
    # Правильна відповідь тут не «нуль» і не перелік, а пояснення будови: у
    # базі КОЖЕН факт народжується з документа, тому «відсутній без
    # документа» не існує за побудовою. Це не відмова через брак даних, це
    # відмова через устрій -- і сказати треба саме так.
    if re.search(r"\bбез\b\s+(?:документ|наказ|підстав|квитк|посвідч)", low):
        return "absent_without_docs_impossible", {}

    # ОСОБОВИЙ СКЛАД. До штатки на це питання відповіді не було, і ярус
    # вільного SQL віддавав дамп 52 прізвищ (другий адверсарний прохід). Зі
    # штаткою відповідь -- число, і саме число: на «скільком» перелік ПІБ не
    # потрібен нікому.
    if re.search(r"особов\w*\s+склад|за\s+штат|скільк\w*\s+(?:осіб|людей)\s+"
                 r"(?:у|в)\s+(?:частин|штат)|усіх\s+військовослужбовц", low):
        return "roster_total", {}

    # СУПУТНИКИ -- окремий шаблон, і він мусить вигравати в загального
    # переліку: «Хто виїхав з супутниками?» раніше давало звичайний список
    # відпусток, тобто точніше питання отримувало грубішу відповідь.
    if re.search(r"супутник|разом\s+з\s+(?:ким|членами)|з\s+родин", low):
        return "with_co_travelers", {}

    if state:
        dims = STATE_DIMS[state]
        if re.search(r"^хто\b|хто\s", low) or "список" in low or "покажи" in low:
            d_from = date_from or on_date or today
            d_to = date_to or on_date or today
            return "list_by_state", {"dims": dims, "state": state,
                                     "date_from": d_from, "date_to": d_to}
        # «скільк» коренем, не «скільки» цілим словом: замовниця питає
        # «СКІЛЬКОМ зараз у відпустці» (давальний), і на цьому питання
        # падало з каталогу на стару дорогу, яка рахує РЯДКИ, а не
        # людей, і не фільтрує стан. Знайдено адверсарним проходом
        # 25.08: демо-сценарій провалювався саме тут.
        if re.search(r"скільк|кількіст", low):
            if date_from and date_to:
                return "count_by_state_period", {
                    "dims": dims, "state": state,
                    "date_from": date_from, "date_to": date_to}
            return "count_by_state_on_date", {
                "dims": dims, "state": state, "on_date": on_date or today}

    name = extract_name(question)
    if name and re.search(r"що відомо|де зараз|стан|про ", low):
        return "person_status", {"name_pattern": name_pattern(name), "name": name}
    if name and len(question.split()) <= 4:
        return "person_status", {"name_pattern": name_pattern(name), "name": name}

    return None



def _plural(n, one, few, many):
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} {one}"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return f"{n} {few}"
    return f"{n} {many}"


def _people(n):
    return _plural(n, "особа", "особи", "осіб")


#: Параметри, які МОЖНА передати в SQL шаблону -- явний перелік, не «усе, що
#: прийшло». Причина: у params їдуть і службові значення (`state`), яких у
#: жодному запиті немає, і psycopg на зайвий іменований параметр не скаржиться,
#: а на ВІДСУТНІЙ -- падає. Тому додавати сюди новий параметр треба разом із
#: шаблоном, який його вживає.
#:
#: `query` -- тема нормативного пошуку: текст їде ЛИШЕ іменованим параметром у
#: websearch_to_tsquery, ніколи в рядок SQL.
#: `subdivision` -- додано 25.08 разом із шаблонами підрозділів. Забути його
#: тут означало «query parameter missing: subdivision», і саме це сталося:
#: шаблон падав, виняток глушився вище, і питання тихо їхало на стару дорогу
#: просити дату. Тобто пропущений рядок тут виглядав як «чат не розуміє
#: питання».
_SQL_PARAM_NAMES = ("dims", "on_date", "date_from", "date_to", "name_pattern",
                    "doc_number", "query", "subdivision")


def _sql_params(template_id, params):
    t = _CATALOG[template_id]
    return {k: v for k, v in params.items()
            if k in _SQL_PARAM_NAMES}, t


def _doc_ref(r):
    """«наказ №1030 (запис №127 у базі)» або лише запис, якщо номера немає.

    Доти в переліках стояло «(документ №127 у базі)», де 127 -- номер ЗАПИСУ.
    На «покажи документ №127» чат відповідав «такого немає» і був правий:
    номер наказу 1030. Відповідь сама пропонувала питання, на яке відмовляла.
    """
    num = (r.get("doc_number") or "").strip().lstrip("№").strip()
    rec = r.get("source_doc_id")
    if num:
        return f"документ №{_esc(num)} (запис №{rec} у базі)"
    return f"запис №{rec} у базі (номер документа не витягнуто)"


#: Скільком сирих рядків показуємо в загальному табличному рендері. Дванадцять
#: -- стільком людина прочитає очима; решта називається числом, а не
#: приховується. Розбір -- у комментарі біля самого рендера.
RAW_ROWS_SHOWN = 12

#: Скільком документів називаємо. Шість — стільки, скільки людина прочитає
#: очима; решта згортається в «і ще N документів». Перелік на пів екрана в
#: блоці «джерело» ніхто не читає, а отже він не допомагає перевірити цифру.
SOURCE_DOCS_SHOWN = 6

#: Провенанс: із яких ДОКУМЕНТІВ складено відповідь.
#:
#: Один запит на всю родину шаблонів про стан. Вікно дати підставляється
#: рядком `_window`, а не конкатенацією значень: значення завжди йдуть
#: параметрами, у рядок склеюється лише вибір між двома готовими умовами.
_SOURCE_DOCS_SQL = """
SELECT d.id                                        AS doc_id,
       coalesce(dt.name, '(тип не визначено)')      AS doc_type,
       coalesce(max(num.value), d.doc_identifier)   AS doc_number,
       coalesce(max(dat.value), d.issue_date::text) AS doc_date,
       count(DISTINCT f.id)                         AS facts
  FROM facts f
  JOIN dimensions dm ON dm.id = f.dimension_id
  JOIN documents d ON d.id = f.source_doc_id
  LEFT JOIN document_types dt ON dt.id = d.type_id
  LEFT JOIN facts num ON num.source_doc_id = d.id
       AND num.dimension_id = (SELECT id FROM dimensions
                                WHERE code = 'document_number')
  LEFT JOIN facts dat ON dat.source_doc_id = d.id
       AND dat.dimension_id = (SELECT id FROM dimensions
                                WHERE code = 'document_date')
 WHERE dm.code = ANY(%(dims)s)
   AND f.status = 'confirmed'
   {window}
 GROUP BY d.id, dt.name, d.doc_identifier, d.issue_date
 ORDER BY doc_date DESC NULLS LAST, d.id DESC
"""

#: Дві форми вікна — на дату й за період. Значення в обох ідуть параметрами.
_WINDOW_ON_DATE = """
   AND f.valid_from IS NOT NULL
   AND f.valid_from <= %(on_date)s
   AND (f.valid_to IS NULL OR f.valid_to >= %(on_date)s)
"""
_WINDOW_PERIOD = """
   AND f.valid_from IS NOT NULL
   AND f.valid_from <= %(date_to)s
   AND (f.valid_to IS NULL OR f.valid_to >= %(date_from)s)
"""


def _source_documents(sql_params):
    """-> (перелік документів, скільком їх усього) або ([], None).

    ([], None) означає «не змогли назвати документи» — і тоді блок «джерело»
    просто не має цих рядків. Провенанс не має права забрати з собою
    відповідь: людина спитала не про нього.
    """
    dims = (sql_params or {}).get("dims")
    if not dims:
        return [], None
    if sql_params.get("on_date"):
        window = _WINDOW_ON_DATE
    elif sql_params.get("date_from") and sql_params.get("date_to"):
        window = _WINDOW_PERIOD
    else:
        return [], None
    params = {k: v for k, v in sql_params.items()
              if k in ("dims", "on_date", "date_from", "date_to")}
    try:
        rows = _run_template_sql(_SOURCE_DOCS_SQL.format(window=window),
                                 params)
    except psycopg.Error:
        return [], None
    return rows[:SOURCE_DOCS_SHOWN], len(rows)


def _source_doc_lines(sql_params):
    """Рядки блоку «джерело» про документи. Порожній список, якщо не вийшло."""
    rows, total = _source_documents(sql_params)
    if not rows:
        return []
    out = [f"документів-джерел: {total}"]
    for r in rows:
        num = (str(r.get("doc_number") or "")).strip().lstrip("№").strip()
        date = (str(r.get("doc_date") or "")).strip()
        head = _esc(str(r.get("doc_type") or "документ"))
        if num:
            head += f" №{_esc(num)}"
        if date:
            head += f" від {_esc(date)}"
        # Скільком полів цього документа увійшло у відповідь: без цього
        # незрозуміло, чи документ дав одне значення, чи весь запис.
        out.append(f"  · {head} — полів у відповіді: {r.get('facts')} "
                   f"(запис №{r.get('doc_id')} у базі)")
    if total > len(rows):
        out.append(f"  · … і ще {total - len(rows)} документів")
    return out


def _fmt_period(r):
    a, b = r.get("valid_from"), r.get("valid_to")
    if a and b:
        return f"{a} — {b}"
    if a:
        return f"з {a}"
    return "період не вказано"


def _closest_names(query, limit=3):
    """Найближчі за написанням прізвища з реєстру -> перелік або [].

    Навіщо. 25.08 Аня питала «що відомо про Усика», чат чесно казав «у реєстрі
    немає особи за «Усик»» -- і це виглядало як поломка, хоч було правдою:
    прізвища в базі синтетичні (Данильчук, Килимник, Яремків…), Усика серед них
    нема. Відмова без підказки не бреше, але й не допомагає: людина не знає, чи
    вона помилилась у прізвищі, чи система зламалась.

    Тому підказка -- не вигадка, а ФАКТ із бази: ось хто справді є, і ось
    наскільки схоже. Порівняння за написанням (difflib), без моделі.
    """
    try:
        rows = _run_template_sql(
            "SELECT o.canonical_name AS name FROM objects o "
            "JOIN object_kinds k ON k.id = o.kind_id AND k.code = 'person'",
            {})
    except Exception:
        return []
    import difflib
    q = (query or "").strip().lower()
    if not q or not rows:
        return []
    scored = []
    for r in rows:
        name = (r["name"] or "").strip()
        if not name:
            continue
        # порівнюємо і з повним рядком, і з кожним словом: людина зазвичай
        # називає лише прізвище
        best = max([difflib.SequenceMatcher(None, q, name.lower()).ratio()]
                   + [difflib.SequenceMatcher(None, q, w.lower()).ratio()
                      for w in name.split()])
        scored.append((best, name))
    scored.sort(reverse=True)
    return [name for score, name in scored[:limit] if score >= 0.55]



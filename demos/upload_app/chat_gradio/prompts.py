# -*- coding: utf-8 -*-
"""Промпти моделі — з файлів у `demos/upload_app/prompts/`, не з коду.

Задача 4.5 плану. Причина -- 12-Factor Agents, фактор 2 «own your prompts»:
промпт це не константа реалізації, а параметр продукту. У пайплайні так уже
зроблено (`llm_context/`), і саме там це виправдало себе: формулювання правили,
не торкаючись коду.

Що тут НЕ робиться і навмисно:

- **перелік шаблонів у файл не вписаний.** Він підставляється з
  `query_catalog.yaml` у місце `{templates}`. Каталог лишається ЄДИНИМ
  джерелом шаблонів: інакше додавання шаблона правилось би у двох місцях, і
  копії розійшлися б мовчки -- та сама помилка, що з `FACT_TYPE_VALIDITY` у
  лоадері БД;
- **немає вбудованої копії промпта на випадок «файла немає».** Копія означала б
  друге джерело правди, тобто рівно те, проти чого цей модуль і зроблений.
  Немає файла -> `load()` кидає, а той, хто його кличе, чесно віддає питання
  далі (у нас -- `model_route` повертає None, і чат живе на правилах і
  векторах). Деградація, не вигадка.

Шапка файла в HTML-комментарі (`<!-- ... -->`) -- це пояснення для людини, а
не частина промпта; вона вирізається перед підстановкою.
"""
import os
import re

PROMPTS_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "prompts")

_COMMENT = re.compile(r"<!--.*?-->", re.S)

_cache = {}


def load(name):
    """-> текст промпта без шапки-комментаря. Кидає OSError, якщо файла немає.

    Кешується на процес: промпт читається один раз, а не на кожне питання.
    Правка файла вимагає перезапуску -- це свідомо: на демо ми не хочемо, щоб
    відповіді мінялись від того, що хтось зберіг файл посеред показу.
    """
    if name not in _cache:
        path = os.path.join(PROMPTS_DIR, name)
        with open(path, encoding="utf-8") as fh:
            _cache[name] = _COMMENT.sub("", fh.read()).strip()
    return _cache[name]


def render(name, **values):
    """Промпт із підставленими значеннями.

    `str.format` не годиться: у промптах є фігурні дужки як ТЕКСТ (приклад
    JSON `{"sql": "..."}`), і format на них падає. Тому підстановка
    буквальна -- тільки ті плейсхолдери, які ми самі назвали.
    """
    text = load(name)
    for key, value in values.items():
        text = text.replace("{" + key + "}", str(value))
    return text


def placeholders(name):
    """Які плейсхолдери є у файлі -- для тестів: щоб файл і код не розійшлись
    молча (у файлі з'явився `{unit}`, а код його не підставляє)."""
    return set(re.findall(r"\{([a-z_]+)\}", load(name)))
